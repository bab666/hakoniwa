/* 第3回（TD）：自動の態度口調（強気・厳格・意地っ張り・穏やか・健気・冷静・奔放・恥じらい・丁寧）の判定。元は作業者の scratchpad の TD/check.js（目視は入れていない）。r.g は話し手の性別（m／f） */
'use strict';
let TONE = '';
/* ---- ここから元の判定の規則（そのまま写した） ---- */
const broken = s => /[♡ぁぃぅぇぉ]|[…‥]っ|っ[…‥]|……っ|ッ|[イい]く[、…！]|[^、。！？]{0,3}っ[、！？]?$/.test(s);
const E = '(?=[。！？!?…‥、」　]|$)';
const R = (s, f) => new RegExp(s + E, f || '');
const cntOf = (s, re) => (s.match(re) || []).length;
const sents = s => s.split(/(?<=[。！？!?])/).map(x => x.replace(/^[　\s…‥]+/, '').trim()).filter(Boolean);
const POL = /(?:です|ます|ません|ました|でした|でしょう|ましょう|ください|ございます|ませんか|下さい)(?:か|ね|よ|よね|けど|から|が|し|の)?[？?！!。…‥、]*$/;
const PLAIN_END = /(?:(?<![でま]し|ござい|くださ|下さ)[るたいう]|だ|だよ|だね|だな|じゃん|よね|かな|の|んだ|ない|ないで|て|てよ|ってば|だろ|ぞ|ぜ|わ|わよ|のよ|かしら)[？?！!。…‥]*$/;
const FIRM = { stern: 1, cool: 1 };
const RULES = {
  common: [
    ['女性に男性的な語尾', { test: (s, g) => g === 'f' && TONE !== 'aniki' && (new RegExp('(?:だぜ|(?<![いな])ぜ|じゃねえ|[てらまわかができ]ねえ|やがれ|やがる|くれてやる)' + E).test(s) || /(?:^|[、。！？…‥　])(?:俺|おい)(?=[、！!…‥。は]|$)/.test(s) || (!FIRM[TONE] && new RegExp('(?<![どなうーよ])ぞ' + E).test(s))) }],
    ['男性に女性的な語尾', { test: (s, g) => g === 'm' && (new RegExp('(?:かしら|わよ|わね|なのね|(?<![でま]す)のよ|ですわ|だわ|(?<=[るたい])わ(?=[。！？]|$)|あたし|あら(?=[、！…]))' + E).test(s) || /(?<!ごめん|おかえり|おやすみ)なさい|(?:たい|[^っ]た|好きな)の(?=[。！…]|$)/.test(s.replace(/[^。！？…]*(?:何|なに|なん|どう|誰|どこ|いつ|なぜ)[^。！？…]*/g,''))) }],
    ['書き言葉調', /である|ではないか|であろう|のであ|ねばならな|否か|せねば|いかなる|しかるべき|ゆえに/],
  ],
  // 敬語と常体の混在
  mix: { test: s => { const ss = sents(s).filter(x => x.replace(/[…‥、。！？!?　]/g, '').length >= 5); if (ss.length < 1) return false;
    if (TONE === 'polite' || TONE === 'devoted') return ss.some(x => !POL.test(x) && PLAIN_END.test(x) && !/^(?:え|あ|うん|はい|ええ|いえ|そう|ほら|ねえ|ごめん)/.test(x) && !/[一-鿿ァ-ヶー]$/.test(x.replace(/[。！？!?…‥]+$/, '')));
    return ss.some(x => POL.test(x) && !/^(?:ありがとうございま|すみません|ごめんなさい|お願いします|いただきます|ごちそうさま|おはようございます)/.test(x)); } },
  proud: [['書き言葉の〜ている', R('(?:て|で)(?:いる|いた|いない|いなかった|いるのか|いるな|いるだろう)')], ['弱気', /ごめんなさい|すみません|かもしれません|どうしよう|ご、ごめん/]],
  aniki: [['書き言葉の〜ている', R('(?:て|で)(?:いる|いた|いない|いなかった|いるのか)')]],
  stern: [['砕けすぎ', new RegExp('マジ|やば|ヤバ|じゃん|っす|っしょ|めっちゃ|すげ|ウケ|ってば|だもん|ちゃう|ちゃっ|ちまっ|だよね|(?<![たま])よね|(?:て|で)る' + E + '|(?:て|で)た' + E + '|(?:て|で)ない' + E)]],
  cool: [['砕けすぎ', new RegExp('マジ|やば|ヤバ|じゃん|っす|っしょ|めっちゃ|すげ|ウケ|ってば|だもん|ちゃう|ちまっ|だよね|わーい|やったー')]],
  tsun: [['語尾の崩れ', /からよね|もんよね|だからよね/]],
  gentle: [['不自然な〜なあ', /(?:ない|(?<![かよ])った|てた|[^っ]た)なあ(?=[。！？…、]|$)/], ['きつすぎ', new RegExp('(?:しろ|やがれ|黙れ|ふざけるな|ねえ(?=[よか])|だろ(?![う？?])|(?<![どなうーよ])ぞ|ぜ)' + E)]],
  devoted: [['尊敬語・書き言葉', /お声|お口|お顔|おっしゃ|いらっしゃ|なさ[りっらる]|いたしま|(?<!も)のです|お尽くし/], ['きつすぎ', new RegExp('(?:しろ|やがれ|黙れ|ふざけるな|ねえ(?=[よか])|だろ(?![う？?])|(?<![どなうーよ])ぞ|ぜ|しなさい)' + E)]],
  free: [['硬すぎ', new RegExp('である|のだ' + E + '|ではない|いたし|ておる|(?<!ら)せよ|(?:て|で)いる' + E + '|(?:て|で)いない' + E + '|だろう' + E + '|かね' + E + '|(?:て|で)いた' + E)]],
  shy: [['強気な言い切り', new RegExp('(?:しろ|やがれ|黙れ|ふざけるな|ねえ(?=[よか])|だろ(?![う？?])|(?<![どなうーよ])ぞ|ぜ|しなさい|なさいよ|(?<![、…])だ(?=！))' + E + '|当然だ|当たり前だ|文句ある|笑ったら殴')], ['硬すぎ', new RegExp('である|のだ' + E + '|ではない' + E + '|(?:て|で)いる' + E + '|(?:て|で)いない' + E)]],
  polite: [['書き言葉の〜のです', /(?<!も)のです(?!か)/], ['砕けすぎ', /じゃん|っす|マジ|ヤバ|めっちゃ/]],
};
/* ---- ここまで元の判定の規則 ---- */

function judge(tone, r) {
  TONE = tone;
  const s = r.s, g = r.g, why = [];
  if (!broken(s)) {
    for (const [k, re] of RULES.common) if (re.test(s, g)) why.push(k);
    if (TONE !== 'shy' && RULES.mix.test(s)) why.push('敬語と常体の混在');
    for (const [k, re] of (RULES[TONE] || [])) if (re.test(s, g)) why.push(k);
  }
  return why;
}
module.exports = { team: 'TD', round: '第3回', tones: ['proud', 'stern', 'tsun', 'gentle', 'devoted', 'cool', 'free', 'shy', 'polite'], judge };
