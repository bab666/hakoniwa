/* ---- ここまで元の判定の規則 ---- */

function judge(tone, r) {
  TONE = tone;
  const s = r.s, why = [];
  if (!broken(s)) {
    for (const [k, re] of RULES[TONE]) if (re.test(s)) why.push(k);
    for (const [k, re] of (GEN[r.g] || [])) if (re.test(s)) why.push(k);
  }
  return why;
}
