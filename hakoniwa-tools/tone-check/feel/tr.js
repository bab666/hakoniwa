/* 2026-11-04（口調の点検のやり直し・担当 TR）：全口調に当てる判定。利用者の報告「新しい箱庭は口調の精度が低い（強気なのに女の口調が混ざる など）」で、
   tone-feel が合格（3% 以下）なのに遊ぶと崩れが見える型を足した。r は tone-feel の台詞の行（s 台詞・g 話し手の性別・fp 口調と性別から決まる一人称・
   rep 一回の遊びで同じ台詞を言った回数・sigRep 一回の遊びで同じ決め台詞（下の SIG）を含む台詞を言った回数）。
   設計と数字は docs/reports/2026-11-04/tone-redo.md、判定の一覧は docs/reports/2026-10-30/tone-feel.md の「第9回（TR）」。
   ・男性に女性語（広げた形）：わよ・わね・のよ・かしら・だわ・なのね・名詞／副詞＋よね（ゆっくりよね）・名詞＋よ（平気よ。神の命令の古風な「〜よ」は除く）・言い切りの〜なの／〜たの・〜てよね・〜ないでよね。
     お姉さん・お嬢様（口調そのものが女性語）は除く。男性のくだけた「〜たわ」（忘れてたわ）は数えない
   ・女性に男性の荒い語：だぜ・〜ぜ・じゃねえ・〜ねえ・やがれ・てめえ（男性的な語尾が口調の個性のもの：ヤンキー・兄貴分・熱血・チャラい・のじゃ・紳士・尊大・神の命令は除く）
   ・一人称の混在：一回の遊びの中で、その話し手の台詞でいちばん多い一人称（6 割以上を占めるときだけ）と違う一人称を言った台詞（私＝わたし、僕＝ぼく＝ボク は同じに数える。
     tone-feel のページの中で回ごとに数えて r.fpMix に入れる。エゴグラムで一人称が変わる口調があるので、回をまたいでは比べない）
   ・ヤンキー・強気（男性）・熱血（男性）のやわらかい「名詞＋だよ」（隙ありだよ・今夜だけだよ。問い・何〜だよ は除く）
   ・敬語でない口調の敬語の残り（文末の です・ます・ません・ました・でした・ましょう・ください と、尊敬語・謙譲語。決まった挨拶は除く）
   ・辞書の言い換えの壊れ（ありませんだった・ないですでした・ですだ・ませんっす・お取引とする・暮らする・〜ようわね・〜からわね・言っただろうね など）
   ・決め台詞の連発（SIG の語を含む台詞を一回の遊びで 3 回以上。お嬢様の「ごめんあそばせ」・意地っ張りの「べ、別に」・論客の「やれやれ」など）。
     参考（判定に入れない）：同じ台詞の連発（一回の遊びで 8 字以上の同じ台詞を 3 回以上。出来事の繰り返しで、口調の崩れではない）は prep が r.rep で数える */
'use strict';
const broken = s => /[♡ぁぃぅぇぉ]|[…‥]っ|っ[…‥]|……っ|ッ|[イい]く[、…！]|[^、。！？]{0,3}っ[、！？]?$/.test(s);
const E = '(?=[。！？!?…‥、」　〜]|$)';
const len = s => s.replace(/[…‥、。！？!?　\s〜ー「」]/g, '').length;
/* 決め台詞（口調の辞書が足す決まった言い回し。一回の遊びで 3 回以上は連発） */
const SIG = /ありがとう存じ|感謝いたしますわ|ごめんあそばせ|ごきげんよう|相分かった|かたじけない|案ずるな|礼を言うぞ|あざっす|あざっした|サンキュ|いやはや|やれやれ|フッ……。|ふむ、|フハハ|べ、別に|勘違いしないで/;
/* 女性語・お嬢様語そのものが口調の個性（男性でも直さない） */
const FEM_OK = { ane: 1, ojou: 1 };
/* 男性的な語尾が口調の個性（女性でも直さない。tone-registry.js の MASC_END ＋ 神の命令・論客） */
const MASC_OK = { yankee: 1, aniki: 1, hero: 1, chara: 1, noja: 1, gentleman: 1, sondai: 1, god: 1, ronkyaku: 1 };
/* 敬語のベース（P）から作る口調（敬語が口調）。ほかは敬語でない口調 */
const POLITE_TONE = { polite: 1, devoted: 1, kohai: 1, ojou: 1, genki: 1, keigo_sarc: 1, keigo_bossy: 1, keigo_flat: 1, chara_down: 1, mixed: 1, otaku: 1, keigo_twist: 1 };
/* 問いの文（その文の中の 何・どう・誰 など、文末の ？） */
const sentOf = (s, at) => { const a = s.slice(0, at), b = s.slice(at); const st = Math.max(a.lastIndexOf('。'), a.lastIndexOf('！'), a.lastIndexOf('？'), a.lastIndexOf('!'), a.lastIndexOf('?')) + 1; const m = b.match(/[。！？!?]/); return s.slice(st, at + (m ? m.index + 1 : b.length)); };
const isQ = x => /[？?]|何|なに|なん[でだの]|どう|誰|どこ|いつ|なぜ|どれ|どっち|どんな|どの/.test(x);
const anyAt = (s, re, ok) => { re.lastIndex = 0; let m; while ((m = re.exec(s))) { if (!ok || ok(m, sentOf(s, m.index))) return true; if (!re.global) break; } return false; };

const FEM_M = new RegExp('(?:わよ|わね|(?<![でま]す)のよ|かしら|だわ|なのね|なのよ|ないでよね|(?<=[てで])よね|(?:[一-鿿々ァ-ヶー]|ゆっくり|ばかり|つもり|はず|こと|もの|だけ|まで|から|一緒)よね)' + E + '|(?:[一-鿿々ァ-ヶー](?<![見寝来出居得似着煮経])|だけ|ばかり|こと|はず|つもり|一緒|平気|大丈夫|本当|ほんと)よ(?=[。！？!?…‥」　〜]|$)', 'g');
const NANO = /(?:なの|(?:たい|(?<!っ)た|しい|好きな|嫌いな)の)(?=[。！!…‥」]|$)/g;
const MASC_F = new RegExp('(?:だぜ|(?<![いなまかぜ])ぜ|じゃねえ|(?:[てまわがき]|(?<!か)ら)ねえ|やがれ|やがる|てめえ)' + E, 'g');
const NEE_OK = { usan: 1, honwaka: 1 };
const FP_RE = /(?<![渡])わたし|あたし|(?<![一-鿿])私|(?<![一-鿿])俺|オレ|(?<![一-鿿])僕|ぼく(?!じょう|し)|ボク|ウチ|(?<![一-鿿ぁ-ゖ])わし(?![づ])|わらわ|拙者|(?<![一-鿿])我(?![慢々一-鿿])/g;
const FP_NORM = { 'わたし': '私', '私': '私', 'あたし': 'あたし', '俺': '俺', 'オレ': 'オレ', '僕': '僕', 'ぼく': '僕', 'ボク': '僕', 'ウチ': 'ウチ', 'わし': 'わし', 'わらわ': 'わらわ', '拙者': '拙者', '我': '我' };
const fpsOf = s => { const out = []; let m; FP_RE.lastIndex = 0; const t = s.replace(/『[^』]*』/g, ''); while ((m = FP_RE.exec(t))) out.push(FP_NORM[m[0]] || m[0]); return out; };
const SOFT_DAYO = new RegExp('(?<!ん|の)だよ(?=[。！!…‥、」　]|$)', 'g');
const KEIGO_END = new RegExp('(?:です|ます|ません|ました|でした|でしょう(?![？?])|ましょう|ください|ませんか)(?:よ|ね|か|から|けど|って)?' + '(?=[。！？!?…‥、」　]|$)', 'g');
const KEIGO_FIXED = /ありがとうございま(?:す|した)|おはようございます|すみません|すいません|お願いします|お願いいたします|いただきます|ごちそうさま(?:でした)?|お疲れさま(?:です|でした)|失礼します|失礼しました|ごめんください|よろしくお願いします|おめでとうございます|行ってきます|行ってまいります|おやすみなさい|いってらっしゃい|ただいま戻りました/g;
const HONOR = /いらっしゃ|おっしゃ|いたしま|ござい(?!ません)|申し上げ|お越し|なさいま|させていただ/;
const BROKEN = /ありませんだ|ではありませんだ|ないです(?:でし|だっ)|ですでし|ますでし|です(?:だ|だっ)(?=[。！？!?…‥、」　]|$)|ますだ(?=[。！？!?…‥、」　]|$)|ませんっす|ですっす|でしたっす|ましたっす|お取引とする|(?<=[一-鿿][らまかやばがたこご])する(?=っす)|[ぁ-ゖ]すっすよ|[うよ]わ[よね]|からわ[よね]|(?:言った|わけがない|わけない|決まってる|決まっている)だろうね|だぞよ|だぜよ|いやはや、いや|ですわっす|ましょうっす|ますでしょう|てくださいっす(?=.*てくださいっす)/;

const RULES = [
  ['男性に女性語（広げた形）', (r, t) => r.g === 'm' && !FEM_OK[t] && (anyAt(r.s, FEM_M, (m, x) => !(/よ$/.test(m[0]) && (isQ(x) || t === 'god'))) || anyAt(r.s, NANO, (m, x) => !isQ(x)))],
  ['女性に男性の荒い語', (r, t) => r.g === 'f' && !MASC_OK[t] && anyAt(r.s, MASC_F, m => !(NEE_OK[t] && /ねえ$/.test(m[0])))],
  ['一人称の混在', (r) => r.fpMix > 0],
  ['やわらかい「名詞＋だよ」', (r, t) => (t === 'yankee' || ((t === 'proud' || t === 'hero') && r.g === 'm')) && anyAt(r.s, SOFT_DAYO, (m, x) => !isQ(x))],
  ['敬語でない口調の敬語の残り', (r, t) => { if (POLITE_TONE[t] || t === 'shy') return false; let s = r.s.replace(/『[^』]*』/g, '').replace(KEIGO_FIXED, ''); if (t === 'ane') s = s.replace(/ましょう(?:か|よ)?/g, ''); return anyAt(s, KEIGO_END) || HONOR.test(s); }],
  ['辞書の言い換えの壊れ', (r) => BROKEN.test(r.s)],
  ['決め台詞の連発', (r) => r.sigRep >= 3]
];
/* 判定の前の印付け（今は無し。一人称の混在は tone-feel のページの中で回ごとに数えて r.fpMix に入れる） */
function prep(rows) { return rows; }

function judge(tone, r) {
  const why = [];
  if (broken(r.s)) return why;
  for (const [k, f] of RULES) if (f(r, tone)) why.push(k);
  return why;
}
module.exports = { team: 'TR', round: '2026-11-04', tones: '*', SIG, FP_RE, FP_NORM, judge, prep, RULES };
