/* 第4回（TK）：関西弁のノリの判定。元は作業者の scratchpad の TK/check4.js（目視は入れていない）。ノリの印の割合（TK/nori.js）は参考の数として noriRate で出す */
'use strict';
let TONE = '';
/* ---- ここから元の判定の規則（そのまま写した） ---- */
const broken = s => /[♡ぁぃぅぇぉ]|[…‥]っ|っ[…‥]|……っ|ッ|[イい]く[、…！]|[^、。！？]{0,3}っ[、！？]?$/.test(s);
const EE = '(?=[。！？!?…‥、」　]|$)';
const cntOf = (s, re) => (s.match(re) || []).length;
const KMARK = new RegExp('や' + EE + '|やん|やで|やろ|やな|やわ|やし|やから|やけど|やった|やって|やない|へん|ねん|とる|とっ|どる|どっ|おる|おっ|おら|おろ|ええ|あかん|ほんま|めっちゃ|せや|ちゃう|ちゃい|ちょい|おもろ|なんや|なあ|[^っ]ん(?=[？?])|んか(?=[？?])|言う|ゆう|てみ' + EE + '|せえ|しよ|[行来見寝出]よ' + EE + '|[こそろ]か[？?]|たる|とき|しゃあない|かまへん|どない|ほな|さかい|もん|かいな|んといて|[^ら]せん|ねや|まう|まへん|てん|ん[やで]|ようさん|しんど|あらへん|いけず|堪忍|おおきに|しい[やな]|ぎょうさん|ほんで|てや' + EE + '|わ' + EE + '|[いるたうくすつむぐぶ]で' + EE + '|[のこそ]や' + EE + '|やと|んて' + EE + '|やかまし|早よ');
const STD = [
  new RegExp('(?:だよ|だね|だよね|だろう|だろ|じゃない|じゃないか|でしょ|でしょう|なんだ|んだ|のよ|わよ|かしら|てるよ|てるね)' + EE),
  new RegExp('(?<![くしじゃでは]|もった)(?:[らかさまなわがばけめせれきいえべみびち]|って|けれ|られ|させ)ない' + EE),
  new RegExp('(?:て|で)(?:る|た|いる|いた)(?<!ってた)' + EE),
  new RegExp('(?<![わっこ]|よろし|かわ)いい(?:よ|か|の|から|けど)?' + EE),
  /言っ(?:て|た)/, /(?:^|[、。　…])(?:だから|だったら|だけど|なので|じゃあ)|(?:[^ん]|^)だったら/,
  /なくて(?:いい|も)|なきゃ|なければ|じゃん|っす|っしょ|マジ|[てで]ちゃ(?:った|う)/,
  new RegExp('(?:[しべけめねれえみきじせてでげ]よ|(?<=[一-龯](?<![夫哀偉]))[こそとのもろごぼ])う' + EE)
];
const RULES = [
  ['標準語寄り', s => STD.some(re => re.test(s))],
  ['硬い', s => /確認|説明|可能|判断|対処|理解|である|のだ(?=[。！？…、]|$)|しかし|ただし|べき|想定|方法を|条件が|速さを|において|における|ではない|ておく|すまない|ください|です|ます/.test(s)],
  ['不自然な関西弁', s => /あかんなんや|へんなんや|やなんや|やねんや|へんや(?=[。！？!?…‥、」　]|$)|ないや(?=[。！？!?…‥、」　]|$)|(?:[るうくすつぬむぐぶ]|(?<!あん)[^っや]た|ない|ええ|へん)(?<!やつ)やで|(?:[るうくすつぬむぐぶ]|[^っやだ]た)やな(?=[。！？!?…‥、」　]|$)|ですわ|ますわ|やや(?=[。！？]|$)|へんへん|とるとる|やでよ|やよ(?=[。！？]|$)|ややん|やで(?:ね|よ)|ねんで(?:ね|よ)|おるる|せえへんよ(?=[。！？]|$)/.test(s) || cntOf(s, /なんや(?!ねん)|やねん|んねん/g) >= 2],
  ['薄い', s => s.replace(/[…‥、。！？!?　\s「」『』]/g, '').length >= 8 && !KMARK.test(s)]
];
/* ---- ここまで元の判定の規則 ---- */

function judge(tone, r) {
  const s = r.s;
  if (broken(s)) return [];
  const why = RULES.filter(([k, f]) => f(s)).map(x => x[0]);
  if (why.includes('不自然な関西弁') && !RULES[2][1](s.replace(/あんたやで|やつやで|いやや/g, ''))) why.splice(why.indexOf('不自然な関西弁'), 1);
  return why.map(k => 'ノリ：' + k);
}
/* TK/nori.js：例文の「ノリ」の印が入った台詞の割合（喘ぎ・崩れ・5 字未満は除く）。合否には使わない参考の数 */
const NORI = new RegExp('やん|やで|やろ|わ' + EE + '|わー|ええ|ほんま|なんや|なあ|もうちょい|ちょい|おる|おっ|おら|おろ|へん|ねん|[^っ]ん(?=[？?])|し' + EE + '|おもろ|やな' + EE + '|[^いな]や' + EE);
const brokenN = s => /[♡ぁぃぅぇぉ]|[…‥]っ|っ[…‥]|……っ|ッ/.test(s);
function noriRate(rows) {
  let tot = 0, hit = 0;
  rows.forEach(r => { if (brokenN(r.s) || r.s.replace(/[…‥、。！？!?　\s]/g, '').length < 5) return; tot += r.n; if (NORI.test(r.s)) hit += r.n; });
  return tot ? +(100 * hit / tot).toFixed(1) : null;
}
