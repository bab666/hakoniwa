/* 口調に合わない語尾・一人称のずれを探す
   node lint.js <collectの出力.json> [口調] [各項目の表示件数=8] */
'use strict';
const fs = require('fs');
const [file, only, show] = process.argv.slice(2);
const d = JSON.parse(fs.readFileSync(file));
const POL = /(です|ます|ました|ません|でした|でしょう|ください|ございます|ましょう)/;
const E = '(?=[。！？!?…、」♡〜ー]|$)', R = s => new RegExp(s + E);
const RULES = {
  polite: [['敬語でない語尾', /(だ|だよ|だね|だな|じゃん|ぜ|ぞ|だろ|よな|かよ|ねえ|しろ|てる|ってる|んだ|なよ|てよ|じゃねえ|だぞ|だわ|のよ)(?=[。！？!?…」]|$)/]],
  gentleman: [['くだけすぎ', R('(ぜ|じゃん|っす|だよな|よな|かよ|やがれ|じゃねえ|ねえよ|だわ|のよ|かしら|わね|わよ|ちゃう|でしょ)')], ['二人称', /(お前|おまえ|あんた|てめえ)/]],
  noja: [['敬語', POL], ['今どきの語尾', R('(じゃん|だよ|だね|わね|のよ|かしら|っす|だろ|でしょ|てる|ってる)')]],
  /* 関西弁：敬語そのものは許す（「〜まへん」「〜ですわ」など）。関西らしさのない、標準語だけの言い切りの敬語を拾う */
  kansai: [['標準語の敬語（言い切り）', { test: s => /(です|ます|ません|でした|ました)(?=[。！!…」]|$)/.test(s) && !/(まへん|ですわ|ますわ|ですやろ|ですやん|ですなあ|ますなあ|や[。！？、]|やん|へん|やろ|ねん|なあ|わ[。！]|で[。！])/.test(s) }], ['標準語の語尾', R('(じゃん|だよ|だね|だろ|でしょ|じゃない|わからない|知らない|できない)')]],
  devoted_p: [['敬語', POL]], aniki: [['敬語', POL]], free: [['敬語', POL]], proud: [['敬語', POL]], tsun: [['敬語', POL]], cool: [['敬語', POL]], stern: [['敬語', POL]],
  /* やわらかい口調（穏やか・献身・内気）：荒い語尾・二人称が残っていないか */
  gentle: [['荒い語尾', R('(よな|だぜ|ぜ|だろ|じゃねえ|ねえよ|かよ|しろよ|やがれ|だぞ|[たる]ぞ)')], ['二人称', /(お前|おまえ|てめえ|貴様)/]],
  gentle_n: [['荒い語尾', R('(よな|だぜ|ぜ|だろ|じゃねえ|ねえよ|かよ|しろよ|やがれ|だぞ|[たる]ぞ)')], ['二人称', /(お前|おまえ|てめえ|貴様)/]],
  devoted: [['荒い語尾', R('(よな|だぜ|ぜ|だろ|じゃねえ|ねえよ|かよ|しろよ|やがれ|だぞ|[たる]ぞ)')], ['二人称', /(お前|おまえ|てめえ|貴様)/]],
  shy: [['荒い語尾', R('(よな|だぜ|ぜ|だろ|じゃねえ|ねえよ|かよ|しろよ|やがれ|だぞ|[たる]ぞ)')], ['二人称', /(お前|おまえ|てめえ|貴様)/]],
  calm: [['分析めいた言葉', /(分析|計算|確率|観察|データ|合理|効率|想定|仮説|検証|パーセント|％)/]],
  /* はっきりした口調（強気・兄貴分・厳格・冷静・意地っ張り（中性的）・紳士・のじゃ）：弱々しい拒み・泣き声・女性的な語尾が残っていないか。
     「やめろ、離せ」が正しく、「いや……離して……」は誤り。「いや、違う」のような普段の「いや」は拾わない */
  mukuchi: [['長すぎる', { test: s => s.replace(/[…‥。、！？!?\s]/g, '').length > 14 }]]
};
const WEAK = [['弱い拒み（お願い形）', /(離して|やめて|見ないで|触らないで|許して|待って|抜いて|止めて|動かないで|来ないで|入れないで|やめてください|お願い|だめ|ダメ)(?=[…‥。！？!?、っー〜」♡]|$)/],
  ['泣き声の拒み', /(?:^|[、…‥「」\s])(?:いや|やだ|いやぁ|やぁ|いやっ|やっ)(?=[…‥っぁー！!、。]|$)/],
  ['女性的な語尾', /(?:わ|のよ|かしら|わね|わよ|なのね)(?=[…‥。！？!?、」♡]|$)/]];
['proud', 'aniki', 'stern', 'cool', 'calm', 'tsun_n', 'gentleman', 'noja'].forEach(t => { RULES[t] = (RULES[t] || []).concat(WEAK); });
const FP = /(俺様|オレ様|俺|僕|ぼく|オレ|ボク|わたくし|ワタクシ|あたくし|あたし|アタシ|わたし|ワタシ|私|拙者|わし|わらわ)(?=[はがもをにのとで、。！？…」っ])/g;
const hits = {};
for (const r of d.results) for (const x of r.recs) {
  if ((only && x.tone !== only) || x.nq) continue;
  (RULES[x.tone] || []).forEach(([nm, re]) => { if (re.test(x.out)) (hits[x.tone + '／' + nm] = hits[x.tone + '／' + nm] || new Set()).add(r.id + '：' + (x.raw || '') + '　→　' + x.out); });
  (x.out.match(FP) || []).forEach(f => { if (f !== x.fp && !x.out.includes(x.fp + f)) (hits[x.tone + '／一人称（' + x.fp + 'のはず）'] = hits[x.tone + '／一人称（' + x.fp + 'のはず）'] || new Set()).add(r.id + '：' + x.out); });
}
Object.keys(hits).sort().forEach(k => { const u = [...hits[k]]; console.log('### ' + k + '　' + u.length + '件'); u.slice(0, +show || 8).forEach(s => console.log('  ' + s.slice(0, 160))); });
