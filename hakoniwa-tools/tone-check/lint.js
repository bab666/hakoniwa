/* 口調に合わない語尾・一人称のずれを探す
   node lint.js <collectの出力.json> [口調] [各項目の表示件数=8] */
'use strict';
const fs = require('fs');
const [file, only, show] = process.argv.slice(2);
const d = JSON.parse(fs.readFileSync(file));
const POL = /(です|ます|ました|ません|でした|でしょう|ください|ございます|ましょう)/;
const E = '(?=[。！？!?…、」♡〜ー]|$)', R = s => new RegExp(s + E);
const RULES = {
  polite: [['敬語でない語尾', /(だ|だよ|だね|だな|じゃん|ぜ|ぞ|だろ|よな|かよ|ねえ|しろ|てる|ってる|んだ|なよ|てよ|じゃねえ|だぞ|だわ|のよ)(?=[。！？!?…」]|$)/]],
  gentleman: [['くだけすぎ', R('(ぜ|じゃん|っす|だよな|よな|かよ|やがれ|じゃねえ|ねえよ|だわ|のよ|かしら|わね|わよ|ちゃう|でしょ)')], ['二人称', /(お前|おまえ|あんた|てめえ)/]],
  noja: [['敬語', POL], ['今どきの語尾', R('(じゃん|だよ|だね|わね|のよ|かしら|っす|だろ|でしょ|てる|ってる)')]],
  /* 関西弁：敬語そのものは許す（「〜まへん」「〜ですわ」など）。関西らしさのない、標準語だけの言い切りの敬語を拾う */
  kansai: [['標準語の敬語（言い切り）', { test: s => /(です|ます|ません|でした|ました)(?=[。！!…」]|$)/.test(s) && !/(まへん|ですわ|ますわ|ですやろ|ですやん|ですなあ|ますなあ|や[。！？、]|やん|へん|やろ|ねん|なあ|わ[。！]|で[。！])/.test(s) }], ['標準語の語尾', R('(じゃん|だよ|だね|だろ|でしょ|じゃない|わからない|知らない|できない)')]],
  devoted_p: [['敬語', POL]], aniki: [['敬語', POL]], free: [['敬語', POL]], proud: [['敬語', POL]], tsun: [['敬語', POL]], cool: [['敬語', POL]], stern: [['敬語', POL]],
  /* やわらかい口調（穏やか・献身・内気）：荒い語尾・二人称が残っていないか */
  gentle: [['荒い語尾', R('(よな|だぜ|ぜ|だろ|じゃねえ|ねえよ|かよ|しろよ|やがれ|だぞ|[たる]ぞ)')], ['二人称', /(お前|おまえ|てめえ|貴様)/]],
  gentle_n: [['荒い語尾', R('(よな|だぜ|ぜ|だろ|じゃねえ|ねえよ|かよ|しろよ|やがれ|だぞ|[たる]ぞ)')], ['二人称', /(お前|おまえ|てめえ|貴様)/]],
  devoted: [['荒い語尾', R('(よな|だぜ|ぜ|だろ|じゃねえ|ねえよ|かよ|しろよ|やがれ|だぞ|[たる]ぞ)')], ['二人称', /(お前|おまえ|てめえ|貴様)/]],
  shy: [['荒い語尾', R('(よな|だぜ|ぜ|だろ|じゃねえ|ねえよ|かよ|しろよ|やがれ|だぞ|[たる]ぞ)')], ['二人称', /(お前|おまえ|てめえ|貴様)/]],
  calm: [['分析めいた言葉', /(分析|計算|確率|観察|データ|合理|効率|想定|仮説|検証|パーセント|％)/]],
  /* はっきりした口調（強気・兄貴分・厳格・冷静・意地っ張り（中性的）・紳士・のじゃ）：弱々しい拒み・泣き声・女性的な語尾が残っていないか。
     「やめろ、離せ」が正しく、「いや……離して……」は誤り。「いや、違う」のような普段の「いや」は拾わない */
  mukuchi: [['長すぎる', { test: s => s.replace(/[…‥。、！？!?\s]/g, '').length > 14 }]]
};
const WEAK = [['弱い拒み（お願い形）', /(離して|やめて|見ないで|触らないで|許して|待って|抜いて|止めて|動かないで|来ないで|入れないで|やめてください|お願い|だめ|ダメ)(?=[…‥。！？!?、っー〜」♡]|$)/],
  ['泣き声の拒み', /(?:^|[、…‥「」\s])(?:いや|やだ|いやぁ|やぁ|いやっ|やっ)(?=[…‥っぁー！!、。]|$)/],
  ['女性的な語尾', /(?:わ|のよ|かしら|わね|わよ|なのね)(?=[…‥。！？!?、」♡]|$)/]];
/* 尊大：紳士の言い換えを借りるので、紳士の決まり＋紳士のやわらかい語尾が残っていないか */
RULES.sondai = (RULES.gentleman || []).concat([['紳士のやわらかい語尾', R('(かい|だい|かな|じゃないか|けど|けどね|頼むよ|だよね)')], ['紳士の感嘆', /(?:^|[「])(?:おや|やれやれ)/]]);
['proud', 'aniki', 'stern', 'cool', 'calm', 'tsun_n', 'gentleman', 'noja', 'sondai'].forEach(t => { RULES[t] = (RULES[t] || []).concat(WEAK); });
/* 女性の話し手の台詞に、男性的な語尾・語が出た（口調を問わない。男性的な口調を選んだ女性＝ヤンキー・兄貴分・熱血・チャラい・のじゃ・紳士・尊大・神は除く。
   tone-registry.js の HK.toneAxis の ending:'m' と同じ並び）。「〜だろ？」「〜だろう？」の問いかけは拾わない */
const MASC_TONES = { yankee: 1, aniki: 1, hero: 1, chara: 1, noja: 1, gentleman: 1, sondai: 1, god: 1, otaku: 1, ronkyaku: 1, flat_plain: 1 };
/* 2026-10-26（順148）：命令・禁止・詠嘆の「な」・「〜てくれ」・「〜のか」・「〜かよ」なども数える（js/tone-plus.js の femKiri で直す形）。
   きりっとした口調（強気・厳格・冷静・冷静（落ち着き）・冷静（丸い）・意地っ張り）の「！」の命令・禁止（伏せろ！・離せ！）と、喘ぎの混じる拒み・関西弁の語尾は数えない */
const KIRI = { proud: 1, stern: 1, cool: 1, calm: 1, cool_soft: 1, tsun: 1, tsun_n: 1 };
const SE = '(?=[…‥。！？!?、」♡〜ー]|$)';
/* 文ごとに見る（k＝きりっとした口調なら「！」の文は数えない） */
const anySent = (s, re, k) => s.split(/(?<=[。！？!?…‥])/).some(x => !(k && /[！!]/.test(x)) && re.test(x.replace(/[。！？!?…‥\s　っッー〜♡、]+$/, '')));
const MOAN_L = /[ぁぃぅぇぉ♡]|[っッ](?=[…‥、。！!？?」〜ー]|$)/;
const HARSH_L = /殺|潰|殴|呪|ぶっ|ぶち|思い知|後悔|地獄|八つ裂|覚え|吊|晒|死ね|くたばれ/;
const IMP_RE = /(?:(?<![うぶっおも])しろ|(?<=[えけげせぜてでねべめれきぎじちにびみり]|(?:^|[^一-鿿々])[見寝着出居])ろ|来い|(?<=^|[^一-鿿々])(?:言|使|払|黙|座|帰|走|乗|守|聞|書|置|引|歩|働|動|叩|吐|跪|鳴|泣|脱|喘|急|離|返|出|話|渡|消|探|隠|押|許|待|持|飲|休|読|進|呼|選|叫)[えけげせてべめれ])(?:よ)?$/;
const PROH_RE = /(?<!(?:ている|でいる|ある|分かる|わかる|できる|見える|がする|思う|助かる|違う|足りる|要る|困る))(?:する|[るうくすつむぐぶぬ])な(?:よ)?$/;
const REFUSE_L = /(?:触る|さわる|見る|離す|動く|来る|くる|入れる|止める|抜く|待つ|やめる|近づく|寄る|近寄る|撮る)な/;
const FEM_M2 = [
  ['命令（〜ろ・〜え・しろ）', { test: (s, k) => !HARSH_L.test(s) && anySent(s, IMP_RE, k) }],
  ['禁止（〜な）', { test: (s, k) => !HARSH_L.test(s.replace(/(?:声|息|気配|足音)を殺/g, '')) && !(k && (MOAN_L.test(s) || REFUSE_L.test(s))) && anySent(s, PROH_RE, k) }],
  ['詠嘆の「だな」「よな」「んだな」', new RegExp('(?:だな|よな)' + SE)],
  ['〜てくれ', new RegExp('[てで]くれ(?:よ)?' + SE)],
  ['〜のか', { test: s => anySent(s, /(?<!も)のか$/) }],
  ['〜かよ', new RegExp('かよ' + SE)],
  ['〜じゃないか', new RegExp('(?<![うよ])じゃないか' + SE)],
  ['すげ・飯', /すげ|(?:^|[^ご御一-鿿々])飯(?![場盒粒])/]
];
const FEM_M = [['だぜ・ぜ', /(?<=[ぁ-ゖ一-鿿])(?<![いな])ぜ(?=[…‥。！？!?、」♡〜]|$)/], ['断定の「だろ」', { test: s => /だろ(?=[…‥。！!、」♡〜]|$)/.test(s) && !/(?:何|なに|なん|どう|なぜ|どこ|いつ|誰(?!か)|どれ|どんな)[^。！？!?]*だろ(?=[…‥。！!、」♡〜]|$)/.test(s) }], ['ぞ', /(?<=[ぁ-ゖ一-鿿])(?<![どなうー])ぞ(?=[…‥。！？!?、」♡〜っ]|$)/],
  ['じゃねえ', /じゃねえ/], ['〜ねえ（打ち消し）', /(?<=[らまわがばきみりえけせてめれげべ])(?<!ねえ)(?<!から|たら)ねえ(?!ね)(?=[よか…‥。！？!?、」♡〜]|$)/], ['やがる', /やが(?:る|れ|った|って)/],
  ['てやる', /(?:てやる|(?<!こちら|そちら|あちら|こっち|そっち|自分|一人|二人|三人|皆|みんな|全員|全部|ここ|そこ)でやる)(?=[よぞぜ…‥。！？!?、」♡〜]|$|から)/], ['おい', /(?:^|[「、…‥\s])おい(?=[、！!…‥。っ]|$)/]];
const FEM_FP = /(?:^|[^ぁ-ゖ])(俺|僕|オレ|ボク)(?=[はがもをにのとで、。！？…」っ]|$)/;
const femHits = {}, femN = {};
function femCheck(r, x) {
  if (x.g !== 'f' || MASC_TONES[x.tone] || x.nq) return;
  femN[x.tone] = (femN[x.tone] || 0) + 1;
  const ks = FEM_M.filter(([, re]) => re.test(x.out)).map(([nm]) => nm);
  if (x.tone !== 'kansai') FEM_M2.forEach(([nm, re]) => { if (re.test(x.out, !!KIRI[x.tone], x)) ks.push(nm); });
  const fm = x.out.match(FEM_FP);
  if (fm && !/^(?:俺|僕|オレ|ボク)$/.test(x.fp)) ks.push('一人称「' + fm[1] + '」');
  if (!ks.length) return;
  (femHits[x.tone] = femHits[x.tone] || []).push(r.id + '：' + ks.join('・') + '｜' + (x.raw || '') + '　→　' + x.out);
}
const FP = /(俺様|オレ様|俺|僕|ぼく|オレ|ボク|わたくし|ワタクシ|あたくし|あたし|アタシ|わたし|ワタシ|私|拙者|わし|わらわ)(?=[はがもをにのとで、。！？…」っ])/g;
const hits = {};
for (const r of d.results) for (const x of r.recs) {
  if ((only && x.tone !== only) || x.nq) continue;
  femCheck(r, x);
  (RULES[x.tone] || []).forEach(([nm, re]) => { if (re.test(x.out)) (hits[x.tone + '／' + nm] = hits[x.tone + '／' + nm] || new Set()).add(r.id + '：' + (x.raw || '') + '　→　' + x.out); });
  (x.out.match(FP) || []).forEach(f => { if (f !== x.fp && !x.out.includes(x.fp + f)) (hits[x.tone + '／一人称（' + x.fp + 'のはず）'] = hits[x.tone + '／一人称（' + x.fp + 'のはず）'] || new Set()).add(r.id + '：' + x.out); });
}
Object.keys(hits).sort().forEach(k => { const u = [...hits[k]]; console.log('### ' + k + '　' + u.length + '件'); u.slice(0, +show || 8).forEach(s => console.log('  ' + s.slice(0, 160))); });
/* 女性の話し手の男性的な語尾・一人称（口調別。件数／その口調の女性の台詞の数） */
{
  const ks = Object.keys(femHits).sort((a, b) => femHits[b].length - femHits[a].length), tot = ks.reduce((n, k) => n + femHits[k].length, 0);
  console.log('### 女性の話し手の男性的な語尾・一人称　' + tot + '件（' + ks.map(k => k + ' ' + femHits[k].length + '/' + femN[k]).join('、') + '）');
  ks.forEach(k => { if (only && k !== only) return; femHits[k].slice(0, +show || 8).forEach(s => console.log('  [' + k + '] ' + s.slice(0, 200))); });
}
