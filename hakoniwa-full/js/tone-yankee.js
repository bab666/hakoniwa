/* 箱庭シミュレーター: 口調「ヤンキー」
   文面の表はエゴグラムからいちばん合う口調のもの（敬語は外す）を使い、できあがった台詞をヤンキーの話し方に付け替える（名前・一人称・並びは tone-registry.js）。
   ・ヤンキー … 「〜じゃねえよ」「〜だろ」「知らねえよ」「文句あんのかよ」「ナメてんのか？　あァ？」「〜コラ」「てめえ」
   強気・意地っ張りなど荒い性格の人ほど威嚇が強く（「コラ」「あァ？」「てめえ」）、
   穏やか・健気・恥じらいなどの人は、砕けてはいても優しさは残す（「なんだよ……調子狂うな」「そういうとこ、可愛いじゃん」） */
(function () {
  'use strict';
  var HK = window.HK, V = HK && HK.Voice, END = HK && HK.TONE_END;
  if (!V || !HK.toneFinish || !END) return;
  var WH = END.wh;
  var ROUGH = { proud: 1, tsun: 1, stern: 1, cool: 1, free: 1 };

  var YOU = /(?:あなた|あんた|おまえ|貴様)(?!さん|方)|(?:きみ|(?<![大姫主父母諸細若暴ァ-ヶー一-鿿A-Za-z])君)(?=(?:は|が|も|の|を|に|と|で|って|、|。|！|？|…|」|$|さ|ね|よ|なら|だけ|たち|ら|だ|じゃ|か|な|から|へ|や|しか|まで|より|一人|自身))/g;
  var B = '(?=[よなねぞかってしけどのだこんもと。！？!?…‥、」っ]|$)';
  function re(s, f) { return new RegExp(s + B, f || 'g'); }
  function hash(s) { var h = 7; for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 100003; return h; }

  /* 形容詞・「ない」の崩し（知らない→知らねえ、すごい→すげえ） */
  var KUZU = [
    [re('(?<![少危汚情幼切、])ない'), 'ねえ'], [re('すごい'), 'すげえ'], [re('うるさい'), 'うるせえ'], [re('やばい'), 'やべえ'], [re('ヤバい'), 'ヤベえ'], [re('うまい'), 'うめえ'],
    [re('痛い'), 'いてえ'], [re('いたい'), 'いてえ'], [re('早い'), 'はええ'], [re('寒い'), 'さみい'], [re('暑い'), 'あちい'], [re('ダサい'), 'ダセえ'], [re('ずるい'), 'ずりい'],
    [re('(?<![気居心])悪い'), 'わりい'], [re('怖い'), 'こええ'], [re('こわい'), 'こええ'], [re('面倒くさい'), 'めんどくせえ'], [re('めんどくさい'), 'めんどくせえ'], [re('くさい'), 'くせえ'],
    [re('知らない'), '知らねえ'], [re('わからない'), 'わかんねえ'], [re('分からない'), '分かんねえ'], [re('つまらない'), 'つまんねえ'], [re('いらない'), 'いらねえ']
  ];
  /* はしゃいだ言い方を落ち着かせる（元気・やわらかい性格の台詞の表から来るもの）。喘ぎの台詞は触らない
     「やったー！」→「よっしゃ！」、「お宝だー！」→「お宝だ！」、「わあ、」→「へえ、」、「たのしー」→「楽しい」、「〜ね〜」→「〜ね」、「やろーよ」→「やろうぜ」 */
  function calm(q) {
    if (/[ぁぃぅぇぉ♡]|ん[〜ー～]|っ(?=[、…‥。」]|$)/.test(q)) return q;
    return q
      .replace(/^(?:やったー|やったぁ|わーい|やったやった)[！!]*\s*/, 'よっしゃ！　').replace(/^よっしゃ！　$/, 'よっしゃ！')
      .replace(/(^|[、。！!？?\s　])(?:うわー|うわあ)(?=[、！!])/g, '$1うおっ').replace(/(^|[、。！!？?\s　])(?:わあ|わー)(?=[、…])/g, '$1へえ').replace(/へえー/g, 'へえ')
      .replace(/たのしー/g, '楽しい').replace(/くやしー/g, 'くそっ、悔しい').replace(/悔しいー/g, '悔しい').replace(/きもちいー/g, '気持ちいい').replace(/かわいー/g, 'かわいい')
      .replace(/おいしかった/g, 'うまかった').replace(/おいしい/g, 'うまい').replace(/ありがとー/g, 'ありがとな').replace(/おつかれー/g, 'おつかれ').replace(/おなかすいた/g, '腹減った')
      .replace(/([ろこぼ]|(?<=[しけせべめれ])よ)ーよ?(?=[！!。]|$)/g, '$1うぜ').replace(/^はーい、/, 'おう、').replace(/ダメー+(?=[！!]|$)/g, 'ダメ')
      .replace(/(?<!あちゃ|ガオ|ぎゅ|ぐ|むぎゅ)([ぁ-ゃゅょ-ん一-鿿])ー+(?=[！!？?。]|$)/g, function (m, c) { return /[ゃゅょャュョッっ]/.test(c) ? m : c; }).replace(/[〜～]+(?=[。！!？?、]|$)/g, '')
      .replace(/(^|[、。！!\s　])ねえ(?=[聞見]|今)/g, '$1なあ');
  }
  function rough(q, who) {
    q = calm(q);
    var hard = who && ROUGH[who.persona];
    var h = hash(q + (who && who.name || ''));
    /* 女性的な語尾・丁寧なやわらかさを外す */
    q = q.replace(/([たいるうくすつむぬぐぶ])わよ(?=[。！？!?…‥、」]|$)/g, '$1よ').replace(/([たいるうくすつむぬぐぶ])わね(?=[。！？!?…‥、」]|$)/g, '$1な').replace(/([一-鿿ァ-ヶー])ね(?=[。！？!?…‥」]|$)/g, '$1だな')
      .replace(/(?<!ん)のよ(?=[。！？!?…‥、」]|$)/g, 'んだよ').replace(/かしら(?=[。！？!?…‥、」]|$)/g, 'かな').replace(/だわ(?=[。！？!?…‥、」]|$)/g, 'だ').replace(/あらあら|あらまあ|おやおや/g, 'おいおい').replace(/(^|[、…\s])あら(?=、)/g, '$1お').replace(/(^|[、…\s])あら(?=…)/g, '$1あ')
      .replace(/ふふ(?:っ)?/g, 'へっ').replace(/えへへ|うふふ/g, 'へへ').replace(/でしょう?(?=[。！？!?…‥、」]|$)/g, 'だろ').replace(/だろう(?=[。！？!?…‥、」]|$)/g, 'だろ');
    /* 硬い言い方を崩す（厳格・冷静の文面から）：している→してる、ではない→じゃない、のだ→んだ、である→だ */
    q = q.replace(/て(?:い)る(?![一-鿿])/g, 'てる').replace(/てい(?=な|た|て|ます|ません)/g, 'て').replace(/では(?=ない|ねえ|なかっ)/g, 'じゃ').replace(/(?<=[ぁ-ん])のだ(?=[。！？!?…‥、」]|$|ろ|よ|な)/g, 'んだ').replace(/である(?=[。！？!?…‥、」]|$)/g, 'だ').replace(/て(?:い)?ろ(?=[。！？!?…‥、」]|$)/g, 'てろ').replace(/てしま(?=う|っ|い)/g, 'ちま').replace(/でしま(?=う|っ|い)/g, 'じま').replace(/てあげて/g, 'てやって').replace(/てあげよう/g, 'てやろう').replace(/てあげ(?=る|た)/g, 'てや').replace(/([てで])お(?=く(?![ぁ-ん])|く[。！？!?…‥、」よぞね]|い[たて])/g, function (m, t) { return t === 'て' ? 'と' : 'ど'; }).replace(/(?<=[んい])でい(?=る|な|た)/g, 'で').replace(/でる(?=る)/g, 'でる').replace(/(^|[、。…\s])では、/g, '$1じゃあ、').replace(/(?<=[るたい])者(?=[はがをにも])/g, 'やつ').replace(/悪かったぞ/g, '悪かったな').replace(/ごめんなさい/g, hard ? 'わりい' : 'ごめん').replace(/お、お腹/g, 'お腹').replace(/お腹(?:が)?(?:空|す)い/g, '腹減っ').replace(/(^|[。…‥\s])礼を言う(?=[。！!…‥」]|$)/g, '$1ありがとな').replace(/のか(?=[。！!…‥」]|$)/g, 'のかよ');
    /* 女性的・上品な命令や頼み（ちょうだい・なさい）、硬い言い方を荒く */
    q = q.replace(/(?:、)?ちょうだい(?=[。！？!?…‥、」]|$)/g, function (m) { return (m.charAt(0) === '、' ? '、' : '') + 'くれ'; }).replace(/しなさい/g, 'しろ').replace(/てなさい/g, 'てろ').replace(/(来|き)なさい/g, '来い')
      .replace(/([えけげせぜてでねべめれ見寝着出])なさい/g, '$1ろ').replace(/([いきぎちにびみり])なさい/g, function (m, k) { return { 'い': 'え', 'き': 'け', 'ぎ': 'げ', 'ち': 'て', 'に': 'ね', 'び': 'べ', 'み': 'め', 'り': 'れ' }[k]; })
      .replace(/なので(?=[。！？!?…‥、」]|$)/g, 'だから').replace(/ので(?=[。！？!?…‥、」]|$)/g, 'から').replace(/なのだから/g, 'なんだから').replace(/やはり/g, 'やっぱ').replace(/このような/g, 'こんな').replace(/そのような/g, 'そんな').replace(/ほしくば/g, 'ほしけりゃ').replace(/(^|[。…‥\s])うむ(?=[。、…‥」]|$)/g, '$1おう')
      .replace(/(^|[。…‥\s])感謝する(?=[。！!…‥」]|$)/g, '$1ありがとな').replace(/([一-鿿][らかまわたなばが])ん(?=[。！？!?…‥、」]|$)/g, '$1ねえ').replace(/する(?=な[。！？!?…‥、」]|な$)/g, 'すん').replace(/([けめれせてねげべ])る(?=な(?:[。！？!?…‥、」]|$))/g, '$1ん').replace(/([らせれけ])ぬ(?=[。！？!?…‥、」]|$)/g, '$1ねえ').replace(/しない(?=！)/g, 'すんな');
    /* 呼びかけ・相づち */
    q = q.replace(/^(?:ねえ|ちょっと)、/, 'おい、').replace(/^え(?:っ)?[？?]/, 'あ？').replace(/^うそ(?:でしょ|だろ)?(?=[。！？!?…‥、」]|$)/, 'マジかよ').replace(/本当は/g, 'ほんとは').replace(/本当に/g, 'マジで').replace(/(?<![一-鿿])本当(?![一-鿿])/g, 'マジ').replace(/ほんとに/g, 'マジで')
      .replace(/(?:とても|すごく)(?=[ぁ-ん一-鿿])/g, 'すげえ').replace(/^ありがとう(?=[。！!…‥、」]|$)/, 'ありがとな').replace(/^ごめん(?:ね|なさい)?(?=[。！!…‥、」]|$)/, hard ? 'わりい' : 'ごめんな');
    /* 二人称：お前。荒い性格で、怒っている台詞なら「てめえ」 */
    var angry = /(?:ふざけ|許さ|ぶっ|殺|ナメ|なめ|黙れ|どけ|消えろ|うぜ|邪魔)/.test(q);
    q = q.replace(YOU, hard && angry ? 'てめえ' : 'お前').replace(/(?:お前|てめえ)(?:たち|達)/g, 'お前ら');
    if (hard && angry) q = q.replace(/お前(?=[はがもをにのと、！？!?」]|$)/, 'てめえ');
    /* 「〜てる」の崩し（何してるの→何してんの、何してるんだ→何してんだ） */
    q = q.replace(/て(?:い)?るん(?=だ|じゃ)/g, 'てん').replace(/て(?:い)?る(?=の)/g, 'てん').replace(/([あすわかなけ])るの(?=か|よ|[？?！!。…‥」]|$)/g, '$1んの');
    /* 「〜ないで」：荒い性格は「〜んじゃねえ」、ほかは「〜んなよ」（ふざけないで→ふざけんじゃねえ／ふざけんなよ） */
    var A2U = { 'ら': 'る', 'わ': 'う', 'か': 'く', 'さ': 'す', 'た': 'つ', 'ま': 'む', 'が': 'ぐ', 'ば': 'ぶ', 'な': 'ぬ' };
    q = q.replace(/(^|[、…‥\s])みないで/g, '$1見ないで');
    q = q.replace(/(^|[^一-鿿])(来|見|寝|出|着)ないで(?:、?(?:くれ|ください|くださ|ちょうだい)|よね?)?(?=[。！？!?…‥」っ]|$)/g, function (m, p, k) { return p + k + (hard ? 'んじゃねえ' : 'んなよ'); });
    q = q.replace(/([一-鿿ぁ-ん]*?)([ぁ-ん])ないで(?:、?(?:くれ|ください|くださ|ちょうだい)|よね?)?(?=[。！？!?…‥」っ]|$)/g, function (m, w, k) {
      if (k === 'し') return w + (hard ? 'すんじゃねえ' : 'すんなよ');
      if (A2U[k]) return w + (hard ? A2U[k] + 'んじゃねえ' : (k === 'ら' ? 'ん' : A2U[k]) + 'なよ');
      if (/[えけげせぜてでねべめれ見来寝出着]$/.test(w + k)) return w + k + (hard ? 'んじゃねえ' : 'んなよ');
      return m;
    });
    KUZU.forEach(function (r) { q = q.replace(r[0], r[1]); });
    /* 「〜じゃない」→「〜じゃねえ」（↑で済み）、「〜ないで」→「〜ねえで」 */
    q = q.replace(/ないで(?=くれ|[。！？!?…‥、」]|$)/g, 'ねえで');
    /* 文末 */
    var parts = q.split(/([。！？!?…‥」\n]+)/), lastI = -1;
    parts.forEach(function (seg, i) { if (!(i % 2) && /[^\s、]/.test(seg)) lastI = i; });
    q = parts.map(function (seg, i) {
      if (i % 2) return seg;
      var next = parts[i + 1] || '', ask = /[？?]/.test(next);
      if (/[っッぁぃぅぇぉー〜～♡]$/.test(seg) || /(?:です|ます|でした|ました|ません)(?:よ|ね|か)?$/.test(seg)) return seg;
      var s = seg;
      if (ask) {
        /* 何してるの？→何してんだよ？、怒ってるの？→怒ってんのかよ？ */
        if (WH.test(s) && /の$/.test(s)) return s.replace(/ん?の$/, hard ? 'んだよ' : 'んだ');
        if (/よね$/.test(s)) return s.replace(/よね$/, 'よな');
        if (/(?:の|ん)$/.test(s) && hard) return s.replace(/(?:の|ん)$/, 'のか');
        if (/じゃねえ$/.test(s)) return s + (hard ? 'か' : '');
        if (hard && /のか$/.test(s)) return s + 'よ';
        if (hard && /(?:誰|何|なに|どこ|いつ|どれ|どっち)$/.test(s)) return s + 'だよ';
        return s;
      }
      /* 女性的な「〜の」「名詞＋よ」を外す（淹れたの→淹れたんだ、大丈夫よ→大丈夫だよ） */
      s = s.replace(/([たい])の$/, '$1んだ').replace(/([一-鿿ァ-ヶー])よ$/, '$1だよ');
      /* 動詞のあとの「ね」は「ぞ」（「な」だと禁止に読める） */
      s = s.replace(/てるね$/, 'てんな').replace(/([おこそとのほもよろごぞどぼぽょ]う)ね$/, '$1な').replace(/([すつぬむるぐぶ]|[一-鿿]く|(?<![おこそとのほもよろごぞどぼぽょ])う)ね$/, '$1ぞ');
      s = s.replace(/(う|よう)じゃねえ$/, '$1じゃねえか').replace(/よね$/, 'よな').replace(/だね$/, 'だな').replace(/(?<![まじ])ね$/, 'な').replace(/かな$/, 'かな').replace(/じゃん$/, 'じゃん');
      return s;
    }).join('');
    /* 荒い性格の、怒った問い・命令に「あァ？」「コラ」を添える（毎回ではない） */
    if (hard && angry) {
      if (/[？?]$/.test(q) && !/あァ？$/.test(q) && h % 2 === 0) q += '　あァ？';
      else if (/[ろけえれせてよ]！$/.test(q) && h % 3 === 0) q = q.replace(/！$/, 'コラ！');
    }
    return q.replace(/ねえねえ/g, 'ねえ').replace(/よろしくぞ/g, 'よろしくな');
  }
  V.yankeeQuote = rough;
  HK.toneFinish('yankee', rough);
})();
