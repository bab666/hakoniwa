  function fateOf(t) {
    var g = t.tg;
    if (g.love) return 'love';
    if (g.drained && g.drained >= g.vit * 0.7) return 'spent';
    if (g.knows) return 'knows';
    if (g.drained) return 'drained';
    if (g.refused && !g.soft) return 'refused';
    if (g.n) return 'soft';
    return 'none';
  }
