/* 箱庭シミュレーター: 穏やかから派生する口調（お姉さん）
   文面と台詞の言い換えは「穏やか」をそのまま使い（書き下ろし・直しも穏やかのものを借りる。お姉さんの直しがあればそちらを優先）、
   できあがった台詞の語尾だけを、最後に付け替える（名前・一人称・並びは tone-registry.js）。
   ・お姉さん … 「〜よ」「〜わよ」「〜わね」「〜のよ」「〜かしら」「〜ってことね？」。余裕があって面倒見がいい
   「〜わ」は台詞の最後の文だけ（毎文につけるとくどい）。喘ぎ・叫びはそのまま。
   借りた文面に残った敬語の文は、敬語で話す相手でなければ崩してから語尾を付ける（V.unPoliteQuote。「規定の深さです」→「規定の深さよ」） */
(function () {
  'use strict';
  var HK = window.HK, V = HK && HK.Voice;
  if (!V || !HK.toneFinish) return;

  var YOU = /(?:お前|おまえ|てめえ|貴様)(?!さん|方)|(?:きみ|(?<![大姫主父母諸細若暴ァ-ヶー一-鿿A-Za-z])君)(?=(?:は|が|も|の|を|に|と|で|って|、|。|！|？|…|」|$|さ|ね|よ|なら|だけ|たち|ら|だ|じゃ|か|な|から|へ|や|しか|まで|より|一人|自身))/g;
  /* もう女性的な語尾・敬語・頼みごと・呼びかけで終わる文は触らない */
  var KEEP = /(?:わ|わよ|わね|のよ|のよね|かしら|よね|(?:です|ます|ました|ません|でした)(?:よ|ね|よね)?|でしょう|ましょう|ください|なさい|ちょうだい|[てで]よ|[てで]ね|[てで])$/;
  /* 「〜わ」を足してよい終わり方（動詞・形容詞・「ない」「た」の言い切り） */
  var PLAIN_END = /(?:[るすむぐぶ]|(?<![一二三四五六七八九十幾いさ])つ|(?<![しかた]|なんとな|ようや|おそら|しばら|まった|な|全|早|遅|強|弱|多|軽|深|長|短|近|遠|よ)く|(?<![おこそとのほもよろごぞどぼぽょ])う|思う|(?<!ちょうだ|なさ|くださ|^は|^お|^ね|^ほ|願|違|遣|合|伝|会|払|思|迷|戦|争|使|扱|祝|誘|呪|占|酔|匂|類|お互|そろ|揃)い|(?<!ませ)ぬ|た)$/;

  /* 「い」「つ」で終わっても名詞・形容動詞のもの（「〜わ」でなく「〜ね」） */
  var NA_END = /(?:みたい|いっぱい|きれい|綺麗|キレイ|嫌い|きらい|大嫌い|せい|ぐらい|くらい|おしまい|あいまい|曖昧|愉快|やつ|ずつ)$/;
  var VOL = { 'こ': 'き', 'ご': 'ぎ', 'そ': 'し', 'と': 'ち', 'の': 'に', 'ぼ': 'び', 'も': 'み', 'ろ': 'り', 'お': 'い' };
  var WH = /(?:何|なに|なん|誰|だれ|どこ|いつ|なぜ|どうして|どんな|どっち|どれ)/;
  /* 「行こう」→「行きましょう」、「始めよう」→「始めましょう」 */
  function volite(s) {
    if (/しよう(?:よ|か)?$/.test(s) && !/(?:どう|こう|そう)しよう/.test(s)) return s.replace(/しよう(よ|か)?$/, 'しましょう$1');
    var m = s.match(/^(.*[一-鿿])([こごそとのぼもろお])う(よ|か)?$/);
    if (m && !/向$/.test(m[1])) return m[1] + VOL[m[2]] + 'ましょう' + (m[3] || '');
    m = s.match(/^(.*(?:[一-鿿]|[えけげせぜてでねべめれみき]))よう(よ|か)?$/);
    if (m && !/(?:どう|そう|こう|ああ|同じ|同)$/.test(m[1]) && !/[一-鿿]$/.test(m[1]) || m && /(?:見|寝|着|出|来|居)$/.test(m[1])) return m[1] + 'ましょう' + (m[2] || '');
    return null;
  }
  function aneOne(s, ask, last, trail) {
    var m, v;
    if (/(?:くれ|もらえ)ないか$/.test(s)) return s + 'しら';
    if ((v = volite(s))) return v;
    if (ask) {
      if (/ないか$/.test(s)) return s.replace(/か$/, '');
      if (/(?:って|という)こと$/.test(s)) return s + 'ね';
      if (/かな$/.test(s)) return s.replace(/かな$/, 'かしら');
      if (/(?:だろう|だろ)$/.test(s)) return s.replace(/(?:だろう|だろ)$/, 'でしょ');
      if (/(?:の|ん)(?:か|だ)$/.test(s)) return s.replace(/(?:の|ん)(?:か|だ)$/, 'の');
      if (/(?<![まやだ])だ$/.test(s)) return s.replace(/だ$/, 'なの');
      return s;
    }
    if (KEEP.test(s) || /^(?:はいはい|はーい|はい)$/.test(s)) return s;
    /* 「どんな顔で死ぬのか」のような問いを含む「のか」は言い切りのまま（「のね」にしない） */
    if (/のか$/.test(s)) return WH.test(s) ? s : s.replace(/のか$/, 'のね');
    /* 「村人なんだ」「苦手なんだ」は説明の「〜なのよ」（「なん」を問いの「何」と取り違えない） */
    if (/(?:なん|何)なんだ$/.test(s)) return s.replace(/なんだ$/, 'なの');
    if (/.なんだ$/.test(s) && !WH.test(s.replace(/なんだ$/, ''))) return s.replace(/なんだ$/, 'なのよ');
    if (/だろうが$/.test(s)) return s.replace(/だろうが$/, 'じゃない');
    /* 「？」のない問いかけ（「何してる」「誰だ」）は「〜の」 */
    /* 「大会前なんで」の「なんで」は理由（問いの「何で」ではない） */
    if (WH.test(s.replace(/(?<=[一-鿿ァ-ヶーい])なんで/g, '')) && !/(?:何でも|なんでも|誰でも|どこでも|いつでも|何も|誰も|何か|誰か|どこか|いつか|何とか|なんとか|何度|なんか)/.test(s)) {
      if (/なんだ$/.test(s)) return s.replace(/なんだ$/, 'なの');
      if (/(?<![まやだ])だ$/.test(s)) return s.replace(/だ$/, 'なの');
      if (PLAIN_END.test(s) && !/[一-鿿]ん?だ$/.test(s)) return s + 'の';
    }
    /* 「飲んだ」「選んだよ」は過去形（「〜のよ」にしない） */
    if ((m = s.match(/^(.*[一-鿿々]ん)だ(よ|ね)?$/))) return last ? m[1] + 'だわ' + (m[2] || '') : s;
    if (/^そうなんだ$/.test(s)) return 'そうなの';
    /* 「〜んだ」「〜なんだよ」→「〜のよ」 */
    if ((m = s.match(/^(.*)(?:(?<!さ)ん|の)だ(よ|よね|ね)?$/)) && m[1]) return m[1] + (m[2] === 'ね' ? 'のね' : m[2] === 'よね' ? 'のよね' : 'のよ');
    if (/だよ[ねな]$/.test(s)) return s.replace(/だよ[ねな]$/, 'よね');
    if (/(?:だろう|だろ)$/.test(s)) return s.replace(/(?:だろう|だろ)$/, 'でしょう');
    if (/たくないかな$/.test(s)) return s.replace(/かな$/, 'の');
    if (/かな$/.test(s)) return s.replace(/かな$/, 'かしら');
    if (/^そうか$/.test(s)) return 'そうなの';
    if (/じゃん$/.test(s)) return s.replace(/じゃん$/, 'じゃない');
    if (/[ぞぜ]$/.test(s) && !/どうぞ$/.test(s)) return s.replace(/(だ)?[ぞぜ]$/, function (x, d) { return d ? 'よ' : 'わよ'; });
    /* 名詞・形容動詞＋だ／だよ／だね／だな → よ／ね（「本物だよ」→「本物よ」、「大げさだね」→「大げさね」）。「まだ」「やだ」はそのまま */
    if (/(?<![まやだ]|あい)だ(?:よ)?$/.test(s) && (s.length > 2 || /^(?:私|俺|僕|あたし|嘘|うそ)だ$/.test(s))) return s.replace(/だ(?:よ)?$/, 'よ');
    /* 「なんだな」「なんだね」は「なのね」（「なんね」にしない） */
    if (/なんだ[ねな]$/.test(s)) return s.replace(/なんだ[ねな]$/, 'なのね');
    if (/(?<![まやだ])だ[ねな]$/.test(s) && s.length > 2) return s.replace(/だ[ねな]$/, 'ね');
    if (/[おこそとのほもよろごぞどぼぽ]うな$/.test(s)) return s.replace(/な$/, 'ね');
    if (/[いた]な$/.test(s)) return s.replace(/な$/, last ? 'わね' : 'ね');
    if (!last) return s;
    /* 最後の文だけ：「いいよ」→「いいわよ」、「頑張ったね」→「頑張ったわね」、「知ってる」→「知ってるわ」 */
    if (NA_END.test(s) || NA_END.test(s.replace(/[よね]$/, ''))) return s.replace(/[よね]?$/, 'ね');
    /* 「うれしいよ」「楽になったよ」は「〜わ」、「帰るよ」「いいよ」は「〜わよ」 */
    if (/よ$/.test(s) && PLAIN_END.test(s.slice(0, -1))) return s.replace(/よ$/, /(?:た|しい|たい)よ$/.test(s) ? 'わ' : 'わよ');
    if (/ね$/.test(s) && PLAIN_END.test(s.slice(0, -1)) && !/(?:また|じゃ)ね$/.test(s)) return s.replace(/ね$/, 'わね');
    /* 「……」で消えていく文（喘ぎ・つぶやき）には「わ」を付けない */
    if (s.length >= 3 && PLAIN_END.test(s) && !/じゃない$/.test(s) && !trail) return s + 'わ';
    return s;
  }
  /* 穏やかの文面に残った敬語の文（「規定の深さです」「幽霊って信じます？」）は、敬語で話す相手（ctx.kg）でなければ崩してから語尾を付ける（「規定の深さよ」「幽霊って信じる？」） */
  function unPolite(q) {
    if (!V.unPoliteQuote) return q;
    var q0 = V.unPoliteQuote(q);
    if (q0 === q) return q;
    return q0.replace(/お疲れさま(?:だった|だ)(?=[。…‥」！!]|$)/g, 'お疲れさま').replace(/(?<=[、。…‥\s]|^)お疲れ(?=[。…‥」]|$)/g, 'お疲れさま').replace(/(?<![をにがで])お願い(?=[。！!…‥」]|$)/g, 'お願いね').replace(/^失礼する(?=[。…‥]|$)/, '失礼するわね').replace(/(だ|た)が(?=、)/g, '$1けど');
  }
  function ane(q, who, ctx) {
    if (!(ctx && ctx.kg)) q = unPolite(q);
    q = q.replace(YOU, 'あなた').replace(/おやおや/g, 'あらあら').replace(/(^|[、…\s])おや(?=[、…])/g, '$1あら')
      .replace(/(^|[、…\s])おい、/g, '$1ちょっと、').replace(/えへへ/g, 'ふふ').replace(/めっちゃ/g, 'すごく').replace(/デカ(?=い|く|かっ)/g, '大き').replace(/食っ(?=た|て)/g, '食べ').replace(/食う(?=[。！？…、」]|$)/g, '食べる')
      .replace(/もん(?=ね?[。！？…、」]|ね?$)/g, 'もの').replace(/(?:^|(?<=[、…\s]))しよ(?:う|っ)か(?=[。！？…、」]|$)/g, 'しましょうか').replace(/(?:^|(?<=[、…\s]))しよう?(?=[。！？…、」]|$)/g, 'しましょう').replace(/(?<=[えけげせぜてでねべめれ見来着寝出]|し)ろよ(?=[。！？…、」]|$)/g, 'てよ').replace(/だなあ(?=[。！？…、」]|$)/g, 'ねえ').replace(/てやる(?=よ|ぞ|わ|[。！？…、」]|$)/g, 'てあげる').replace(/(^|[、…\s])だが、/g, '$1でも、').replace(/すまない/g, 'ごめんなさい').replace(/あいつ(?=ら)/g, 'あの人').replace(/あいつ(?=[はがもをにのとって、。！？…」]|$)/g, 'あの人')
      .replace(/腹(?:が)?減っ/g, 'お腹が空い').replace(/食わせ/g, '食べさせ').replace(/食えない/g, '食べられない').replace(/([がはもをにで])さ(?=、)/g, '$1ね')
      /* 乱暴な「〜やがった」、一人称の「自分」（「次は自分が」「見つけたのは自分だ」）。問いかけ・「〜ってさ、自分が」のように相手を指す「自分」は残す */
      .replace(/(?<=[ぁ-ん一-鿿])やがっ(?=た|て)/g, '').replace(/(?<=[ぁ-ん一-鿿])やがる(?=[。！？…、」]|$)/g, 'る').replace(/(^|[、。…\s]|は)自分(?=[がはもだ])/g, function (m, pre, at, all) { var sen = all.slice(at).split(/[。！!]/)[0]; return /[？?]|でしょ|分かってない|わかってない|どう見え|は何/.test(sen) || /ってさ、$|って、$/.test(all.slice(0, at + pre.length)) ? m : pre + '私'; }).replace(/てやろう/g, 'てあげよう').replace(/てやった/g, 'てあげた');
    var parts = q.split(/([。！？!?…‥」\n]+)/), lastI = -1;
    parts.forEach(function (seg, i) { if (!(i % 2) && /[^\s、]/.test(seg)) lastI = i; });
    return parts.map(function (seg, i) {
      if (i % 2) return seg;
      var next = parts[i + 1] || '';
      /* 叫び（！）・喘ぎ（っ・ぁ・♡）の文はそのまま */
      if (/[っッぁぃぅぇぉー〜～♡]$/.test(seg)) return seg;
      /* 叫び（！）は「〜だ！」→「〜よ！」だけ */
      if (/[！!]/.test(next)) return /[一-鿿ァ-ヶー]だ$/.test(seg) && !/[一-鿿]んだ$/.test(seg) && !WH.test(seg) ? seg.replace(/だ$/, 'よ') : seg;
      var lead = (seg.match(/^[…‥、\s]+/) || [''])[0], tail = (seg.match(/[、]+$/) || [''])[0];
      var body = seg.slice(lead.length, seg.length - tail.length);
      return body ? lead + aneOne(body, /[？?]/.test(next), i === lastI, /^[…‥]/.test(next) && !/[^…‥」\s]/.test(parts.slice(i + 1).join(''))) + tail : seg;
    }).join('');
  }
  V.aneQuote = ane;
  /* 語尾の判定は、ほかの派生口調（tone-usan.js など）でも使う */
  HK.TONE_END = { plain: PLAIN_END, na: NA_END, wh: WH };
  HK.toneFinish('ane', ane);
})();
