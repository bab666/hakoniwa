  /* 箱庭の共通の段（前戯・繋がる・果てる）から、その状況に合わない場所の文を外す */
  var AVOID = { bath: /砂|焚き火|洞窟|寝床|波打ち際/, cave: /砂|波打ち際|波の|満月|浜|椰子|焚き火|潮/, storm: /満月|星|月明かり|波打ち際|焚き火/, watch: /洞窟|波打ち際|満月/, fire: /洞窟/, roof: /毛布/, car: /毛布の上/ };
