  /* 状況の型：受けの反応の書き分けと、「いつ死ぬか分からない」の一言・閾値の下げ */
  var GROUP = { horde: 'crisis', storm: 'crisis', grief: 'crisis', hunger: 'crisis', norescue: 'crisis', injury: 'care', bite: 'care', watch: 'hush', hide: 'hush', car: 'hush', blackout: 'hush', ruins: 'hush', cave: 'hush', bath: 'open', fire: 'open', roof: 'open' };
  var NOW_SIT = { horde: 1, storm: 1, grief: 1, hunger: 1, norescue: 1 };
