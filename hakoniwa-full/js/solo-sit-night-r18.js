  var SETUP = /跨[りっ]|横たえ|寝かせ|座らせ|連れ込|抱き上げ|導いて/;

  /* ======================= 関係 ======================= */
  function has(ctx, a, b, t) { return !!(HK.Ties && HK.Ties.has(ctx, a, b, t)); }
  function from(ctx, a, b, t) { return !!(HK.Ties && HK.Ties.from && HK.Ties.from(ctx, a, b, t)); }
  /* 執着度（関係「執着」なら 55 から。状態を作らずに読む） */
  function obLv(ctx, a, b) {
    var O = HK.Obsess;
    if (!O || !O.yanTie || (O.blocked && O.blocked(ctx, a, b))) return 0;
    var m = ctx.pair(a, b).ob;
    if (m && m[a.i]) return m[a.i].lv;
    return O.yanTie(ctx, a, b) ? 55 : 0;
  }
  function couple(ctx, a, b) { return !!ctx.pair(a, b).couple || has(ctx, a, b, 'lover') || has(ctx, a, b, 'mate') || has(ctx, a, b, 'fated'); }
  /* 二人の関係と、誘う側（a） */
  function relOf(ctx, a, b) {
    if (RK.lockedTo(b, a) && !RK.lockedTo(a, b)) { var s0 = a; a = b; b = s0; }
    if (RK.lockedTo(a, b)) return { k: 'lock', a: a, b: b };
    var la = obLv(ctx, a, b), lb = obLv(ctx, b, a);
    if (Math.max(la, lb) >= 35 && HK.Obsess.stance) {
      var o = la >= lb ? a : b, t = o === a ? b : a, st = HK.Obsess.stance(ctx, t, o);
      if (st === 'accept' || st === 'mutual') return { k: 'yan', a: o, b: t };
    }
    var cp = couple(ctx, a, b);
    if (!cp && has(ctx, a, b, 'ex')) return { k: 'ex', a: a, b: b };
    /* 両片想い（どちらからも片想い）は、片想いより先に見る */
    if (!cp && from(ctx, a, b, 'crush') && from(ctx, b, a, 'crush')) return { k: 'pining', a: a, b: b };
    if (!cp && (from(ctx, a, b, 'crush') || from(ctx, b, a, 'crush'))) return from(ctx, a, b, 'crush') ? { k: 'crush', a: a, b: b } : { k: 'crush', a: b, b: a };
    if (!cp && (has(ctx, a, b, 'rival') || has(ctx, a, b, 'bad') || has(ctx, a, b, 'enemy') || (ctx.R(a, b).ten > 38 && ctx.R(b, a).ten > 38))) return { k: 'rival', a: a, b: b };
    if (cp) return { k: 'lover', a: a, b: b };
    if (has(ctx, a, b, 'fwb') || ctx.pair(a, b).fwb) return { k: 'fwb', a: a, b: b };
    if (RK.exact(ctx, a, b, 'mentor')) return { k: 'mentor', a: a, b: b };
    if (has(ctx, a, b, 'childhood')) return { k: 'osana', a: a, b: b };
    return { k: 'new', a: a, b: b };
  }
  /* 吊り橋の条件：二人とも追い詰められていて（焦りの合計が50以上。無人島は焦りがたまりにくく、嵐・飢え・仲間の死そのものが怖さになるので15以上）、少しは意識していて、嫌い合っていない */
  function bridgeReady(ctx, a, b, sc) {
    var ra = ctx.R(a, b), rb = ctx.R(b, a);
    return a.stress + b.stress >= (sc === 'island' ? 15 : 50) && ra.att >= 5 && rb.att >= 5 && ra.aff > -10 && rb.aff > -10 && ra.ten < 45 && rb.ten < 45;
  }
  /* 惹かれの閾値（危機の夜は10下がる＝吊り橋） */
  var TH = { bridge: 0, lover: 28, fwb: 28, lock: 36, yan: 30, ex: 32, crush: 34, pining: 32, rival: 36, mentor: 40, osana: 38, new: 52 };
  function ready(ctx, r, crisis) {
    var a = r.a, b = r.b, ra = ctx.R(a, b), rb = ctx.R(b, a), th = TH[r.k] - (crisis ? 10 : 0);
    if (r.k === 'crush') return ra.att > th + 10 && rb.att > th;
    if (r.k === 'yan') return rb.att > th;
    if (!(ra.att > th && rb.att > th)) return false;
    if (r.k === 'mentor') return ra.trust > 25 || rb.trust > 25;
    if (r.k === 'new') return ra.aff > (crisis ? 10 : 22) && rb.aff > (crisis ? 10 : 22);
    return true;
  }

  /* ======================= 状況の判定（今の値から。乱数は使わない） ======================= */
  /* 直近（back 段階以内）に、二人とも加わった出来事があったか */
  function recent(ctx, a, b, re, back) {
    var lg = ctx.log || [], s = ctx.stepIndex;
    for (var i = lg.length - 1; i >= 0; i--) {
      var e = lg[i];
      if (e.step < s - back) break;
      if (re.test(e.cat) && e.actors && e.actors.indexOf(a.i) >= 0 && e.actors.indexOf(b.i) >= 0) return true;
    }
    return false;
  }
  /* 直近に亡くなった仲間（二人のどちらかが親しかった人） */
  function lost(ctx, a, b) {
    var s = ctx.stepIndex, best = null, bv = 20;
    ctx.chars.forEach(function (c) {
      if (c === a || c === b || c.alive || c.diedAt == null || s - c.diedAt > 2) return;
      var v = Math.max(ctx.R(a, c).aff, ctx.R(b, c).aff);
      if (v > bv) { bv = v; best = c; }
    });
    return best;
  }
  /* 怪我をしている方（体力が半分を切った・傷・毒） */
  function hurtOf(ctx, a, b, zb) {
    function hurt(c) { return c.hp < 50 || (zb ? c.z.wound >= 0 : c.flags.venom > 0); }
    var ha = hurt(a), hb = hurt(b);
    if (ha && hb) return a.hp <= b.hp ? a : b;
    return ha ? a : hb ? b : null;
  }
  function stormNow(ctx) {
    var lg = ctx.log || [], s = ctx.stepIndex;
    for (var i = lg.length - 1; i >= 0; i--) { var e = lg[i]; if (e.step < s) break; if (/嵐になった/.test(e.text || '')) return true; }
    return false;
  }
  function detectZ(ctx, a, b) {
    var Z = HK.ZB, pt = Z.part(ctx), out = [], d, h;
    if (pt < 1) return out;
    var stress = Math.max(a.stress, b.stress);
    if (recent(ctx, a, b, /^(combat|escape)$/, 1)) { out.push({ id: 'horde', w: 2 }); out.push({ id: 'bite', w: 1.4 }); }
    if (pt < 2) return out;
    if ((d = lost(ctx, a, b))) out.push({ id: 'grief', w: 2, d: d });
    if (a.z.hunger >= 2 || b.z.hunger >= 2) out.push({ id: 'hunger', w: 1.3 });
    if (ctx.env.end === 'none' && Z.day(ctx) >= 3 && stress > 25) out.push({ id: 'norescue', w: 1 });
    if ((h = hurtOf(ctx, a, b, true)) && h.hp > 18) out.push({ id: 'injury', w: 1.6, h: h });
    var A = ctx.zb && ctx.zb.A && ctx.zb.A[a.z.area];
    if (A && A.z >= 45) out.push({ id: 'hide', w: 0.7 });
    if (pt === 3) out.push({ id: 'watch', w: 0.7 });
    out.push({ id: 'blackout', w: 0.5 }, { id: 'ruins', w: 0.45 }, { id: 'car', w: 0.4 }, { id: 'roof', w: 0.4 });
    return out;
  }
  function detectI(ctx, a, b) {
    var out = [], d, h, s = ctx.stepIndex, storm = stormNow(ctx);
    if (storm) out.push({ id: 'storm', w: 2.2 });
    if ((d = lost(ctx, a, b))) out.push({ id: 'grief', w: 2, d: d });
    if (ctx.isl && ctx.isl.hungry >= 2) out.push({ id: 'hunger', w: 1.3 });
    if ((ctx.env.rescue === 'no' && s >= 3) || (ctx.flags.raftCrew && !a.out && !b.out) || ctx.flags.raftFail) out.push({ id: 'norescue', w: 1.1 });
    if ((h = hurtOf(ctx, a, b, false)) && h.hp > 18) out.push({ id: 'injury', w: 1.6, h: h });
    out.push({ id: 'watch', w: 0.6 }, { id: 'cave', w: 0.5 }, { id: 'fire', w: 0.6 });
    if (!storm) out.push({ id: 'bath', w: 0.6 });
    return out;
  }

  /* ======================= 文を組む ======================= */
  function pickF(ctx, arr, v, avoid) {
    var a2 = avoid ? arr.filter(function (s) { return !avoid.test(s); }) : arr;
    return fill(fp(ctx, a2.length ? a2 : arr), v);
  }
  /* sc：'zombie'|'island'、st：判定した状況、r：関係（誘う側 a）、lv：'fade'|'high' */
  function compose(ctx, sc, st, r, lv) {
    var a = r.a, b = r.b, o = RN.order(a, b), x = o[0], y = o[1], T = S[st.id] || (sc === 'zombie' ? SZ : SI)[st.id];
    var base = sc === 'zombie' ? RN.ZT.high : RN.I.high, g = RN.combo(x, y), av = AVOID[st.id];
    var h = st.h || null, c = h ? (h === a ? b : a) : null;
    var v = { a: a.name, b: b.name, x: x.name, y: y.name, d: st.d ? st.d.name : '', h: h ? h.name : '', c: c ? c.name : '',
      spot: sc === 'zombie' ? 'バリケードの奥の部屋' : '岩陰の寝床', noise: sc === 'zombie' ? '外の呻き声' : '波の音' };
    var t = pickF(ctx, T.intro, v) + pickF(ctx, REL.start[r.k], v);
    if (NOW_SIT[st.id] && ctx.rng() < (lv === 'high' ? 0.75 : 0.5)) {
      var nw = pickF(ctx, NOW[RN.psOf(a)] || NOW.gentle, v);
      t += nw;
    }
    if (lv !== 'high') return t + pickF(ctx, T.fade, v) + pickF(ctx, REL.after[r.k], v);
    var B = st.id === 'injury' ? T.body[h === x ? 'X' : 'Y'] : T.body, BG = B[g] || B.mf;
    function stage(s) {
      var arr = RN.noMut(base[g][s] || base.mf[s], x, y), ok = av ? arr.filter(function (z) { return !av.test(z); }) : arr;
      if (!ok.length && sc === 'island') { var zb = RN.ZT.high; ok = RN.noMut(zb[g][s] || zb.mf[s], x, y).filter(function (z) { return !ZONLY.test(z) && !(av && av.test(z)); }); }
      return fill(fp(ctx, ok.length ? ok : arr), v);
    }
    /* 本番：描写の長さ・作風・濃さ（solo-rel-r18.js の RN.body）。数行で短くなら、状況ごとの文で組む */
    t += RN.body(ctx, sc, x, y, function () {
      var u = '', mid = pickF(ctx, RN.noMut(BG.mid, x, y), v);
      u += BG.fore ? pickF(ctx, RN.noMut(BG.fore, x, y), v) : stage('fore');
      if (!SETUP.test(mid)) u += stage('insert');
      u += mid;
      u += pickF(ctx, REACT[GROUP[st.id]][RN.psOf(y)] || REACT[GROUP[st.id]].gentle, v);
      u += stage('end');
      if (RK.tone(x) === 'aniki' && ctx.rng() < 0.5) u += x.name + fill(fp(ctx, RN.ANIKI), v);
      return u;
    }, function () { return BG.fore ? pickF(ctx, RN.noMut(BG.fore, x, y), v) : stage('fore'); });
    t += pickF(ctx, T.after, v);
    if (ctx.rng() < 0.6) t += fill(fp(ctx, RN.AFTER_PS[RN.psOf(y)] || RN.AFTER_PS.gentle), v);
    return t + pickF(ctx, REL.after[r.k], v);
  }
  /* 夜のあとの関係の変化 */
  function settle(ctx, st, r) {
    var a = r.a, b = r.b, pf = ctx.pair(a, b), cr = !!CRISIS[st.id];
    pf.sitN = (pf.sitN || 0) + 1; pf.sitAt = ctx.stepIndex; pf.night = true;
    ctx.mod2(a, b, { att: 8, aff: 8, trust: 6 }, { att: 8, aff: 8, trust: 6 });
    var ds = cr ? 16 : 8; a.stress = Math.max(0, a.stress - ds); b.stress = Math.max(0, b.stress - ds);
    if (r.k === 'lock' || r.k === 'crush' || r.k === 'pining') pf.couple = true;
    else if (r.k === 'ex') pf.couple = pf.couple || ctx.rng() < 0.6;
    else if (r.k === 'new' || r.k === 'osana') pf.couple = pf.couple || ctx.rng() < 0.5;
    else if (r.k === 'bridge') { pf.bridge = true; pf.couple = pf.couple || ctx.rng() < 0.35; }
    else if (r.k === 'rival') { var ra = ctx.R(a, b), rb = ctx.R(b, a); ra.ten = Math.max(0, ra.ten - 12); rb.ten = Math.max(0, rb.ten - 12); }
    else if (r.k === 'yan' && HK.Obsess && HK.Obsess.add) HK.Obsess.add(ctx, a, b, 6);
  }
  function chooseSit(ctx, list) { return HK.weighted(ctx.rng, list, function (s) { return s.w; }); }

  /* 起きる条件（両方の箱庭で共通の部分） */
  function baseOk(ctx, a, b, gap) {
    if (!RN.okPair(ctx, a, b) || (HK.Pos && !HK.Pos.okSex(a, b))) return false;
    if (a.hp < 15 || b.hp < 15) return false;
    var pf = ctx.pair(a, b), s = ctx.stepIndex;
    if ((pf.sitN || 0) >= 2) return false;
    var last = [pf.sitAt, pf.irAt, pf.zlvAt, pf.zr18At].filter(function (x) { return x != null; });
    return !last.some(function (x) { return s - x < gap; });
  }
  /* 判定した状況のうち、今の関係で起きるもの（危機なら閾値を下げる）。結果は段階ごとにしまっておく */
  function cands(ctx, a, b, sc) {
    var pf = ctx.pair(a, b), key = ctx.stepIndex + ':' + sc;
    if (pf._sitK === key && pf._sitA === a.i) return pf._sitC;
    var r = relOf(ctx, a, b), all = (sc === 'zombie' ? detectZ : detectI)(ctx, a, b), list = all.filter(function (st) { return ready(ctx, r, !!CRISIS[st.id]); });
    /* 吊り橋：特別な関係のない二人（恋人・片想い・セフレ・執着などでない）でも、危機の夜に二人とも追い詰められていれば求め合う */
    if (!list.length && (r.k === 'new' || r.k === 'osana' || r.k === 'mentor' || r.k === 'rival') && bridgeReady(ctx, a, b, sc)) {
      var cr = all.filter(function (st) { return CRISIS[st.id]; });
      if (cr.length) { r = { k: 'bridge', a: r.a, b: r.b }; list = cr; }
    }
    pf._sitK = key; pf._sitA = a.i; pf._sitC = { r: r, list: list };
    return pf._sitC;
  }
  function why(ctx, st, r, extra, sc) {
    r = { a: r.a, b: r.b, k: r.k, sc: sc };
    var v = { a: r.a.name, b: r.b.name, d: st.d ? st.d.name : '', h: st.h ? st.h.name : '' };
    return fill((r.sc === 'island' && SIT_NAME_I[st.id]) || SIT_NAME[st.id], v) + '（' + fill(REL_NAME[r.k], v) + '／惹かれ ' + Math.round(ctx.R(r.a, r.b).att) + '・' + Math.round(ctx.R(r.b, r.a).att) + '／焦り ' + Math.round(r.a.stress) + '・' + Math.round(r.b.stress) + (extra || '') + '）';
  }

  /* ======================= 無人島 ======================= */
  var isl = HK.SCENARIOS.island;
  if (isl && RN.I) {
    isl.events.push({
      id: 'ir18_sit', cat: 'romance', scope: 'pair', r18: true,
      when: function (ctx, a, b) {
        if (!baseOk(ctx, a, b, 2)) return false;
        return cands(ctx, a, b, 'island').list.length > 0;
      },
      w: function (ctx, a, b) {
        var C = cands(ctx, a, b, 'island'), cr = C.list.some(function (s) { return CRISIS[s.id]; });
        return (cr ? 1.1 : 0.3) + (C.r.k === 'bridge' ? 0.8 : 0) + (ctx.R(a, b).att + ctx.R(b, a).att) / 160 + (a.stress + b.stress) / 200;
      },
      run: function (ctx, a, b) {
        var C = cands(ctx, a, b, 'island'), st = chooseSit(ctx, C.list), r = C.r, lv = RN.lv(ctx) === 'low' ? 'fade' : 'high';
        settle(ctx, st, r);
        return { text: compose(ctx, 'island', st, r, lv), why: (r.k === 'bridge' ? '吊り橋：' : '島の夜：') + why(ctx, st, r, '', 'island'), mag: CRISIS[st.id] ? 28 : 22 };
      }
    });
  }

  /* ======================= ゾンビの街 ======================= */
  var Z = HK.ZB;
  if (Z && Z.scen && Z.loveLv && RN.ZT) {
    Z.scen.events.push({
      id: 'zr18_sit', cat: 'romance', scope: 'pair', r18: true,
      when: function (ctx, a, b) {
        if (Z.loveLv(ctx) === 'off' || !baseOk(ctx, a, b, 4)) return false;
        if (a.z.bitten || b.z.bitten || a.z.alone || b.z.alone) return false;
        return cands(ctx, a, b, 'zombie').list.length > 0;
      },
      w: function (ctx, a, b) {
        var C = cands(ctx, a, b, 'zombie'), cr = C.list.some(function (s) { return CRISIS[s.id]; });
        return (cr ? 1.2 : 0.3) + (ctx.R(a, b).att + ctx.R(b, a).att) / 160 + (a.stress + b.stress) / 160;
      },
      run: function (ctx, a, b) {
        var C = cands(ctx, a, b, 'zombie'), st = chooseSit(ctx, C.list), r = C.r;
        settle(ctx, st, r);
        return { text: compose(ctx, 'zombie', st, r, Z.loveLv(ctx)), why: (r.k === 'bridge' ? '吊り橋：' : '') + why(ctx, st, r, '・' + Z.day(ctx) + '日目'), mag: CRISIS[st.id] ? 30 : 24 };
      }
    });
  }

  /* 点検用（数え直し・試し引き） */
  HK.SitNight = { REL: REL, NOW: NOW, REACT: REACT, S: S, SZ: SZ, SI: SI, GROUP: GROUP, relOf: relOf, detectZ: detectZ, detectI: detectI, compose: compose };
