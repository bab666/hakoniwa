/* 箱庭シミュレーター: 奔放から派生する口調（チャラい）
   文面と台詞の言い換えは「奔放」をそのまま使い、できあがった台詞を最後にチャラ系の言い回しに付け替える（名前・一人称・見本・派生元は tone-registry.js）。
   ・チャラい … 「よろしゃーっす」「サンキュ！　マジ助かったわ！」「嘘だろ、聞いてねーって」「〜っしょ」「〜じゃね？」「マジで」「ヤバい」「〜的な」
   威嚇はしない（それはヤンキー）。女性は「〜わ」「ねー」「だろ」など男っぽいところを外す（「マジ」「サンキュ」「〜っしょ」は残す）。
   毎回足すとくどいので、語尾の「わ」「って」や「マジ」の足し込みは台詞ごとのくじで間引く。喘ぎ・叫びだけの台詞・敬語・沈んだ台詞はそのまま */
(function () {
  'use strict';
  var HK = window.HK, V = HK && HK.Voice, END = HK && HK.TONE_END;
  if (!V || !HK.toneFinish) return;
  var PLAIN_END = END && END.plain;

  /* 文の切れ目（この直前で言葉が終わっている） */
  var EB = '(?=[。！？!?…‥、」\\s]|$)';
  function re(s, f) { return new RegExp(s, f || 'g'); }
  /* 喘ぎ（小さい「ぁ」「っ……」「♡」）。「助かった」の「っ」は数えない */
  var MOAN = /[ぁぃぅぇぉ♡]|[っッ](?=[…‥、。！？!?」]|$)|(?:^|[、…‥\s])(?:ん|あ|は|ひ|や)(?=[…‥、])|はぁ|あぁ|んっ/;
  /* 敬語の台詞（敬語で話す相手への台詞も含む） */
  var KEIGO = /(?:です|ます|ませ|ました|でした|ください|くださ|でしょう|ましょう|ござい|なさい|いただ|申し|存じ)/;
  /* 沈んだ・深刻な台詞（軽口を混ぜない） */
  var SAD = /(?:死|殺|泣|ごめんなさい|許さ|許せ|最低|つら|辛|悲し|寂し|さみし|苦し|怖|こわ|嫌|いや|やめて|助けて|お願い|痛|いた|帰らないで|行かないで|離さ|謝|悔し|恨|憎|呪|遺言|葬|墓|血|傷)/;
  /* 「ない」で終わっても否定の「ない」でない語（少ない・危ない・切ない…）。「幼い」「汚い」はもともと「ない」を含まない */
  var NAI_NG = /(?:少|危|切|せつ|情け|なさけ|あどけ|頼り|たより|つた|はか|ぎこち|おぼつか|心許|こころもと|申し訳|もったい|勿体|さり気|さりげ|味気|あっけ|しがな|やるせ|えげつ|いけ|すく|あぶ)$/;
  /* 「〜ない」→「〜ねー」にしてよい直前（動詞の未然形・「〜てない」・「わかん」「関係」など） */
  var NAI_OK = /(?:[かさたなまらわがばぱ]|[てで]|[えけげせぜねべめれ]|[見来寝出着居似煮得経]|^し|[^ぁ-ん]し|わかん|分かん|関係|仕方|しょうが|しょーが|意味|興味|覚え|間違い|問題|自信|余裕|時間|金|気が|気は|気も|用は|用も|暇|ひま)$/;
  var NAI_END = '(?=[。！？!?…‥、」\\s]|$|って|し(?:[。！？!?…‥、」\\s]|$)|から|よ|わ|じゃん|けど|もん|ん?だ)';

  /* ---------- 言い回し（台詞全体に） ---------- */
  function words(q, masc, lot2, lot3) {
    /* あいさつ・お礼・お詫び */
    q = q.replace(re('よろしく、?お願い(?:する|ね|な|だ)?' + EB), 'よろしゃーっす').replace(re('よろしく(?:ね|な|だ)?' + EB), 'よろしゃーっす')
      .replace(re('(?:ありがとう|ありがと)(?:ね|な|よ)?' + EB), lot3 ? 'あざっす' : 'サンキュ')
      .replace(re('(^|[、。！？!?…‥\\s])お疲れ(?:さま|様)?(?:ね|な|だ)?' + EB), '$1おつかれー').replace(re('(^|[、。！？!?…‥\\s])おはよう?' + EB), masc ? '$1おはよっす' : '$1おはよー')
      .replace(re('(^|[、。！？!?…‥\\s])久しぶり(?:だね|だな|ね|だ)?' + EB), '$1おひさ').replace(re('(^|[、。！？!?…‥\\s])了解(?:だ|です)?' + EB), '$1りょーかい');
    if (masc && lot2) q = q.replace(re('^ごめん(?:ね|な)?(?=[。！!…‥]|$)'), 'わりーわりー');
    /* 本当 → マジ */
    q = q.replace(/(?:本当|ほんと|ホント)に/g, 'マジで').replace(re('(^|[、。！？!?…‥\\s])(?:本当|ほんと|ホント)(?=[？?！!。…‥」]|$)'), '$1マジ')
      .replace(/(?<![一-鿿ぁ-ん])(?:ほんと|ホント)(?=[一-鿿])/g, 'マジ').replace(/^嘘でしょ(?:う)?(?=[。！？!?…‥、」]|$)/, masc ? '嘘だろ' : 'マジ').replace(/^うそ(?:でしょ)?(?=[。！？!?…‥」]|$)/, masc ? '嘘だろ' : 'マジ');
    /* とても・すごく → めっちゃ、すごい → ヤバい（言い切りは三回に一回「パネェ」） */
    q = q.replace(/(?:とても|すごく|スゴく|凄く)、?(?=[ぁ-ん一-鿿ァ-ヶ])/g, 'めっちゃ')
      .replace(re('(?:すごい|スゴい|凄い)(?:ね|な)' + EB), 'ヤバいじゃん').replace(re('(?:すごい|スゴい|凄い)(?=[。！!…‥」]|$)'), lot3 ? 'パネェ' : 'ヤバい').replace(/(?:すごい|スゴい|凄い)/g, 'ヤバい');
    if (lot3) q = q.replace(/ちょっと(?=[^？?]*$)/, 'ちょい');
    /* 誘い・同意を求める「〜じゃない？」「〜くない？」→「〜じゃね？」「〜くね？」 */
    q = q.replace(/(?:じゃない|じゃねえ|じゃねー)(?=[？?])/g, 'じゃね').replace(/(?<=[ぁ-ん一-鿿])くない(?=[？?])/g, 'くね');
    /* 「〜でしょ」→「〜っしょ」（「でしょう」は敬語なのでここまで来ない） */
    q = q.replace(/(?:でしょ|だろ)(?=[？?])/g, 'っしょ').replace(/でしょ(?:ね)?(?=[。！!…‥、」]|$|って)/g, 'っしょ');
    if (masc) {
      /* 動詞の誘い（してみない？）は「〜ね？」、否定の言い切りは「〜ねー」（少ない・危ない・切ないなどは除く） */
      q = q.replace(/([ぁ-ん一-鿿]+?)ない(?=[？?])/g, function (m, w) { return NAI_NG.test(w) || !NAI_OK.test(w) ? m : w + 'ね'; })
        .replace(re('([ぁ-んァ-ヶ一-鿿]+?)ない' + NAI_END), function (m, w) {
          if (NAI_NG.test(w) || !NAI_OK.test(w)) return m;
          if (/(?:仕方|しょうが|しょーが)$/.test(w)) return w.replace(/(?:仕方|しょうが|しょーが)$/, 'しゃー') + 'ねー';
          return w + 'ねー';
        }).replace(/(?<=ねー)(?:よ)(?=[。…‥」]|$)/g, 'って');
      /* 「だろ」の言い切りは「〜っしょ」（ひとりごとの「〜んだろ」「何〜だろ」は除く） */
      if (lot2) q = q.replace(/(?<![んの])だろ(?=[。…‥」]|$)/g, function (m, at, all) { return /(?:何|なに|なん|誰|どこ|いつ|どう)/.test(all.slice(0, at)) ? m : 'っしょ'; });
    }
    /* 「〜みたいな」で言いさす文は「〜的な」 */
    q = q.replace(/([一-鿿ァ-ヶー]{2,})みたいな(?=[。…‥」]|$)/g, '$1的な');
    return q;
  }

  /* 「マジ」を足す気持ちの言葉（文頭か「、」のあと。すでに「マジ」「めっちゃ」があれば足さない） */
  var MAJI = /(^|[、。！!…‥\s]|俺|あたし|は|も)(助かった|助かる|嬉しい|うれしい|嬉しかった|うれしかった|楽しい|楽しかった|最高|うまい|美味い|美味しい|おいしい|おいしかった|疲れた|無理|かわいい|可愛い|かっこいい|カッコいい|ウケる|びびった|ビビった|焦った|感謝してる)(?=[。！？!?…‥、」]|$|ね|な|わ|じゃん|って|かも|し)/;

  /* ---------- 語尾（台詞の最後の文だけ） ---------- */
  function ending(s, masc, ex, lot2, lot3) {
    if (/(?:って|わ|っしょ|じゃん|ぜ|ぞ|ね|な|よな|さ|っす|ー|的な|サンキュ|あざっす|マジ|かも|けど|から|し|の|ん|[てで])$/.test(s)) return s;
    /* 「〜ねー」→「〜ねーって」（聞いてねーって） */
    if (/ねー$/.test(s)) return lot2 ? s + 'って' : s;
    /* 「〜んだよ」「〜だよ」→「〜んだって」「〜だって」 */
    if (/(?:ん|な)だよ$/.test(s) && lot2) return s.replace(/よ$/, 'って');
    if (/(?<![まやだ])だよ$/.test(s) && lot3) return s.replace(/よ$/, 'って');
    if (!masc || ex) {
      /* 「助かった！」「最高！」のような叫びは「わ」を足さない（男性も「マジ〜わ！」の形だけ） */
      return s;
    }
    /* 男性：「〜たわ」「〜するわ」「〜ねーわ」（「助かったわ」「俺、行くわ」） */
    if (s.replace(/^[…‥、\s]+/, '').length <= 2) return s;
    if (/(?<![てで])た$/.test(s) && lot2) return s + 'わ';
    if (PLAIN_END && PLAIN_END.test(s) && !/(?:た|い)$/.test(s) && lot3) return s + 'わ';
    if (/(?:無理|最高|マジ[一-鿿ぁ-ん]+)$/.test(s) && lot2) return s + 'だわ';
    return s;
  }

  function chara(q, who) {
    if (!q || KEIGO.test(q) || MOAN.test(q)) return q;
    var masc = !(who && who.gender === 'f');
    var lot2 = HK.lineLot(q, 2), lot3 = HK.lineLot(q + '*', 3);
    var sad = SAD.test(q);
    /* 沈んだ台詞は「ない→ねー」なども付けず、そのまま */
    if (sad) return q;
    q = words(q, masc, lot2, lot3);
    var parts = q.split(/([。！？!?…‥」\n]+)/), lastI = -1, majiDone = /(?:マジ|めっちゃ|ヤバ|パネェ)/.test(q);
    parts.forEach(function (seg, i) { if (!(i % 2) && /[^\s、]/.test(seg)) lastI = i; });
    return parts.map(function (seg, i) {
      if (i % 2) return seg;
      var next = parts[i + 1] || '';
      if (!/[^\s、…‥]/.test(seg) || /[っッぁぃぅぇぉ〜～♡]$/.test(seg)) return seg;
      var ask = /[？?]/.test(next), ex = /[！!]/.test(next);
      /* 「……」で消えていく文はそのまま */
      var trail = /^[…‥]/.test(next) && !/[^…‥」\s]/.test(parts.slice(i + 1).join(''));
      var lead = (seg.match(/^[…‥、\s]+/) || [''])[0], tail = (seg.match(/[、]+$/) || [''])[0];
      var s = seg.slice(lead.length, seg.length - tail.length);
      if (!s || ask || trail) return seg;
      /* 気持ちの言葉に「マジ」を（台詞にひとつだけ。二回に一回） */
      if (!majiDone && lot2 && MAJI.test(s)) { s = s.replace(MAJI, '$1マジ$2'); majiDone = true; }
      /* 「マジ助かった！」は「マジ助かったわ！」 */
      if (masc && ex && /^(?:.*[、\s])?マジ(?:助かった|焦った|びびった|ビビった|疲れた)$/.test(s)) s += 'わ';
      else if (i === lastI) s = ending(s, masc, ex, lot2, lot3);
      return lead + s + tail;
    }).join('').replace(/マジマジ/g, 'マジ').replace(/ってって/g, 'って').replace(/わわ(?=[。！？!?…‥」]|$)/g, 'わ');
  }
  V.charaQuote = chara;
  HK.toneFinish('chara', chara);
})();
