/* 箱庭シミュレーター: 長い台詞の仕上げ（ギャル・チャラい・ミステリアス）
   各口調の語尾の付け替え（tone-gyaru.js など）は短い一言が中心で、人狼の推理・館の推理のような長い台詞には目印が付きにくい。
   そこで、長い台詞（28文字以上）だけ、各口調の仕上げのあとに
   ・言い出し（「さっきから気になってたんだけど、」「結論から言うと、」など）を一つ
   ・最後の文と、途中の文一つ（台詞ごとのくじ）の語尾
   を口調の言い方に寄せる。すでに口調の目印がある文・問い・喘ぎ・敬語・「……」で沈んだ文・重い台詞は触らない */
(function () {
  'use strict';
  var HK = window.HK;
  if (!HK || !HK.TONE_FINISH) return;

  var MOAN = /[ぁぃぅぇぉ♡]|[っッ](?=[…‥、。！!？?\s」〜～ー]|$)/;
  var KEIGO = /(?:です|ます|ません|でした|ください|ござい|でしょう|いたし|申し|いただ)/;
  var GRAVE = /(?:死|殺|亡|葬|遺体|血|怖|痛|助けて|許さ|許して|ごめんなさい|泣|涙|苦し|さよう?なら|後悔|悲し|つら|辛い|謝)/;
  var FP = '(私|あたし|ウチ|俺|僕|自分|わたし|オレ|ボク)';

  /* 言い出し（台詞の頭に一つだけ） */
  var OPEN = {
    gyaru: [
      [/^さっきから気になってたんだけど、/, 'てかさ、さっきから気になってたんだけど、'], [/^言いにくいけど、言うね。/, 'ぶっちゃけ言うね。'],
      [/^結論から言うと、/, 'ぶっちゃけ、'], [/^ひとつ引っかかってる。/, '一個引っかかってんだけど。'], [/^今のうちに言っておく。/, '今のうちに言っとくね。'],
      [new RegExp('^' + FP + 'の考えを言う。'), '$1的にはさ、'], [/^整理させて。/, 'ちょ、整理させて。'], [/^確認なんだけど、/, '一応確認なんだけど、'],
      [/^みんな、聞いて。/, 'みんな、ちょっと聞いて〜。'], [/^ちょっといい？/, 'ちょ、いい？']
    ],
    chara: [
      [/^さっきから気になってたんだけど、/, 'いやさ、さっきから気になってたんだけど、'], [/^言いにくいけど、言うね。/, 'ぶっちゃけ言うと、'],
      [/^結論から言うと、/, '結論から言うとさ、'], [/^ひとつ引っかかってる。/, '一個引っかかってんだよね。'], [/^今のうちに言っておく。/, '今のうちに言っとくけど、'],
      [new RegExp('^' + FP + 'の考えを言う。'), '$1的にはさ、'], [/^整理させて。/, 'ちょい整理させて。'], [/^確認なんだけど、/, '確認なんだけどさ、'],
      [/^みんな、聞いて。/, 'みんな、ちょい聞いて。'], [/^ちょっといい？/, 'ちょい、いい？']
    ],
    mystic: [
      [/^さっきから気になってたんだけど、/, 'ふふ、さっきから気になっていたんだけど、'], [/^言いにくいけど、言うね。/, '言いにくいけれど、言わせてもらおうか。'],
      [/^結論から言うと、/, '結論から言おうか。'], [/^ひとつ引っかかってる。/, 'ひとつ、引っかかっていることがあるのさ。'], [/^今のうちに言っておく。/, '今のうちに言っておこうか。'],
      [new RegExp('^' + FP + 'の考えを言う。'), '$1の考えを話そうか。'], [/^整理させて。/, '少し整理させてもらおうか。'], [/^確認なんだけど、/, '確認させてほしいんだけど、'],
      [/^みんな、聞いて。/, 'みんな、聞いてくれるかい。']
    ]
  };
  /* 文末（男女で分けるところは f を見る） */
  function ends(tone, f) {
    if (tone === 'gyaru') return [
      [/気がする$/, '気がすんだよね'], [/感じがする$/, '感じ'], [/と思う$/, 'と思うんだよね'], [/すぎる$/, 'すぎ'],
      [/を推す$/, '推しでいくね'], [/推す$/, '推すね'], [/(?:入れて)?おきたい$/, function (m) { return m.replace(/ておきたい$/, 'ときたい').replace(/おきたい$/, 'ときたい') + 'かも'; }],
      [/聞きたい$/, '聞きたいんだけど'], [/詰めたい$/, '詰めたいんだよね'], [/てほしい$/, 'てほしいんだけど'], [/聞く$/, '聞くけど'],
      [/今は([^、]{1,12})$/, '今は$1って感じ'], [/ないなら、([^、]{1,12})で$/, 'ないなら、$1でいいじゃん'],
      [/になる$/, 'になるっしょ'], [/一番黒い$/, '一番クロ'],
      /* 人のようすは「〜てるじゃん」「〜てたじゃん」、自分のことは「〜てるから」「〜てたんだよね」 */
      [/((?:思っ|考え|知っ|分かっ|わかっ|覚え|信じ|決め|待っ)て)る$/, '$1るし'], [/((?:思っ|考え|知っ|分かっ|わかっ|覚え|信じ|決め|待っ)て)た$/, '$1たんだよね'],
      [/^((?:(?!私|あたし|ウチ|俺|僕|自分|オレ|ボク).)*[てで])る$/, '$1るじゃん'], [/([てで])る$/, '$1るから'],
      [/^((?:(?!私|あたし|ウチ|俺|僕|自分|オレ|ボク).)*[てで])た$/, '$1たじゃん'], [/([てで])た$/, '$1たんだよね']
    ];
    if (tone === 'chara') return [
      [/気がする$/, f ? '気がすんだよね' : '気がすんだよな'], [/感じがする$/, '感じすんだよね'], [/と思う$/, f ? 'と思うんだよね' : 'と思うわ'], [/すぎる$/, 'すぎっしょ'],
      [/推す$/, f ? '推すね' : '推すわ'], [/(?:入れて)?おきたい$/, function (m) { return m.replace(/ておきたい$/, 'ときたい').replace(/おきたい$/, 'ときたい') + (f ? 'かな' : 'わ'); }],
      [/聞きたい$/, '聞きたいんだけど'], [/詰めたい$/, f ? '詰めたいんだよね' : '詰めたいんだわ'], [/てほしい$/, 'てほしいんだけど'], [/聞く$/, f ? '聞くよ' : '聞くわ'],
      [/今は([^、]{1,12})$/, '今は$1一択っしょ'], [/ないなら、([^、]{1,12})で$/, 'ないなら、$1でいいっしょ'],
      [/になる$/, 'になるっしょ'], [/一番黒い$/, f ? '一番クロかな' : '一番クロだわ'], [/([てで])る$/, f ? '$1んだよね' : '$1んだよな'], [/([てで])た$/, f ? '$1たんだよね' : '$1たんだよな']
    ];
    return [
      [/気がする$/, '気がするね'], [/感じがする$/, '感じがするね'], [/と思う$/, 'と思うよ'], [/すぎる$/, 'すぎるね'],
      [/推す$/, '推すとしようか'], [/おきたい$/, 'おきたいね'], [/聞きたい$/, '聞かせてほしいな'], [/詰めたい$/, '詰めたいところだね'],
      [/説明してほしい$/, '説明してくれるかい'], [/聞く$/, '聞こうか'],
      [/今は([^、]{1,12})$/, '今は$1だと思っているよ'], [/ないなら、([^、]{1,12})で$/, 'ないなら、$1でいいんじゃないかな'], [/一番黒い$/, '一番黒いと見ているよ'], [/([てで])る$/, '$1いるね']
    ];
  }
  /* すでに口調の目印がある文 */
  var MARK = /(?:[〜～]|じゃん|っしょ|だし|的な|ウケ|マジ|ヤバ|わ|ぜ|さ|かい|だね|よね|よな|だろうね|かな|かも|けど|んだよ[ねな]?|ね|よ|し|って)$/;

  function fix(tone, q, who) {
    if (!q || q.length < 28 || MOAN.test(q) || KEIGO.test(q) || GRAVE.test(q)) return q;
    var f = who && who.gender === 'f';
    var o = OPEN[tone] || [];
    for (var i = 0; i < o.length; i++) if (o[i][0].test(q)) { q = q.replace(o[i][0], o[i][1]); break; }
    var parts = q.split(/([。！？!?…‥\n]+)/), sents = [];
    for (var j = 0; j < parts.length; j += 2) if (parts[j] && /[^\s、]/.test(parts[j])) sents.push(j);
    if (!sents.length) return q;
    /* ギャル：「……」のある台詞（沈んだ・言いよどむ台詞）は語尾を足さない */
    if (tone === 'gyaru' && /[…‥]/.test(q)) return parts.join('');
    var E = ends(tone, f), done = 0;
    /* 最後の文と、途中の文一つ（くじ）。後ろから見る */
    var pick = [sents[sents.length - 1]];
    if (sents.length >= 3 && HK.lineLot(q, 2)) pick.push(sents[1 + (q.length % (sents.length - 2))]);
    pick.forEach(function (k) {
      var seg = parts[k], next = parts[k + 1] || '', prev = k ? parts[k - 1] : '';
      if (/[？?]/.test(next) || /[…‥]/.test(prev) || /^[…‥]/.test(next) || /[…‥]/.test(seg) || MARK.test(seg)) return;
      for (var e = 0; e < E.length; e++) if (E[e][0].test(seg)) { parts[k] = seg.replace(E[e][0], E[e][1]); done++; return; }
    });
    return parts.join('');
  }

  ['gyaru', 'chara', 'mystic'].forEach(function (tone) {
    var f0 = HK.TONE_FINISH[tone];
    if (!f0) return;
    HK.TONE_FINISH[tone] = function (q, who) { return fix(tone, f0(q, who), who); };
  });
})();
