/* 箱庭シミュレーター: 口調「尊大（〜のかね）」
   「君、ふざけているのかね」「私に任せたまえ」「ほう、そういうこともあるのか」「……私は君のそういうところを気に入っているのだがね」。
   厳格の表を、古風な紳士と同じ言い換え（「〜たまえ」「君」）で台詞にしてから、語尾を尊大に付け替える（tone-registry.js の derive: 'gentleman'）。
   紳士のやわらかい「〜かい？」「〜だい？」は「〜かね？」に、「おや」は「ほう」に、「やれやれ」は「まったく……」に。
   めったに崩れないが、驚くと「何なんだこれは！」と声を荒らげる。口調は話し方だけで、行動はエゴグラムで決まる */
(function () {
  'use strict';
  var HK = window.HK, V = HK.Voice;
  if (!V || !HK.toneFinish || !V.gentlemanQuote) return;
  var E = '(?=[。！？!?…‥、」]|$)';
  function re(s) { return new RegExp(s + E, 'g'); }
  /* 言い換えのない台詞は、紳士の言い換えに通す（語尾は下の sondai で付け替える） */
  var sq0 = V.styleQuote;
  V.styleQuote = function (q, who) {
    if (!who || who.tone !== 'sondai') return sq0(q, who);
    return sq0(q, Object.assign({}, who, { tone: 'gentleman' }));
  };
  var END = [
    /* 問いかけ：「〜かい？」「〜だい？」→「〜かね？」 */
    [/(何|誰|どこ|いつ|どう|なぜ|どれ|どんな|どの|どちら|どっち)([^？?。！!、]{0,12}?)(?:んだい|のだい)(?=[？?])/g, function (m, w, x) { return w + x + (/[てで]$/.test(x) ? 'いる' : '') + 'のかね'; }],
    [/(何|誰|どこ|いつ|なぜ|どれ|どっち|どちら|どなた)だい(?=[？?])/g, '$1かね'],
    [/(何|誰|どこ|いつ|どう|なぜ|どれ|どんな|どの|どちら|どっち)([^？?。！!、]{0,12}?)だい(?=[？?])/g, '$1$2かね'],
    [/([てで])んだい(?=[？?])/g, '$1いるのかね'], [/んだい(?=[？?])/g, 'のかね'], [/かい(?=[？?])/g, 'かね'],
    /* 「〜してた？」「〜ある？」のような素の問いかけも「〜のかね？」に */
    [/([てで])くれる(?=[？?])/g, '$1くれないかね'],
    [/([^かのねなよだ、…‥。！？!?「\s])([てで])た(?=[？?])/g, '$1$2いたのかね'], [/([^かのねなよだ、…‥。！？!?「\s])(る|た|ない)(?=[？?])/g, '$1$2のかね'],
    [/([^かのねなよだいはおえあ、…‥。！？!?「\s])い(?=[？?])/g, '$1いかね'], [/(?<=[^おこそとのほもよろごぞどぼぽょ、…‥。！？!?「\s])([うくすつぬむぶぐ])(?=[？?])/g, '$1かね'],
    [/のか(?=[？?])/g, 'のかね'], [/だい(?=[？?])/g, 'かね'], [/(?<!何|誰|どこ|いつ)([^かのねなよだ、…‥。！？!?「\s])か(?=[？?])/g, '$1かね'], [/のかい(?=[。…‥」]|$)/g, 'のかね'], [/かい(?=[…‥]+[？?])/g, 'かね'], [/(^|[…‥。、])(?:じゃ|では)ないと、/g, '$1さもないと、'],
    [/(何|誰|どこ|いつ|なぜ|どう)([^。？?、…‥]{0,10}?)の(?=。|$)/g, '$1$2のかね'],
    [re('かな'), 'かね'], [re('かしら'), 'かね'],
    /* 「〜じゃないか」は古風に */
    [/(?:じゃ|では)ないか(?=[。！!…‥、」]|$)/g, 'ではないか'], [/じゃないかね/g, 'ではないかね'],
    /* 「〜けど」「〜けどね」→「〜のだがね」「〜なのだがね」 */
    [re('(だろ|でしょ)うけど(?:ね|な)?'), 'だろうがね'], [re('なんだけど(?:ね|な)?'), 'なのだがね'], [re('んだけど(?:ね|な)?'), 'のだがね'], [re('だけど(?:ね|な)?'), 'なのだがね'], [re('([るたいうくすつぬむぶぐ])けど(?:ね|な)?'), '$1のだがね'],
    /* 紳士のやさしい止め方 →「〜ないでくれよ」 */
    [re('してはいけないよ'), 'しないでくれよ'], [re('来てはいけないよ'), '来ないでくれよ'], [re('行ってはいけないよ'), '行かないでくれよ'],
    [re('気にすることはないよ'), '気にすることはない'],
    [re('(う|よう)ぜ'), '$1ではないか'], [re('だぜ'), 'だ'], [re('(?<=[るたいうくすつむぶぐ])ぜ'), ''],
    [re('なんとかなるって'), 'なんとかなるだろう'], [re('([いしっきち])てない'), '$1ていない'],
    [re('感謝するよ'), '感謝する'], [/^見事(?:だね)?(?=[！!。]?$)/, '大したものだ'], [/(?<!お)見事(?=[。！!]?$)/, '見事なものだ'],
    /* 「〜んではない」（紳士の言い換えの残り）→「〜のではない」、「だろ」→「だろう」 */
    [/なんではない/g, 'なのではない'], [/んではない/g, 'のではない'], [re('だろ'), 'だろう'], [/んだろう/g, 'のだろう'],
    /* 「じゃ」は「では」に */
    [/じゃな([いく])/g, 'ではな$1'], [/ままじゃ/g, 'ままでは'], [/(それ|これ)じゃ(?=[、あ])/g, '$1では'], [/てたまえ/g, 'ていたまえ'],
    /* 「〜ろよ」（命令）→「〜たまえ」、意向の「〜うな」→「〜うではないか」 */
    [re('([えけげせてねべめれじ])ろよ'), '$1たまえ'], [re('(?<!おやす|お休|お帰|おかえ|ごめん)((?<!な)い|[きしちにひみりぎじびえけせてねへめれ])な(?:さい|よ)'), '$1たまえ'], [/([おこそとのもろごぞどぼぽよ])うな(?=[。！!]?$)/, '$1うではないか'],
    [/何なのだ(?:ね|な)(?=[！!])/g, '何なのだ'], [/(たかった|かった)んだね(?=[。]?$)/, '$1のだよ'], [/^大丈夫だね(?=[。！]?$)/, '大丈夫だ'], [/(私|君)だね(?=[。！]?$)/, '$1だ']
  ];
  function sondai(q) {
    if (!q) return q;
    /* 感嘆：台詞の頭の「おや」→「ほう」、「どうしよう」→「どうしたものか」（喘ぎや取り乱した台詞はそのまま） */
    var moan = /[…‥]っ|っ[…‥]|♡|[ぁぃぅぇぉ]|^[あん]、/.test(q);
    if (!moan) {
      /* 紳士の「頼むよ」は尊大には軽すぎる（「頼む」「頼むぞ」） */
      q = q.replace(/頼むよ(?=[。！？!?…、」]|$)/g, '頼む').replace(/^よろしく頼む(?=[。…」]|$)/, 'よろしく頼むぞ');
      q = q.replace(/^おや(?:おや)?(?=[、。！？!?]|$)/, 'ほう');
      q = q.replace(re('どうしよう'), 'どうしたものか');
    }
    /* 苛立ち：「やれやれ」→「まったく……」 */
    if (moan) q = q.replace(/やれやれ/g, 'くっ');
    q = q.replace(/やれやれ、(?=[^。]*[！!])/g, 'くっ、').replace(/やれやれ[、…‥。]*/g, 'まったく……');
    /* 二人称は「君」、「ごめん」は「すまない」、「どっち」は「どちら」 */
    q = q.replace(/あなた(?:たち|方|がた)/g, '君たち').replace(/あなた(?!様)/g, '君')
      .replace(/ごめん(?:なさい)?(?!だ)(ね)?/g, function (m, ne) { return 'すまない' + (ne || ''); }).replace(/どっち/g, 'どちら');
    /* 驚き：「何これ」「何だこれ」「なんなの、これ」→「何なんだこれは」 */
    q = q.replace(/(?:何|なに|なん)(?:だ|なの|なんだ)?、?(?:これ|コレ)(?:は)?(?=[！!？?…‥。]|$)/g, '何なんだこれは');
    q = q.replace(/何なんだこれは[？?]/g, '何なんだこれは！');
    END.forEach(function (w) { q = q.replace(w[0], w[1]); });
    /* 紳士の「〜だよ」は言い切りに。言い切りの「〜だね」は、ときどき「〜だな」に */
    q = q.replace(re('(?<![んの])だよ'), 'だ').replace(/じゃないのだがね/g, 'ではないのだがね');
    if (HK.lineLot(q, 2)) q = q.replace(/(?<!(?:何|誰|どこ|いつ|どう|なぜ|どれ|どちら|私|君))だね(?=[。！]?$)/, 'だな');
    /* 2026-10-30（第2回）：紳士の書き下ろしを借りた台詞のやわらかい文末（「止まったよ」「何でもないよ」「待たせたね」「ずるいね」）は、
       尊大の言い切りに（「止まった」「何でもない」「待たせたな」「ずるいな」、気づきの「〜ているよ」「赤いよ」は「〜ぞ」）。
       「〜のだよ」「〜だね」「〜かね」「〜からね」「〜だろうね」はそのまま。喘ぎ・取り乱した台詞は直さない */
    if (!moan) {
      var SE = '(?=[。！!…‥」]|$)';
      q = q.replace(new RegExp('すまないね' + SE, 'g'), 'すまない')
        .replace(new RegExp('([てで]い(?:る|た))よ' + SE, 'g'), '$1ぞ')
        .replace(new RegExp('(?<!じゃ|では)ないよ' + SE, 'g'), 'ない').replace(new RegExp('(?<!じゃ|では)ないね' + SE, 'g'), 'ないな').replace(new RegExp('([てで]いる|がたい)ね' + SE, 'g'), '$1な')
        .replace(new RegExp('(たい|いい)よ' + SE, 'g'), '$1').replace(new RegExp('(?<=[ぁ-ん一-鿿])(た|だ)よ' + SE, 'g'), function (m, t, off, str) { return t === 'だ' ? (/[のん]$/.test(str.slice(0, off)) ? m : 'だ') : 'た'; })
        .replace(new RegExp('(?<=[ぁ-ん一-鿿])たね' + SE, 'g'), 'たな').replace(new RegExp('(?<=[ぁ-ん一-鿿])([うくすつぬむぶぐる])よ' + SE, 'g'), '$1')
        .replace(new RegExp('(?<=[ぁ-ん一-鿿])(?<![たい])いよ' + SE, 'g'), 'いぞ').replace(new RegExp('(?<=[ぁ-ん一-鿿])(?<![たいな])いね' + SE, 'g'), 'いな');
    }
    /* 「〜ではないかね」の重なりなど */
    return q.replace(/かねかね/g, 'かね').replace(/([！？!?])。/g, '$1');
  }
  V.sondaiQuote = sondai;
  HK.toneFinish('sondai', sondai);
})();
