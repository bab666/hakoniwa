    "gentle\t〈〉ってさ、自分がどう見えてるか分かってないでしょ\t〈〉ってさ、自分が周りからどう見えてるか、わかってないよね",

    /* ---- 頼れる兄貴・姉貴分（aniki）：さっぱりした話し言葉に ---- */
