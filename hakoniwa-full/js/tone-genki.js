/* 箱庭シミュレーター: 敬語から派生する口調（明るい敬語）
   文面と台詞の言い換えは「敬語」をそのまま使い（名前・一人称・見本・派生元は tone-registry.js）、
   できあがった敬語の台詞を、最後に元気いっぱいの言い方に付け替える。
   ・かたい謙譲・尊敬の言い回しはふつうの丁寧語に（「いたします」→「します」、「恐れ入りますが」→「すみません」、「少々」→「ちょっと」）
   ・「〜てしまいました」→「〜ちゃいました」、「えっ」→「ええっ！？」、「やった」→「やったー！」
   ・明るい文は「。」を「！」に。ときどき「〜まーす！」「〜ですよ〜」「〜ましょー！」と伸ばす（毎文にはつけない）
   喘ぎ・叫びの台詞は触らない。悲しい・謝る・怒る・ためらう（……）台詞は落ち着いたまま（言い回しだけ直す） */
(function () {
  'use strict';
  var HK = window.HK, V = HK && HK.Voice;
  if (!V || !HK.toneFinish) return;

  var END = '(?=[。！？!?…‥、」\\s]|$)';
  /* 喘ぎ（「っ」で切れる・小さい母音・♡）。文頭の驚きの「えっ」「あっ」は除く */
  var MOAN = /[ぁぃぅぇぉァィゥェォ♡]|ッ|(?:^|[^えあおう])っ(?=[、。…‥！？!?\s～〜ー]|$)|ん(?:っ|ぅ)/;
  /* 叫び（「ああああ」「きゃあ」） */
  var SCREAM = /([ぁ-んァ-ン])\1\1|きゃ|ぎゃ|うわあ|ひいい|いやあ/;
  /* 悲しい・謝る・怒る・深刻な台詞（明るくしない） */
  var SAD = /ごめん|すみません|すいません|申し訳|失礼|恐縮|悲し|かなし|寂し|さみし|さびし|辛|つら[いかく]|痛|苦し|死|殺|泣|涙|怖|こわ[いか]|嫌|いや[だで]|いやです|許さ|許して|許しません|最低|最悪|残念|無理|ダメ|だめ|やめ|止め|助けて|別れ|さよう?なら|後悔|心配|不安|危な|危険|疲れ|血|傷|病|亡|葬|墓|謝|反省|すまな|怒|ふざけ|黙|うるさ|邪魔|帰って|出て行|出ていけ|消え|憎|恨|裏切|犯人|嘘|うそ|罪|罰|逃げ|離して|触らな|来ないで|見ないで|放っておいて|寒|震|恥|情けな|悔し|くやし|絶望|孤独|ひとり|一人で|狙|襲|捕|監禁|脅|命令|我慢|耐え|勘弁|違います|困り|困っ|迷惑|おかしい|変です|まずい|^しまった|やられ|仕留|真相|正体|人狼|事件|いい加減|お断り|心外/;
  /* 明るい文の目印 */
  var UP = /ありがとう|よろしく|お願いしま|頑張|がんば|やった|嬉し|うれし|楽し|たのし|すご[いく]|すっご|おいし|美味し|うま[いか]|大丈夫|任せ|ましょう|おはよう|こんにちは|こんばんは|行ってきま|いってきま|ただいま|おかえり|^いただきます|ごちそう|おめでとう|最高|さすが|素敵|すてき|かわい|可愛|大好き|わかりました|分かりました|了解|もちろん|ぜひ|是非|なんとか|元気|よかった|良かった|助か|できました|やりました|勝ちました|見つけました|ばっちり|バッチリ|完璧|楽しみ|わくわく|ワクワク|いい天気|お疲れ|どうぞ|こっちです|早く早く|行きます|来ました|着きました|まーす|ちゃいま/;

  /* かたい言い回しをふつうの丁寧語に（どの台詞でも） */
  function soften(q) {
    return q
      .replace(/恐れ入りますが、?/g, 'すみません、').replace(/恐れ入ります/g, 'すみません')
      .replace(/かしこまりました/g, 'わかりました').replace(/承知(?:いた)?しました/g, 'わかりました')
      .replace(/(?:いたし|致し)かねます/g, 'できません')
      .replace(/(?:いた|致)し(?=ま[すしせ]|て|た)/g, 'し')
      .replace(/でございます/g, 'です').replace(/でございました/g, 'でした')
      .replace(/(?<!ありがとう|おはよう|おめでとう)ございま(?=[すしせ])/g, 'ありま')
      .replace(/と申します/g, 'です').replace(/お願い申し上げま/g, 'お願いしま')
      .replace(/て参りま(?=[すし])/g, 'てきま').replace(/参りま(?=[すし])/g, '行きま')
      .replace(/と存じます/g, 'と思います').replace(/存じませ(?=ん)/g, '知りませ').replace(/存じて/g, '知って')
      .replace(/させていただきま(?=[すし])/g, 'させてもらいま').replace(/させていただ(?=く)/g, 'させてもら')
      .replace(/いただけま(?=[すせ])/g, 'もらえま').replace(/いただけない/g, 'もらえない')
      .replace(/少々/g, 'ちょっと').replace(/誠に/g, '本当に').replace(/皆様/g, 'みなさん').replace(/今宵/g, '今夜')
      .replace(/いかがですか/g, 'どうですか').replace(/いかがでしょう/g, 'どうでしょう');
  }
  /* 「〜てしまいました」→「〜ちゃいました」（明るい台詞だけ） */
  function chau(q) {
    return q.replace(/([てで])しま(いました|います|いません|いそう|って|った|う|おう|いましょう)/g, function (m, t, e) {
      var c = t === 'て' ? 'ちゃ' : 'じゃ';
      return c + { 'いました': 'いました', 'います': 'います', 'いません': 'いません', 'いそう': 'いそう', 'って': 'って', 'った': 'った', 'う': 'う', 'おう': 'おう', 'いましょう': 'いましょう' }[e];
    });
  }

  /* 一文を伸ばす（間引きは文ごとのくじ） */
  var GREET = /(?:よろしくお願いします|^(?:お願いします|行ってきます|いってきます|いただきます))$/;
  function stretch(s) {
    if (/[ー〜～]$/.test(s)) return s;
    if (GREET.test(s)) return s.replace(/ます$/, 'まーす');
    if (/お願いします$/.test(s)) return HK.lineLot(s, 2) ? s.replace(/ます$/, 'まーす') : s;
    if (/[ぁ-ん一-鿿]ます$/.test(s) && !/(?:思い|ござい|あり|おり|い)ます$/.test(s) && HK.lineLot(s, 4)) return s.replace(/ます$/, 'まーす');
    if (/(?:です|ません)よ$/.test(s) && HK.lineLot(s, 2)) return s + '〜';
    if (/ましょう$/.test(s) && HK.lineLot(s, 3)) return s.replace(/ましょう$/, 'ましょー');
    return s;
  }

  function conv(q, who) {
    if (!q || MOAN.test(q.replace(/^[…‥、\s]*えっ/, '')) || SCREAM.test(q)) return q;
    q = soften(q);
    var sad = SAD.test(q), shy = /[…‥]/.test(q);
    /* 驚きの「えっ」→「ええっ！？」（「えっと」は除く） */
    if (!shy) q = q.replace(/^えっ(?!と)[、。！？!?\s]*/, 'ええっ！？　').replace(/^ええっ！？　$/, 'ええっ！？');
    if (sad || shy) return q;
    q = chau(q);
    /* 「やった」（間投詞）→「やったー！」 */
    q = q.replace(/(^|[。！？!?\s])やった[ぁあー]*(?:[、。！!]+|$)\s*/g, function (m, p, at, all) { return p + 'やったー！' + (at + m.length < all.length ? '　' : ''); });

    var parts = q.split(/([。！？!?…‥\n]+)/), bright = false, bang = false;
    parts.forEach(function (seg, i) { if (!(i % 2) && UP.test(seg)) bright = true; });
    if (!bright) return q;
    for (var i = 0; i < parts.length; i += 2) {
      var seg = parts[i], punct = parts[i + 1] || '';
      if (!seg || /[？?]/.test(punct)) continue;
      var lead = (seg.match(/^[、\s]+/) || [''])[0];
      var body = seg.slice(lead.length);
      if (!body || /[ー〜～、か]$/.test(body)) continue;
      var up = UP.test(body);
      /* 言い切りの文（打ち消しは、明るい目印がないかぎり除く） */
      var polite = /(?:です|ます|ました|でした|ましょう|ください|ですよ|ですね|ますよ|ますね|ませんよ|ますって|ですって)$/.test(body);
      var neg = /(?:ません|ない|なかった|ないです|ずに)(?:よ|ね|でした)?$/.test(body) && !up;
      /* 明るい目印のない文は、短い言い切り（「仁です」「近道を見つけました」）だけ */
      var plain = /(?:です|ます|ました|でした)$/.test(body) && !/(?:から|けど|ので)/.test(body) && body.length <= 12;
      if (neg || !(up ? polite || body.length <= 10 : plain)) continue;
      if (up) body = stretch(body);
      parts[i] = lead + body;
      if (/^。/.test(punct)) parts[i + 1] = punct.replace(/^。/, '！');
      else if (i === parts.length - 1) bang = true;
    }
    var s = parts.join('') + (bang ? '！' : '');
    /* 文の途中の「！」のあとは全角空き（「仁です！　よろしく」） */
    return s.replace(/！(?=[^！？!?」\s　）)…‥])/g, '！　').replace(/！！+/g, '！');
  }
  HK.toneFinish('genki', conv);
})();
