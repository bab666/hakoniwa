  /* 「〜てしまいました」→「〜ちゃいました」（明るい台詞だけ） */
  function chau(q) {
    return q.replace(/([てで])しま(いました|います|いません|いそう|いたい|って|った|う|おう|いましょう)/g, function (m, t, e) {
      var c = t === 'て' ? 'ちゃ' : 'じゃ';
      return c + { 'いました': 'いました', 'います': 'います', 'いません': 'いません', 'いそう': 'いそう', 'いたい': 'いたい', 'って': 'って', 'った': 'った', 'う': 'う', 'おう': 'おう', 'いましょう': 'いましょう' }[e];
    });
  }

  /* 一文を伸ばす（間引きは文ごとのくじ） */
  var GREET = /(?:よろしくお願いします|^(?:お願いします|行ってきます|いってきます|いただきます))$/;
  function stretch(s) {
    if (/[ー〜～]$/.test(s)) return s;
    if (GREET.test(s)) return s.replace(/ます$/, 'まーす');
    if (/お願いします$/.test(s)) return HK.lineLot(s, 2) ? s.replace(/ます$/, 'まーす') : s;
    if (/[ぁ-ん一-鿿]ます$/.test(s) && !/(?:思い|ござい|あり|おり|い|わかり|分かり|でき)ます$/.test(s) && HK.lineLot(s, 4)) return s.replace(/ます$/, 'まーす');
    if (/(?:です|ません)よ$/.test(s) && HK.lineLot(s, 2)) return s + '〜';
    if (/ましょう$/.test(s) && HK.lineLot(s, 3)) return s.replace(/ましょう$/, 'ましょー');
    return s;
  }

  function conv(q, who) {
    if (!q) return q;
    q = casual(soften(q));
    /* 「我慢なさらなくて結構です」→「我慢しなくていいんです」、問いの「誰です」→「誰ですか？」 */
    q = q.replace(/なさらなくて結構です/g, 'しなくていいんです').replace(/なさら(ない|なく)/g, 'し$1')
      .replace(/(何|誰|どこ|いつ|どれ|どなた)です(?=[。]|$)/g, '$1ですか？').replace(/？。/g, '？');
    /* 喘ぎ・叫びは「〜てしまいます」→「〜ちゃいます」だけ */
    if (MOAN.test(q.replace(/^[…‥、\s]*えっ/, '')) || SCREAM.test(q)) return chau(q);
    var sad = SAD.test(q), shy = /[…‥]/.test(q);
    /* 驚きの「えっ」→「ええっ！？」（「えっと」は除く） */
    if (!shy) q = q.replace(/^えっ(?!と)[、。！？!?\s]*/, 'ええっ！？　').replace(/^ええっ！？　$/, 'ええっ！？');
    if (sad) return q;
    q = chau(q);
    if (shy) return q;
    /* 「やった」（間投詞）→「やったー！」 */
    q = q.replace(/(^|[。！？!?\s])やった[ぁあー]*(?:[、。！!]+|$)\s*/g, function (m, p, at, all) { return p + 'やったー！' + (at + m.length < all.length ? '　' : ''); });

    var parts = q.split(/([。！？!?…‥\n]+)/), bright = false, bang = false;
    parts.forEach(function (seg, i) { if (!(i % 2) && (UP.test(seg) || /(?<!あり)ませんよ$/.test(seg))) bright = true; });
    if (!bright) return q;
    for (var i = 0; i < parts.length; i += 2) {
      var seg = parts[i], punct = parts[i + 1] || '';
      if (!seg || /[？?]/.test(punct)) continue;
      var lead = (seg.match(/^[、\s]+/) || [''])[0];
      var body = seg.slice(lead.length);
      if (!body || /[ー〜～、か]$/.test(body)) continue;
      /* 「〜ませんよ」は言い返し（「負けませんよ〜！」） */
      var up = UP.test(body) || /(?<!あり)ませんよ$/.test(body);
      /* 言い切りの文（打ち消しは、明るい目印がないかぎり除く） */
      var polite = /(?:(?:です|ます|ました|でした|ましょう|ください|ません)(?:よ|ね|よね)?|(?:です|ます)って)$/.test(body);
      var neg = /(?:ません|ない|なかった|ないです|ずに)(?:よ|ね|でした)?$/.test(body) && !up;
      /* 明るい目印のない文は、短い言い切り（「仁です」「近道を見つけました」）だけ */
      var plain = /(?:です|ます|ました|でした)(?:よ|ね)?$/.test(body) && !/(?:から|けど|ので)/.test(body) && body.length <= 12;
      if (neg || !(up ? polite || body.length <= 10 : plain)) continue;
      if (up) body = stretch(body);
      parts[i] = lead + body;
      if (/^。/.test(punct)) parts[i + 1] = punct.replace(/^。/, '！');
      else if (i === parts.length - 1) bang = true;
    }
    var s = parts.join('') + (bang ? '！' : '');
    /* 文の途中の「！」のあとは全角空き（「仁です！　よろしく」） */
    return s.replace(/！(?=[^！？!?」\s　）)…‥])/g, '！　').replace(/！！+/g, '！');
  }
  HK.toneFinish('genki', conv);
