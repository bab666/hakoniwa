/* 箱庭シミュレーター: 口調「古風な紳士」
   「〜したまえ」「〜ということだね」「〜ということかい？」「〜のようだね」といった、落ち着いた古風な話し方。
   口調は台詞の話し方を決めるだけで、行動はエゴグラムの数値で決まる（文面の表は「厳格」から借りて、話し方を整える） */
(function () {
  'use strict';
  var HK = window.HK, V = HK.Voice, EX = HK.TONE_EXTRA;
  if (!V || !EX) return;
  var E = '(?=[。！？!?…、」]|$)';
  function re(s) { return new RegExp(s + E, 'g'); }
  /* 命令・お願い → 「〜たまえ」 */
  var IMP = [
    ['(?:待て|待って(?:くれ|ください)?)', '待ちたまえ'], ['(?:来い|来て(?:くれ|ください)?)', '来たまえ'], ['(?<!から|より)(?:見ろ|見て(?:くれ|ください)?)', '見たまえ'],
    ['(?:休め|休んで(?:くれ|ください)?)', '休みたまえ'], ['(?:言え|言って(?:くれ|ください)?)', '言いたまえ'], ['(?<!って|と)(?:聞け|聞いて(?:くれ|ください)?)', '聞きたまえ'],
    ['(?:座れ|座って(?:くれ|ください)?)', '座りたまえ'], ['(?:下がれ|下がってろ|下がって(?:いて)?)', '下がっていたまえ'], ['(?:食え|食べろ|食べて(?:くれ|ください)?)', '食べたまえ'],
    ['(?:寝ろ|寝て(?:くれ|ください)?)', '眠りたまえ'], ['(?:逃げろ|逃げて(?:くれ|ください)?)', '逃げたまえ'], ['(?:考えろ|考えて(?:くれ|ください)?)', '考えたまえ'],
    ['(?:落ち着け|落ち着いて(?:くれ|ください)?)', '落ち着きたまえ'], ['(?:急げ|急いで(?:くれ|ください)?)', '急ぎたまえ'], ['(?:黙れ|黙って(?:くれ|ろ)?)', '黙っていたまえ'],
    ['(?:守れ|守って(?:くれ|ください)?)', '守りたまえ'], ['(?:走れ|走って(?:くれ|ください)?)', '走りたまえ'], ['(?:戻れ|戻って(?:くれ|ください)?)', '戻りたまえ'],
    ['(?:任せろ|任せて(?:くれ|ください)?)', '任せたまえ'], ['(?:気をつけろ|気をつけて(?:くれ|ください)?)', '気をつけたまえ'], ['(?:やめろ|やめて(?:くれ|ください)?)', 'やめたまえ'],
    ['(?:止まれ|止まって(?:くれ|ください)?)', '止まりたまえ'], ['(?:立て|立って(?:くれ|ください)?)(?!、?いられ)', '立ちたまえ'], ['(?:見せろ|見せて(?:くれ|ください)?)', '見せたまえ'],
    ['(?:貸せ|貸して(?:くれ|ください)?)', '貸したまえ'], ['(?:止めろ|止めて(?:くれ|ください)?)', '止めたまえ'], ['(?:行くな|行かないで(?:くれ|ください)?)', '行ってはいけないよ'],
    ['気に(?:するな|しないで(?:くれ|ください)?)', '気にすることはないよ'], ['(?:するな|しないで(?:くれ|ください)?)', 'してはいけないよ'], ['(?:来るな|来ないで(?:くれ|ください)?)', '来てはいけないよ'],
    ['(?<!決|対|関|通|際|に対|に関|と|を通|反|^そ|^こう|^ああ|^どう|[、…‥。]そ|緊張|興奮|動揺|混乱|感動|後悔|苦労|安心|納得|困惑)(?:しろ|せよ|して(?:くれ|ください)?|しなさい)', 'したまえ'], ['(?:頼む|お願い(?:します)?)', '頼むよ']
  ];
  var ASK = [
    [re('じゃない(?:でしょ|でしょう|だろ|だろう)[？?]'), 'ではないだろう？'], [re('(?:でしょ|でしょう)[？?]'), 'だろう？'],
    [re('なんじゃない(?:の|か)?[？?]'), 'なのではないかい？'],
    [re('じゃない(?:の|か)?[？?]'), 'ではないかい？'], [re('ではない(?:の)?か[？?]'), 'ではないかい？'],
    [/(何|誰|どこ|いつ|どう|なぜ|どれ|どっち)([^？?。！、]{0,12})(?:のだ|の|んだ)[？?]/g, '$1$2んだい？'], [re('のだ[？?]'), 'のかい？'], [re('(?:の|んだ)(?:か)?[？?]'), 'のかい？'], [re('ってこと(?:か)?[？?]'), 'ということかい？'], [re('ということ(?:か)?[？?]'), 'ということかい？'],
    [re('こと[？?]'), 'ことかい？'], [re('いい[？?]'), 'いいかい？'], [/(誰|何|どこ|いつ|なぜ|どうして|どれ|どっち|どなた)[？?]/g, '$1だい？'], [/([一-龯ァ-ヶー])[？?]/g, '$1かい？'], [re('(?:だ)?か[？?]'), 'かい？'], [re('(?:だ)?よな[？?]'), 'だろう？']
  ];
  var END = [
    [re('ってことだ(?:な|よ|ね)?'), 'ということだね'], [re('ってこと'), 'ということだね'], 
    [re('(?:の|ん)かよ'), 'のかね'], [re('かよ'), 'なのかね'],
    [re('感謝する'), '感謝するよ'], [re('だぜ'), 'だよ'], [re('だよな'), 'だね'], [re('よな'), 'ね'], [re('だな'), 'だね'], [re('じゃない(?:でしょ|でしょう|だろ)'), 'ではないだろう'], [re('(?:でしょ|でしょう)'), 'だろう'], [re('(いる|ある|ない|てる|いい)な'), '$1ね'], [re('じゃないか'), 'ではないかい'], [re('(る)んじゃない'), '$1のではない'], [re('じゃない'), 'ではない'],[re('じゃん'), 'だろう'], [re('(?<!どう)ぞ'), 'よ'], [re('((?<!^|[、…‥。！？!?「\\s])う|(?<!ふわ)[^、…‥。！？「\\sう])(?:わ|わよ|のよ)'), '$1よ']
  ];
  var WORD = [[/(?:お前|おまえ|あんた|てめえ|貴様)(?!さん|方)/g, '君'], [/(?<![手ど下やへ])(?:くそっ?|クソっ?)(?![たれ])|ちっ(?![ちさぽ])(?=[、。…！!？?」\s]|$)/g, 'やれやれ'], [/マジで|まじで/g, '本当に'], [/それって(?=[、どなー])/g, 'それは'], [/^ありがとう(?=[。！]|$)/, 'ありがとう、感謝するよ'], [/助かる(?=[。！]|$)/g, '助かるよ'], [/すげえ|すごい/g, '見事'], [/やばい|ヤバい/g, 'まずい'], [/うるさい/g, '騒々しい']];
  function gentle(q) {
    /* 敬語の台詞は、まずくだけた形にしてから紳士の言い方へ */
    if (V.casualQuote && /(です|ます|ください|ません|でした|ました)/.test(q)) q = V.casualQuote(q);
    WORD.forEach(function (w) { q = q.replace(w[0], w[1]); });
    /* 荒い打ち消し「イかねえ」「分からねえ」→「イかない」「分からない」 */
    q = q.replace(/([かさたなまらわがば])ねえ(?=[。！？!?…、」よ]|$)/g, '$1ない');
    /* 「一人でいるな」（してはいけない）を、あとで「いるね」にしない */
    q = q.replace(/一人でいるな(?=[。！!]|$)/g, '一人でいてはいけない');
    var WANT_MU = /(?:[休読飲住産踏盗噛咬編挑拝望恨悩頼絡包進済潜込囲積組畳刻睨憎惜沈澄嗜掴摘挟拒揉覗]|楽し|苦し|悲し|親し|惜し|慈し|怪し|訝し|やす|たの|つか|すす|(?:^|[、…‥\s「])[のよかこふつもす])$/;
    /* 「〜みたいだ」「〜らしい」→ 用言のあとは「ようだね」、名詞のあとは「のようだね」 */
    q = q.replace(re('(.)(?:みたいだ|みたい|らしい)(?:な|ね|よ)?'), function (m, ch, off, str) {
      /* 「休みたい」「楽しみたい」は「〜む」の動詞の「〜たい」で、「〜のようだ」ではない */
      if (/^.みたい/.test(m) && WANT_MU.test(str.slice(0, off + 1))) return m;
      return ch + (/[ぁ-ん]/.test(ch) && !/[のね]/.test(ch) && !/(?:つもり|もの|こと|はず|わけ|とこ|ところ|ども|たち|ぼく|わたし|あなた|みんな)$/.test(str.slice(0, off + 1)) ? 'ようだね' : 'のようだね'); });
    /* 台詞の頭の「見て、」「待って、」は呼びかけ（あとが「〜た」でも命令） */
    q = q.replace(/^見て、/, '見たまえ、').replace(/^待って、/, '待ちたまえ、');
    /* 「〜して、誰が…？」のように、あとが問いかけなら「て、」は命令ではない */
    IMP.forEach(function (w) { q = q.replace(/て/.test(w[0]) ? new RegExp(w[0] + '(?=[。！!…」]|$|、(?![^。！？!?]*(?:[？?]|誰|何|どこ|なぜ|どう|[^よ]た(?=[。…]|$)|[おこそとのもろごぞどぼぽ]う(?=[。…]|$))))', 'g') : re(w[0]), w[1]); });
    ASK.forEach(function (w) { q = q.replace(w[0], w[1]); });
    END.forEach(function (w) { q = q.replace(w[0], w[1]); });
    /* 「見てて」「待ってて」→「見ていたまえ」 */
    q = q.replace(/(見|待っ|聞い|黙っ)て(?:て|いろ)(?=[。！!…」]|$)/g, '$1ていたまえ').replace(/てたまえ/g, 'ていたまえ');
    /* 言い切りの「〜だ」は、ときどき「〜だね」に（長い台詞の最後だけ） */
    q = q.replace(/([^まただ])だ(?=[。！]?$)/, '$1だね');
    /* 「〜かね」は使わない（もとの口調の表から来たものも、やわらかく） */
    q = q.replace(/のかね(?=[？?])/g, 'のかい').replace(/(何|誰|どこ|いつ|どう|どれ|なぜ)(?!か|も|でも)([^？?。！]{0,12})かね(?=[？?])/g, '$1$2だい').replace(/かね(?=[？?])/g, 'かい').replace(/かね(?=[。！…、」]|$)/g, 'かな');
    q = q.replace(/(何|誰|どこ|いつ|どう|どれ|なぜ|どんな|どの|どちら)(?!か|も|でも)([^？?。！]{0,12}?)([^ん])かい(?=[？?])/g, '$1$2$3だい');
    /* 「やめたまえってば」→「やめたまえと言っている」 */
    q = q.replace(/たまえってば/g, 'たまえと言っている');
    return q.replace(/かいかい/g, 'かい').replace(/だねね/g, 'だね').replace(/([！？!?])。/g, '$1');
  }
  V.gentlemanQuote = gentle;
  var sq0 = V.styleQuote;
  V.styleQuote = function (q, who) {
    if (!who || who.tone !== 'gentleman') return sq0(q, who);
    q = sq0(q, Object.assign({}, who, { persona: 'stern' }));
    return gentle(q);
  };
})();
