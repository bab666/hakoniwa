  function noteOf(c) { return (c && (c.raceNote || (c.src && c.src.raceNote))) || ''; }
  /* 文を出せる人か：体の特徴・その他の種族の名前・目につく特徴のどれかがあれば種族の鍵（種族が無ければ 'feat'） */
