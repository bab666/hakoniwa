/* 箱庭シミュレーター: 吸血鬼の吸血に重なる性描写（R18版のみ。全年齢版ではこのファイルは読み込まれない）
   催眠をかけた相手・力ずくで押さえた相手を、血を吸いながら抱く（恋仲の同意のうえのこともある）。
   どちらが攻めかは HK.Pos.order で決める。自分で「攻め」を選んだ人を受ける側には置かない（Pos.okSex を満たす組だけ呼ばれる）。
   {t}=攻め（動く側） {u}=受け {v}=吸血鬼 {w}=吸われる人。登場人物はすべて成人として扱う */
(function () {
  'use strict';
  var HK = window.HK, SP = HK.Special;
  if (!SP) return;
  function L(s) { return s.split('|'); }
  function fmt(t, v) { return String(t).replace(/\{(\w+)\}/g, function (m, k) { return v[k] != null ? v[k] : m; }); }
  /* 吸血鬼が攻め（抱く側） */
  var VT = {
    pen: L('{v}は{w}を組み敷いたまま、首筋に牙を沈め、同時に奥まで貫いた。血を啜られるたびに{w}の体はびくりと跳ね、そのたびに{v}は深く突き上げた。|{v}は{w}の脚を割り開き、喉元に牙を立てたまま腰を打ちつけた。{w}は血を吸われる甘い痺れと、内側を抉られる熱の区別がつかなくなっていった。|{v}は{w}を壁に押しつけて後ろから貫き、うなじに牙を立てた。吸われるたびに{w}の中が締まり、{v}は{w}の奥に熱を吐き出した。'),
    ride: L('{v}は{w}を床に押し倒して跨り、自分から腰を沈めた。{w}が身じろぐたびに、{v}は首筋の傷に舌を這わせ、搾り取るように腰を揺すった。|{v}は{w}の上に跨ったまま、首筋に牙を立てて血を啜った。{w}がたまらず達しても、{v}は腰を止めなかった。'),
    ff: L('{v}は{w}を抱きすくめ、首筋に牙を立てながら、脚の間に指を沈めた。血を吸われるたびに{w}は甘く痙攣し、{v}の指を締めつけた。|{v}は{w}に覆いかぶさり、喉元から血を啜りながら、濡れたところを擦り合わせた。{w}は抗う力もなく、何度も果てた。')
  };
  /* 吸われる側が攻め（吸血鬼が受ける側）：吸血鬼が誘い、跨り、血を吸いながら抱かれる */
  var WT = {
    pen: L('{v}は{w}の首に腕を回し、引き寄せた。{w}は熱に浮かされたように{v}を押し倒し、そのまま貫いた。{v}は突き上げられながら{w}の首筋に牙を立て、血と快楽を同時に貪った。|{v}は{w}の膝に跨り、自分から{w}を受け入れた。腰を沈めるたびに、{v}は{w}の喉元から血を啜った。'),
    ride: L('{v}は{w}を誘うように横たわった。{w}は{v}の上に跨り、腰を落とした。{v}は下から{w}を抱き寄せ、揺さぶられながら首筋に牙を沈めた。'),
    ff: L('{v}は{w}の手を取り、自分の脚の間へ導いた。{w}の指に掻き回されながら、{v}は{w}の首筋に牙を立てた。')
  };
  var HOW = { '催眠': L('{w}は、命じられるままに服を脱いだ。|{w}の目は、うつろなままだった。'), '力ずく': L('{w}はもがいたが、吸血鬼の力には敵わなかった。|{w}の抵抗は、血を吸われるうちに弱まっていった。'), '同意（恋仲）': L('{w}は自分から{v}の背中に腕を回した。'), '同意': L('{w}は戸惑いながらも、拒まなかった。') };
  function body(top, bot) {
    var Pz = HK.Pos;
    if (Pz.isF(top) && Pz.isF(bot)) return 'ff';
    if (Pz.isF(top)) return 'ride';
    return 'pen';
  }
  SP.R18 = {
    text: function (A, v, w, how) {
      var Pz = HK.Pos, o = Pz.order(v, w, [v, w]), top = o[0], bot = o[1];
      if (Pz.hardTop(bot)) return '';
      var pool = top === v ? VT : WT, k = body(top, bot);
      var arr = pool[k] || pool.pen, h = HOW[how] || [''];
      return fmt(h[Math.floor(A.rng() * h.length)], { v: v.name, w: w.name }) + fmt(arr[Math.floor(A.rng() * arr.length)], { v: v.name, w: w.name });
    }
  };
})();
