/* 箱庭シミュレーター: デスゲーム系の共通部品 ―― 生い立ち（人の死・殺人への耐性）と、検死の知識
   ・生い立ち：平和な日常／死が身近な世界／人を殺したことがある。エゴグラムが同じでも、
     死体を見たときの消耗、殺人へのためらい、手にかけたあとの崩れ方が変わる（耐性 tol 0〜1）
   ・検死の知識：なし／少し（看護師・救急隊員・刑事など）／専門家（医師・監察医・鑑識）（kn 0〜2）
     推理が苦手でも、死因や死亡推定時刻で捜査に貢献できる。犯人側なら偽装にも使える
   ・裁判デスゲームの動機と館内放送の追加分（K.MOTIVES・K.BROADCAST）
   裁判デスゲーム・バトルロワイヤル・吹雪の館の殺人で使う */
(function () {
  'use strict';
  var HK = window.HK, clamp = HK.clamp;
  var K = HK.DGK = {};

  K.LIFE = { id: 'life', label: '生い立ち', auto: 'おまかせ（気質から）', options: [
    { id: 'peace', label: '平和な日常を生きてきた' },
    { id: 'harsh', label: '死が身近な世界で生きてきた（戦地・災害現場・裏社会など）' },
    { id: 'killed', label: '人を殺したことがある' }
  ] };
  K.KNOW = { id: 'know', label: '検死の知識', auto: 'おまかせ（気質から）', options: [
    { id: 'none', label: 'なし' },
    { id: 'some', label: '少しある（看護師・救急隊員・刑事など）' },
    { id: 'expert', label: '専門家（医師・監察医・鑑識）' }
  ] };
  K.LIFE_LABEL = { peace: '平和な日常', harsh: '死が身近な世界', killed: '人を殺したことがある' };
  K.KNOW_LABEL = ['なし', '少しある', '専門家'];

  /* c: { tr, pick } に life / tol / kn をつける */
  K.init = function (rng, c, opt) {
    opt = opt || {};
    var t = c.tr, pick = c.pick || {};
    var life = pick.life;
    if (!K.LIFE_LABEL[life]) {
      var w = { peace: 1, harsh: 0.1 + t.cold * 0.2 + t.aggr * 0.12, killed: 0.02 + t.cold * t.aggr * 0.12 };
      life = HK.weighted(rng, ['peace', 'harsh', 'killed'], function (k) { return w[k]; });
      c.lifeAuto = true;
    }
    c.life = life;
    var base = { peace: 0.08, harsh: 0.5, killed: 0.76 }[life];
    c.tol = clamp(base + t.cold * 0.22 + t.aggr * 0.06 - t.ac * 0.06 - t.np * 0.04, 0, 1);
    if (opt.know === false) return c;
    var kn = { none: 0, some: 1, expert: 2 }[pick.know];
    if (kn == null) {
      var r = rng();
      kn = r < 0.03 + t.a * 0.04 + (opt.knBias || 0) ? 2 : r < 0.1 + t.a * 0.1 + (opt.knBias || 0) * 2 ? 1 : 0;
      if (opt.knMin) kn = Math.max(kn, opt.knMin);
      c.knAuto = true;
    }
    c.kn = kn;
    return c;
  };
  K.tol = function (c) { return c && c.tol != null ? c.tol : null; };
  /* 死体や死を目にしたときの消耗の倍率（平和な人ほど大きい） */
  K.drain = function (c) { return c && c.tol != null ? 1.35 - c.tol * 0.75 : 1; };
  /* 殺すことへのためらい（0〜1） */
  K.hesitate = function (c) { return c && c.tol != null ? clamp((1 - c.tol) * 0.55 + c.tr.np * 0.2 - c.tr.cold * 0.15, 0, 0.9) : 0.2; };
  /* 取っ組み合いの強さ（武器や体力のない箱庭向けのおおまかな値） */
  K.phys = function (c, rng) { return c.tr.aggr * 0.4 + c.tr.cp * 0.15 + (c.tol || 0) * 0.25 + (c.stats && c.stats.hp ? (c.stats.hp - 3) * 0.06 : 0) + rng() * 0.35; };
  K.note = function (c) {
    var s = [];
    if (c.life) s.push('生い立ち：' + K.LIFE_LABEL[c.life] + (c.lifeAuto ? '（気質から）' : ''));
    if (c.kn != null) s.push('検死の知識：' + K.KNOW_LABEL[c.kn]);
    return s.join('・');
  };

  /* 死体を見たときの反応 */
  K.SHOCK = {
    peace: ['{a}はその場で膝から崩れ、口を押さえて吐いた。', '{a}は悲鳴も出せずに立ち尽くした。指先の震えが、いつまでも止まらなかった。', '{a}は「嘘でしょ｜嘘だろう｜嘘でしょう」と何度も繰り返しながら、後ずさりした。'],
    harsh: ['{a}は黙って遺体のそばに膝をつき、瞼をそっと閉じてやった。', '{a}は一度だけ目を閉じ、それから冷静に周りを見回した。', '{a}は「触るな、現場が崩れる｜＝｜触らないでください、現場が崩れます」と低く言った。'],
    killed: ['{a}は眉ひとつ動かさなかった。その落ち着きに、何人かが息を呑んだ。', '{a}は遺体を見下ろして、小さく言った。「……慣れたくなかったな｜……慣れたくなかった｜……慣れたくなかったです」', '{a}は、傷口の角度をじっと見ていた。まるで、自分ならどうするかを考えているように。']
  };
  /* 初めて手にかけたあと */
  K.AFTER_KILL = {
    peace: ['{a}は自分の手を見つめたまま、朝まで一睡もできなかった。', '{a}は何度も手を洗った。皮膚が赤く剥けても、洗うのをやめられなかった。', '{a}は部屋の隅で膝を抱え、震えながら誰かの名前を呼んでいた。'],
    harsh: ['{a}は長いあいだ、黙って空を見ていた。', '{a}は息を整えて、何もなかったような顔をつくった。手だけが、まだ冷たかった。'],
    killed: ['{a}の呼吸は、もう落ち着いていた。それが一番、自分でも怖かった。', '{a}は淡々と後始末をした。手際がよすぎた。']
  };

  /* 黒幕が配る動機の追加分（裁判デスゲームの MOTIVES に足す）。texts から一つ選んで告げる。fit(t) はその動機が刺さりやすい気質 */
  K.MOTIVES = [
    { id: 'hostage', label: '仲間の命', fit: function (t) { return t.np * 0.5 + t.warmth * 0.3 + 0.1; }, texts: [
      '「明日の夜までに事件が起きなければ、いちばん仲の良い二人のうち、片方を処刑します」という告知',
      '一人の宿泊客の部屋の扉だけが外から溶接され、「誰かが殺せば、開けてあげます」と書かれた札',
      '「次の朝食までに誰も死ななければ、皆様の中から一人を、こちらで選ばせていただきます」という放送'
    ] },
    { id: 'wish', label: '願いをひとつ', fit: function (t) { return t.fc * 0.4 + t.impulse * 0.3 + t.cold * 0.2; }, texts: [
      '「生きて帰った方の願いを、何でも一つ叶えます」という約束',
      '「卒業された方には、失ったものを一つだけお返しします」という手紙と、それぞれが一番取り戻したいものの写真',
      '「最後に残った方の借金も、罪も、過去も、すべて消して差し上げます」という契約書'
    ] },
    { id: 'past', label: '過去の罪', fit: function (t) { return t.jealous * 0.4 + t.caution * 0.3 + t.aggr * 0.2; }, texts: [
      '「この中の一人は、昔、別の誰かの人生を壊した」という告発文',
      '宿泊客の一人が過去に起こした事故の新聞記事と、被害者の名前の一覧',
      '「あなたの大切な人を傷つけた人が、このホテルに泊まっています」という、名前の伏せられた手紙'
    ] },
    { id: 'outside', label: '外の世界', fit: function (t) { return t.ac * 0.4 + t.caution * 0.3 + t.a * 0.2; }, texts: [
      '外の街が無人になり、通りに車が放置されたままの映像',
      '「皆様が閉じ込められてから、外ではもう一年が過ぎています」という告知と、日付の入った新聞',
      '自分の家が知らない人に住まれ、自分の名前が忘れられている映像'
    ] }
  ];
  /* 館内放送の追加分（裁判デスゲーム）。morning＝朝、quiet＝事件のなかった朝、verdict＝処刑のあと */
  K.BROADCAST = {
    morning: [
      '館内放送：「おはようございます。昨夜もぐっすり眠れた方は、少しは疑うことを覚えましょう」',
      '館内放送：「本日のレストランのおすすめは、ふわふわのオムレツです。最後の晩餐にならないといいですね」',
      '館内放送：「朝の体操の時間です。……誰も来ない？　そうですか。では、本日も殺し合いに励んでください」',
      'モニターに、宿泊客の顔写真が一枚ずつ映された。最後に「本日の主役は、あなたかもしれません」という文字が出た。'
    ],
    quiet: [
      'モニターの中の声は、わざとらしく欠伸をした。「皆様、仲良しごっこはそろそろ飽きませんか。明日はもっと、刺激的なものをご用意します」',
      '館内放送：「昨夜も、何も起きませんでした。残念です。とても、残念です」――放送はそこで切れたが、スピーカーの雑音だけがしばらく続いた。',
      '館内放送：「このままでは、ホテルの在庫が先に尽きてしまいますね。食料庫の鍵を、一つ閉めておきました」'
    ],
    verdict: [
      '館内放送：「処刑完了。皆様、引き続き快適なご滞在をお楽しみください」',
      '館内放送：「お見事でした。正しい投票に、拍手を」――拍手の音は、録音だった。',
      'モニターに「次の裁判も、お待ちしております」という文字が浮かび、すぐに消えた。',
      '館内放送：「クロは裁かれました。では、次のクロはどなたでしょう」'
    ]
  };
})();
