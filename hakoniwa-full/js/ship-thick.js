    if (HK.SAFE_ON || !HK.Voice || !TK.ok(t, u)) return null;
    var pk = function (arr) { return HK.Ero && HK.Ero.fresh ? HK.Ero.fresh(S, arr, function (l) { return S.rng.pick(l); }) : S.rng.pick(arr); };
