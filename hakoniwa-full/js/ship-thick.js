    var lw = (S.env && S.env.slewd) || 40, dp = lw < 35 ? 1 : lw < 70 ? 2 : 3;
    /* 女性が攻め・女性どうしでは、受ける側の「内側」「繋がったまま」を言う結びを使わない */
