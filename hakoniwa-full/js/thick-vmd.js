    gentle: [L('ん……っ、そこ、いい……|あ……っ、ゆっくり、ね……|ふふ……っ、上手……'), L('あ……っ、イく……っ、一緒に……|もう、だめ……溶けちゃう……|あ、あ……っ、もっと……')],
    devoted: [L('ご、ごめんなさい、声が……|もっと……ほしい……っ|う、嬉しい……っ'), L('イきます、イっちゃいます……っ|もう、だめです……っ|あ……っ、いっぱい……')],
    cool: [L('……っ、予想より……|呼吸が……落ち着か、ない……|……そこ、は……想定、外……'), L('考え、られない……っ|……っ、イく……|頭が、白く……っ')],
