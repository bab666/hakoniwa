    var A = HK.Attr, NL = LK.NIGHT_LIGHT;
    if (!S || !top || !bot || top === bot || HK.SAFE_ON || !A || !A.nightOf || !NL) return NONE;
    opt = opt || {};
    /* 受けが攻め指定の組（向きの決まらない組）には足さない */
    if (HK.Pos && HK.Pos.hardTop && HK.Pos.hardTop(bot, top)) return NONE;
    var nt = A.nightOf(top, bot), nb = A.nightOf(bot, top);
    /* マゾは攻めの文にしない。受けの表は maso・shy・sweet だけ */
