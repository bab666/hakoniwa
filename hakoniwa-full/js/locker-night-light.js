    var who = side === 'a' ? top : bot, night = side === 'a' ? nt : nb;
    var text = LK.pick(S, side === 'a' ? pt : pb).replace(/\{a\}/g, top.name).replace(/\{b\}/g, bot.name);
    if (Array.isArray(A.log)) A.log.push({ who: who.name, role: side, night: night, a: top.name, b: bot.name });
    return text ? { text: text, label: who.name + '＝' + nameOf(night) } : NONE;
