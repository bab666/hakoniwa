    if (nb === 'sadist' || nb === 'mean') nb = '';
    /* 攻めの文は手を使うので、動く側が手錠のときは足さない */
    var pt = nt && !top.bound && NL.top[nt] && NL.top[nt].length ? NL.top[nt] : null;
    var pb = nb && NL.bot[nb] && NL.bot[nb].length ? NL.bot[nb] : null;
    if (!pt && !pb) return NONE;
    /* 攻めの文と受けの文は、どちらか一つだけ */
