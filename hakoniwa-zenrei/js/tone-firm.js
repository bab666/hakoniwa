/* 箱庭シミュレーター: はっきりした口調の「拒み方・崩れ方」をそろえる
   台詞の表には、抵抗や喘ぎを柔らかい口ぶりで書いたもの（「いや……離して……」「見ないで」「やだぁ」「だめよ」）が多い。
   強気・兄貴分・厳格・冷静・意地っ張り（中性的）は「やめろ、離せ」「見るな」「くっ」に、
   のじゃは「離さぬか」「見るでない」「ならぬ」に、古風な紳士は「やめたまえ」「離したまえ」にそろえる。
   普段の「いや、違う」「待って、この床」のような言い方は、意味を変えずに口調だけ合わせる。
   書き下ろし（辞書）の台詞は通らない（voice.js が言い換えを飛ばす）ので、自動の言い換えだけに効く */
(function () {
  'use strict';
  var HK = window.HK, V = HK && HK.Voice;
  if (!V || !V.styleQuote) return;

  /* どの口調をどの言い換えにするかは tone-registry.js の firm（'plain' / 'noja' / 'gentleman'） */
  function firmOf(t) { return HK.toneOpt ? HK.toneOpt(t, 'firm') : null; }
  /* 区切り（文の切れ目・読点・言いよどみ） */
  var B = '(?=[…‥。！？!?、っッー〜～」♡\\s]|$)'; /* r18:ok */
  function R(s, f) { return new RegExp(s, f || 'g'); }

  /* [柔らかい形, 強気・冷静など, のじゃ, 紳士] */
  var VERBS = [
    ['力(?:を)?抜いて', '力を抜け', '力を抜くのじゃ', '力を抜きたまえ'],
    ['見ないで(?:くれ|ください|ちょうだい)?', '見るな', '見るでない', '見ないでくれたまえ'],
    ['離して(?:くれ|ください|ちょうだい)?', '離せ', '離さぬか', '離したまえ'],
    ['やめて(?:くれ|ください|ちょうだい)?', 'やめろ', 'やめよ', 'やめたまえ'],
    ['触らないで(?:くれ|ください)?', '触るな', '触るでない', '触れないでくれたまえ'],
    ['動かないで(?:くれ|ください)?', '動くな', '動くでない', '動かないでくれたまえ'],
    ['来ないで(?:くれ|ください)?', '来るな', '来るでない', '来ないでくれたまえ'],
    ['入れないで(?:くれ|ください)?', '入れるな', '入れるでない', '入れないでくれたまえ'],
    ['聞かないで(?:くれ|ください)?', '聞くな', '聞くでない', '聞かないでくれたまえ'],
    ['止めて(?:くれ|ください)?', '止めろ', '止めよ', '止めたまえ'],
    ['止まって(?:くれ|ください)?', '止まれ', '止まれ', '止まりたまえ'],
    ['いかないで(?:くれ|ください)?', '行くな', 'ゆくでない', '行かないでくれたまえ'],
    ['抜いて(?:くれ|ください)?', '抜け', '抜くのじゃ', '抜きたまえ'],
    ['待って(?:ちょうだい|ください|くれ)?', '待て', '待て', '待ちたまえ'],
    ['許して(?:ください|ちょうだい)?', '勘弁しろ', '許せ', '許してくれたまえ'],
    ['無理しないで(?:くれ|ください)?', '無理するな', '無理をするでない', '無理をしないでくれたまえ'],
    ['脱いで(?:くれ|ください)?', '脱げ', '脱ぐのじゃ', '脱ぎたまえ'],
    ['舐めて(?:くれ|ください)?', '舐めろ', '舐めよ', '舐めたまえ'],
    ['(見|触|動|イ)(?:っ|い)?ちゃ(?:だめ|ダメ)', null, null, null]
  ];
  var CHA = { '言': ['言うな', '言うでない', '言ってはいけない'], '見': ['見るな', '見るでない', '見てはいけない'], '触': ['触るな', '触るでない', '触れてはいけない'], '動': ['動くな', '動くでない', '動いてはいけない'] };
  /* r18:begin */
  CHA['イ'] = ['イくな', 'イくでない', '達してはいけない'];
  /* r18:end */

  function firm(q, kind) {
    var k = kind === 'noja' ? 2 : kind === 'gentleman' ? 3 : 1, s = q;
    /* 「待って待って」は二つともそろえる（片方だけ「待て」にしない） */
    s = s.replace(/待って待って/g, ['', '待て待て', '待て待て', '待ちたまえ、待ちたまえ'][k]);
    /* 荒い禁止「すんな」「逃げんな」「触んな」：荒い口調（強気・兄貴分・意地っ張り）以外は「するな」に戻し、のじゃは「〜るでない」、紳士は「〜るのはよしたまえ」 */
    if (!/^(proud|aniki|tsun_n|yankee)$/.test(V._firmTone || '')) {
      s = s.replace(/(?<![みそこあどけ])([一-龯げけべめれせてねえすつ])んな(よ)?(?=[。！!…‥、」]|$)/g, function (m, st) {
        return st + ['', 'るな', 'るでない', 'るのはよしたまえ'][k];
      });
    }
    /* 「見ないで、くれ」「離して、ください」のように読点で切れた頼み方を、ひと続きに戻してから言い換える */
    s = s.replace(/([てで])、(?:くれ|ください)(?![たさるな])/g, '$1');
    s = s.replace(/([てで])、くれたまえ/g, '$1くれたまえ');
    /* 「〜ちゃだめ」 */
    s = s.replace(/(見|触|動|イ|言)(?:っ|い)?ちゃ(?:だめ|ダメ)だから(?:ね|な)?/g, function (m, v) { return CHA[v] ? CHA[v][k - 1] + ['', 'よ', 'ぞ', 'よ'][k] : m; });
    s = s.replace(/(見|触|動|イ|言)(?:っ|い)?ちゃ(?:だめ|ダメ)[〜ー]*/g, function (m, v) { return CHA[v] ? CHA[v][k - 1] : m; });
    VERBS.forEach(function (row) {
      if (!row[1]) return;
      s = s.replace(R('(' + row[0] + ')' + B), row[k]);
    });
    /* させて（して）ほしい系：「入れさせて」→「入れさせろ」 */
    s = s.replace(R('させて' + B), ['', 'させろ', 'させよ', 'させてくれたまえ'][k]);
    s = s.replace(/ちょうだい/g, ['', 'くれ', 'くれ', 'くれたまえ'][k]);
    /* お願い（頼み） */
    s = s.replace(R('お願い(?!し|いた|致|申)' + B), '頼む');
    /* 「だめだって」（拒みの念押し）→「よせって」、「〜でしょ」→「〜だろ」 */
    s = s.replace(/(?:だめ|ダメ)、?だって/g, ['', 'よせって', 'ならぬと言うに', 'よしたまえと言っている'][k]);
    if (k === 1) s = s.replace(/でしょ(?=[…‥。！？!?、」]|$)/g, 'だろ');
    /* 柔らかい語尾：「言ってるの」→「言ってるんだ」、「あるよね」→「あるよな」（問いかけの「〜の？」はそのまま） */
    if (k === 1) s = s.replace(/(てる|ってる|ている|った|てた|ない|ちがう|違う)の(?=[。！!…‥」]|$)/g, '$1んだ').replace(/(?<![てで])よね(?=[？?。！!…‥」]|$)/g, 'よな');
    /* 泣き声の拒み：「やだぁ」「いやぁ」→ 歯を食いしばる声。「や、やだ」→「く、くそ」。「やだ」→「嫌だ」 */
    s = s.replace(/(^|[、…‥「\s])や、やだ、(?:やだ|いや)ぁ*/g, '$1' + ['', 'い、嫌だ、嫌だ', 'い、嫌じゃ、嫌じゃ', 'よ、よしたまえ、よしたまえ'][k]);
    s = s.replace(/(?:やだぁ+|いやぁ+|やぁ+)/g, 'くっ');
    s = s.replace(/(^|[、…‥「\s])や、やだ/g, '$1' + ['', 'く、くそ', 'く、くっ', 'く、くっ'][k]);
    s = s.replace(R('(^|[、…‥「\\s])(?:やだ|いやっ)' + B), '$1' + ['', '嫌だ', '嫌じゃ', 'ごめんだね'][k]);
    /* 拒みの「いや……」（後ろに言いよどみが続くもの）。「いや、違う」「四…いや、六」は変えない */
    s = s.replace(/(^|[、…‥「\s])いや(?=[…‥]+(?:っ|離|やめ|だめ|見|そこ|待|触|もう|お願い|頼))/g, '$1' + ['', 'よせ', 'よさぬか', 'よしたまえ'][k]);
    /* 「だめ」の拒み（「だめだ」は残す） */
    s = s.replace(/まだ(?:だめ|ダメ)[〜ー]*/g, ['', 'まだだ', 'まだじゃ', 'まだだよ'][k]);
    s = s.replace(/そこ、(?:だめ|ダメ)(?!だ)/g, ['', 'そこは、よせ', 'そこは、ならぬ', 'そこは、いけない'][k]);
    s = s.replace(R('(^|[、…‥「\\s])(?:だめ|ダメ)(?!、?(?:だ|じゃ|です))' + B), '$1' + ['', 'だめだ', 'ならぬ', 'いけない'][k]);
    /* 女性的な語尾（のじゃの「〜わ」は古風な言い回しなので残す） */
    s = s.replace(/、よ(?=[…‥。！？!?」]|$)/g, '');
    s = s.replace(/だけよ(?=[…‥。！？!?」]|$)/g, ['', 'だけだ', 'だけじゃ', 'だけだよ'][k]);
    s = s.replace(/のよ(?=[…‥。！？!?、」]|$)/g, ['', 'んだ', 'のじゃ', 'のだよ'][k]);
    s = s.replace(/かしら(?=[…‥。！？!?、」]|$)/g, ['', 'か', 'かのう', 'かね'][k]);
    s = s.replace(/わね(?=[…‥。！？!?、」]|$)/g, ['', 'な', 'のう', 'ね'][k]);
    s = s.replace(/わよ(?=[…‥。！？!?、」]|$)/g, ['', 'ぞ', 'ぞ', 'よ'][k]);
    if (k !== 2) s = s.replace(/(た|る|い|ない)わ(?=[…‥。！？!?」]|$)/g, k === 3 ? '$1よ' : '$1');
    /* 「あら」（女性的な驚き） */
    s = s.replace(/(^|[、…‥「\s])あ、あら(?=[…‥、っ!！])/g, '$1' + ['', 'く、くっ', 'む、むう', 'お、おや'][k]);
    s = s.replace(/(^|[、…‥「\s])あら(?=[…‥、っ!！])/g, '$1' + ['', 'くっ', 'むう', 'おや'][k]);
    /* 甘えた語尾：「止まってよぉ」→「止まれ」、「〜てよ」→「〜てくれ」、「〜なんだから」→「〜なんだからな」 */
    s = s.replace(/([てで])よぉ+(?=[…‥。！？!?、」]|$)/g, '$1よ');
    VERBS.forEach(function (row) { if (row[1]) s = s.replace(R('(' + row[0] + ')よ' + B), row[k]); });
    if (k === 1) s = s.replace(/(?<!なん|何|どう|なに)([てで])よ(?=[…‥。！？!?、」]|$)/g, '$1くれ').replace(/んだから(?=[…‥。！？!?、」]|$)/g, 'んだからな')
      .replace(/(だ|ない)もん(?=[…‥。！？!?、」っ]|$)/g, '$1').replace(/([てし])なさいよ?(?=[…‥。！？!?、」]|$)/g, function (m, c) { return c === 'し' ? 'しろよ' : 'てろよ'; }).replace(/(ばか|やだ|だめ|もう)ぁ+(?=[…‥。！？!?、」っ]|$)/g, '$1');
    /* ねだる繰り返し（「話して。して。お願い」）、「〜て」で終わる頼み、どもった「み、ないで」 */
    if (k === 1) {
      s = s.replace(/話して。して。(?:お願い|頼む)/g, '話をしてくれ。……退屈だ');
      s = s.replace(/(聞かせ|教え|見せ|頼ん|話し|手伝っ|待っ|来)て(?=[。！!…‥」]|$)/g, '$1てくれ');
      s = s.replace(/み、ないで/g, 'み、見るな');
    }
    /* 謝り・戸惑いの崩れ */
    s = s.replace(/ごめ、なさ/g, ['', 'す、すま', 'す、すま', 'す、すま'][k]);
    if (k !== 2) s = s.replace(/ご、ごめんなさ(?!い)/g, 'す、すまな').replace(/ご、ごめんなさい/g, 'す、すまない').replace(/ごめんなさい(?=[…‥。！？!?、っ」]|$)/g, 'すまない').replace(/ごめんなさ(?!い)/g, 'すまな');
    if (k === 2) s = s.replace(/ご、ごめんなさ(?!い)/g, 'す、すま').replace(/ご、(?:ごめん(?:ね|なさい)?|すまぬ)/g, 'す、すまぬ').replace(/ごめんなさ(?!い)/g, 'すま');
    /* 子どもっぽい「〜んだもん」、途中で切れた「〜んだも」 */
    s = s.replace(R('んだもん?' + B), ['', 'んだ', 'のじゃ', 'のだよ'][k]);
    s = s.replace(/お願いできる/g, '頼める').replace(/逃がする/g, '逃がす');
    if (k === 2) {
      s = s.replace(/ごめん(?:ね|なさい)?(?=[…‥。！？!?、っ」]|$)/g, 'すまぬ').replace(/わかんない|分かんない|わからない/g, 'わからぬ')
        .replace(/どうしよう(?=[…‥。！？!?、っ」]|$)/g, 'どうしたものか').replace(/無理無理無理/g, '無理じゃ、無理じゃ').replace(/だいじょ、ぶ/g, 'だい、じょうぶ、じゃ');
    }
    /* 整形で崩れた「こんなんだ……で」、丁寧すぎる「よろしくお願いするな」 */
    s = s.replace(/([こそあ])んなんだ(?=[…‥])/g, '$1んな');
    /* 言い換えた命令形のあとに、整形が足した「だ」（「見るなだ」）を外す */
    s = s.replace(R('(見るな|離せ|やめろ|触るな|動くな|来るな|入れるな|待て|止まれ|止めろ|抜け|見るでない|離さぬか|やめよ)だ' + B), '$1');
    /* 紳士の整形で崩れる言いよどみ（「整わ、ない……ね……」→「整わ、な……」） */
    if (k === 3) s = s.replace(/ない……ね(?=[…‥])/g, 'な');
    if (k === 1) s = s.replace(/よろしくお願いする[ねな]?(?=[…‥。！？!?、」]|$)/g, 'よろしく頼む');
    /* 紳士の命令形（「聞かせろ」「受け止めろ」→「〜たまえ」） */
    if (k === 3) s = s.replace(R('([えけげせてねべめれ])ろ' + B), '$1たまえ').replace(R('しろ' + B), 'したまえ');
    /* 「〜ちゃう」：厳格・冷静・紳士は「〜てしまう」、強気・兄貴分などは「〜ちまう」 */
    var rough = kind === 'plain' && /^(proud|aniki|tsun_n)$/.test(V._firmTone || '');
    s = s.replace(R('([っ])ちゃう' + B), rough ? '$1ちまう' : '$1てしまう').replace(R('([^っ])ちゃう' + B), rough ? '$1ちまう' : '$1てしまう');
    /* ♡（はっきりした口調では使わない。描写の作風「男性向け」の結果だけは残す） */
    if (!V._keepHeart) s = s.replace(/[♡♥]/g, '');
    /* 紳士の「やめたまえってば」→「やめたまえと言っている」 */
    if (k === 3) s = s.replace(/たまえってば/g, 'たまえと言っている');
    /* 甘えた伸ばし（「これぇ」「なにこれぇ」） */
    s = s.replace(/なに、これぇ/g, ['', 'なんだ、これ', '何じゃ、これは', '何だね、これは'][k]);
    s = s.replace(/([ぁ-んァ-ヶ])ぇ+(?=[…‥！!っ」]|$)/g, '$1');
    return s;
  }
  V.firmQuote = function (q, who) {
    var t = who && (HK.toneOf ? HK.toneOf(who) : who.tone);
    V._firmTone = t;
    var k = firmOf(t);
    return k ? firm(q, k) : q;
  };
  /* 書き下ろし辞書の台詞（のじゃ・紳士など）にも、拒み方だけは同じ言い換えをかける */
  var of0 = V.overrideFor;
  if (of0) V.overrideFor = function (q, who) { var r = of0.apply(this, arguments); return r == null ? r : V.firmQuote(r, who); };
  var sq0 = V.styleQuote;
  V.styleQuote = function (q, who) {
    var t = who && (HK.toneOf ? HK.toneOf(who) : who.tone);
    if (t === 'gentle_n') q = q.replace(/いいの、よ/g, 'いいんだ').replace(/大丈夫よ(?=[…‥。！？!?、」]|$)/g, '大丈夫だよ').replace(/、よ(?=[…‥。！？!?」]|$)/g, '').replace(/(^|[、…‥「\s])まあ、/g, '$1ああ、');
    /* 口調ごとの整形が「ください」「ちょうだい」を先にいじって崩さないよう、はっきりした口調では先に外しておく */
    if (firmOf(t)) q = q.replace(/([てで])、?(?:くださいませ|ください|ちょうだい)(?![たさ])/g, '$1').replace(/([てで])、くれ(?![たさるれ])/g, '$1');
    var out = V.firmQuote(sq0.call(this, q, who), who);
    /* 全口調の後始末：言い換えで重なった読点、敬語の口調で残った「して。」 */
    out = out.replace(/、{2,}/g, '、').replace(/、([…‥])/g, '$1');
    if (t === 'gentle_n') out = out.replace(/いいの、よ/g, 'いいんだ').replace(/大丈夫よ(?=[…‥。！？!?、」]|$)/g, '大丈夫だよ').replace(/、よ(?=[…‥。！？!?」]|$)/g, '');
    /* けだるげ：「あら」「〜です」「お願いする」が残らないように */
    if (t === 'darui') out = out.replace(/(^|[、…‥\s])あら(?=[…‥、])/g, '$1あ').replace(/よろしくお願いする(?=[…‥。！？!?」]|$)/g, 'よろしく').replace(/([いきし])、?です(?=[…‥。！？!?、っ」]|$)/g, '$1');
    if (/^(devoted|polite)$/.test(t)) out = out.replace(/ください。して。お願いです/g, 'ください。……お願いします');
    return out;
  };
})();
