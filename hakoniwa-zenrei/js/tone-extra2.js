/* 箱庭シミュレーター: 口調「のじゃ」「敬語まじりのため口」「無口」
   口調は台詞の話し方を決めるだけで、行動はエゴグラムの数値で決まる（文面の表もエゴグラムからいちばん合う口調のものを使い、話し方だけを整える）
   ・のじゃ … 「〜なのじゃ」「〜じゃろう」「〜ぞ」「〜ておる」「〜ぬ」「おぬし」。一人称は わし／わらわ
   ・敬語まじりのため口 … 一つの台詞の中でも、敬語の文とため口の文が混ざる（「そうなんですね。でもさ、それ変じゃない？」）
   ・無口 … ほとんど「……」。話しても、ひと言だけ */
(function () {
  'use strict';
  var HK = window.HK, V = HK.Voice, EX = HK.TONE_EXTRA;
  if (!V || !EX) return;
  var E = '(?=[。！？!?…、」]|$)';
  function re(s, f) { return new RegExp(s + E, f || 'g'); }
  function hash(s) { var h = 7; for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 100003; return h; }
  function casual(q) { return V.casualQuote && /(です|ます|ください|ません|でした|ました|ございます|でしょう|ましょう)/.test(q) ? V.casualQuote(q) : q; }
  var YOU = /(?:あなた|あんた|お前|おまえ|てめえ|貴様)(?!さん|方)|(?:きみ|(?<![大姫主父母諸細若暴])君)(?=(?:は|が|も|の|を|に|と|で|って|、|。|！|？|…|」|$|さ|ね|よ|なら|だけ|たち|ら|だ|じゃ|か|な|から|へ|や|しか|まで|より|一人|自身))/g;

  /* ---------- のじゃ ---------- */
  var NOJA = [
    [/じゃないか/g, 'ではないか'], [/じゃない(?=[かの]?[？?])/g, 'ではないか'], [re('じゃない'), 'ではない'], [re('じゃん'), 'じゃろう'],
    [re('(?:だろう|だろ|でしょう|でしょ)'), 'じゃろう'], [re('(?:だよね|だよな)'), 'じゃよな'], [re('だよ'), 'じゃよ'], [re('(?:だね|だな)'), 'じゃな'],
    [/なの(?=[？?])/g, 'なのか'], [re('(?:のだ|んだ)'), 'のじゃ'], [re('(?:なのよ|なの)(?!じゃ)'), 'なのじゃ'], [re('(?:のよ|わよ)'), 'のじゃ'], [re('だわ'), 'じゃ'], [re('(?:かしら|かな)'), 'かのう'],
    [/ている(?=[。！？!?…、」のんか]|$)/g, 'ておる'], [/てる(?=[。！？!?…、」のんかよね]|$)/g, 'ておる'], [/ていた(?=[。！？!?…、」のんか]|$)/g, 'ておった'], [/てた(?=[。！？!?…、」のんか]|$)/g, 'ておった'],
    [/(ここ|そこ|あそこ|に|が)いる(?=[。！？!?…、」よのか]|$)/g, '$1おる'], [/(に|が)いた(?=[。！？!?…、」よのか]|$)/g, '$1おった'],
    /* 打ち消しの「ない」→「ぬ」（動詞のあとだけ） */
    [/しないで(?=[。！!…」]|$)/g, 'するでない'], [/しない(?=！)/g, 'するでない'], [/しない(?=[。!…、」よのかぞ]|$)/g, 'せぬ'], [/しない(?=[？?])/g, 'せぬか'],
    [/(知ら|分から|わから|でき|いら|行か|言わ|させ|許さ|逃がさ|負け|見え|聞こえ|止まら|帰れ|動け|出られ|眠れ|足り|かまわ|構わ|変わら|もた|させら|信じられ|やら|せ|来|し)ない(?=[。！!…、」よのかぞ]|$)/g, '$1ぬ'], [/(知ら|分から|わから|でき|いら|行か|言わ|見え|聞こえ|帰れ|動け|眠れ|足り|変わら|やら|来|し)ない(?=[？?])/g, '$1ぬか'],
    [/([るうくすつむぐぶ])(?=[？?])/g, '$1かの'],
    [/(で|が|も|は)いい(?=[。！？!?…、」よの]|$)/g, '$1よい'], [/^いい(?=[。！？!?…、」よの]|$)/, 'よい'],
    [/じゃないの(?:か)?(?=[？?。！…」]|$)/g, 'ではないか'], /* 相手以外への願い（「誰かに届いてほしい」「雨が止んでほしい」）は、お願いの「たもれ」にしない */
    [/((?:誰か|どこか|皆|みんな|みな|神様?|空|星)に[^、。「」]*?|[^、。「」]{1,8}が[^、。「」]*?)((?:[っいしきえけせべめれちみりびねげじ]て|[んい]で)ほしい)(?=[。」]|$)/g, '$1$2のう'], [/(?<![るうただいよねなさ])([っいしきえけせべめれちみりびねげじ]て|[んい]で)(?:くれ|ください|ちょうだい|ほしい)?(?=[。」]|$)/g, '$1たもれ'], [/(て|で)くれ(?=、)/g, '$1たもれ'], [/てろ(?:よ)?(?=[。！？!?…、」]|$)/g, 'ておれ'], [/てなさい(?:よ)?(?=[。！？!?…、」]|$)/g, 'ておれ'], [/なさいよ(?=[。！？!?…、」]|$)/g, 'なされ'], [/とけ(?:よ)?(?=[。！？!?…、」]|$)/g, 'ておけ'], [/^(?:ねえ|ねぇ)、/, 'のう、'], [/(?<=[ぁ-ん一-鿿ァ-ヶ])(?:わね|わねえ|ねえ)(?=[。！？!?…、」]|$)/g, 'のう'], [/てない(?=[？?])/g, 'ておらぬか'], [/([いえけげせてねべめれ])ろ(?=[！!。…」]|$)/g, '$1よ'], [/言っとく/g, '言うておく'], [/とく(?=[。！…」]|$)/g, 'ておく'], [/ようね(?=[。！？!?…、」]|$)/g, 'ようぞ'], [/([たい])な(?=[。！？!?…、」]|$)/g, '$1のう'],
    [/([るうくすつむぬぐぶたいい])よ(?=[。！？!?…、」]|$)/g, '$1ぞ'], [/([るうくすつむぬぐぶたい])(?:よね|ね)(?=[。！？!?…、」]|$)/g, '$1のう'],
    [/([るうくすつむぐぶた])の(?=[？?])/g, '$1のか'], [re('です'), 'じゃ'], [re('ですね'), 'じゃな'], [re('(?:失礼しました|失礼します)'), '失礼した']
  ];
  function noja(q) {
    q = casual(q.replace(/ありがとう、?ございま(?:す|した)/g, 'ありがとう'));
    q = HK.thinIntj(q, { 'あらあら': 'ほほう', 'あらまあ': 'なんと', 'あら': 'おや' }).replace(YOU, 'おぬし').replace(/本当に/g, 'まことに').replace(/本当/g, 'まこと').replace(/すごく|とても/g, 'たいそう');
    q = q.replace(/^(?:ありがとう|ありがと)(?=[。！…]|$)/, '礼を言うぞ').replace(/(?:ごめんなさい|ごめん|すみません|すまない)(?=[。！…、」]|$)/g, 'すまぬ');
    NOJA.forEach(function (r) { q = q.replace(r[0], r[1]); });
    /* 言い切りの「だ」→「じゃ」（まだ・ただ などは除く） */
    q = q.replace(/([^まただ])だ(?=[。！？!?…」]|$)/g, '$1じゃ');
    return q.replace(/じゃじゃ/g, 'じゃ').replace(/のじゃのじゃ/g, 'のじゃ').replace(/([！？!?])。/g, '$1');
  }

  /* ---------- 敬語まじりのため口 ---------- */
  function mixed(q) {
    var parts = q.split(/(?<=[。！？!?])(?![。！？!?」])/).filter(function (x) { return x; });
    var start = hash(q) % 2;
    if (parts.length === 1) {
      /* 一文だけのときは、読点の前と後で言い方を変えることも */
      var m = q.match(/^(.{3,}?[^、…])、(.{3,})$/);
      /* 区切るのは、前半が言い切りで終わるときだけ（「〜て、」「〜の、」で切ると「話してくれてください、」のように崩れる） */
      var cut = m && /(?:[いたよねなかうるす]|だ|ない)$/.test(m[1]) && !/(?:って|って|んない|の)$/.test(m[1]) && !/[、]/.test(m[1].replace(/^[^、]*、/, '').slice(-3)) && !/^(?:から|って|ください|くれ|ちょうだい|る|んだ|ね|よ)/.test(m[2]);
      if (cut && hash(q) % 3 === 0) return V.polite(m[1]) + '、' + casual(m[2]);
      return hash(q) % 5 < 3 ? V.polite(q) : casual(q);
    }
    /* 文が二つ以上あるとき：短い反応や独り言（「ありがとう」「大丈夫」「〜かな」）はため口、説明や頼みごとは敬語
       （「ありがとう。ほんとに助かりました」「大丈夫。なんとかなります」） */
    return parts.map(function (s, i) {
      var core = s.replace(/[。！？!?…‥、\s]+$/, '').replace(/^[…‥、\s]+/, '');
      var short = core.length <= 6 || /^(?:ありがと(?:う|うございます)?|よろしく(?:ね|お願いします)?|大丈夫(?:です)?|平気(?:です)?|ごめん(?:なさい)?|すみません|了解(?:です)?|うん|はい|ほんと(?:に)?|まあ|へえ|えっ?|あ、?あの|なるほど)$/.test(core);
      var self = /(?:かな|かも|よな|なあ|かなあ|だろうな)$/.test(core);
      /* 頼みごと（「離してください」「来て」）は短くても敬語のまま（ため口にすると「離せ」「来い」と命令になる） */
      var ask = /(?:ください|下さい|ちょうだい|くれ|[てで]|[てで]ね|ませんか|ますか|しろ|来い|[^いきしちにひみりぎじびぴ]ろ|[けせてねめれえ])$/.test(core);
      return (short || self) && !ask ? casual(s) : V.polite(s);
    }).join('');
  }

  /* ---------- 無口 ---------- */
  function mukuchi(q) {
    /* 喘ぎや短い声（ひらがなと記号だけ）は、そのまま */
    if (q.length <= 12 && /^[…‥っ、。ぁ-んー！？!?\s（）]+$/.test(q) && /[…‥っぁぃぅぇぉ]/.test(q)) return q;
    if (/^[…‥]{2,}/.test(q) && q.length <= 14) return q;
    q = casual(q);
    var core = q.replace(/^[…‥・\s、。]+/, '');
    if (!core) return '……';
    var END = /(?:わね|わよ|のよね|んだよね|んだよな|んだよ|んだね|んだな|なんだ|んだ|のよね|のよ|のね|よね|よな|だよ|だね|だな|よ|ね|さ|ぞ|ぜ|わ)$/;
    var LEAD = /^(?:あらあら|あら|まあまあ|ふふ|えへへ|おーっと|あなた|お前|おまえ|きみ|君|あんた|ねえ|おい|あの|その|えっと|うん|ああ|ええ|はい|いや|よかったら|でも|だって|じゃあ|それで|それに|ほら)$/;
    function trim(c) {
      c = c.replace(/[。！？!?…‥っッぁ〜」]+$/, '').replace(/([ぁ-ゖ])ー+$/, '$1').replace(/[。！？!?…‥っッぁ〜」]+$/, '').replace(/^[…‥\s]+/, '').replace(/^(?:だから|でも|じゃあ|それで|それに|さあ|まあ|ほら)(?=.)/, '').replace(END, '').replace(/([^るうかくすつぬむぶぐ])な$/, '$1');
      /* 長いときは、助詞のところで前を落として述語のほうを残す */
      for (var k = 1; c.length > 12 && k < c.length - 1; k++) if (/[はがもをにで]/.test(c.charAt(k - 1)) && /[一-鿿ァ-ヶー]/.test(c.charAt(k - 2)) && !/[のをにがはでともか]/.test(c.charAt(k)) && !/^(?:しょ|す|し|した|ない|も)/.test(c.slice(k)) && c.length - k >= 3 && c.length - k <= 12) { c = c.slice(k); break; }
      return c;
    }
    /* 文と読点で区切ったかたまりから、2〜12字のものを一つ選ぶ（最後の文の後ろのかたまり＝結論・述語を優先。「分かってる。でも、好きだ」→「……好き」） */
    var sens = core.split(/(?<=[。！？!?])/).filter(function (x) { return x.trim(); }), pick = null, ask = false, ex = false;
    /* ただし最初の文が命令・禁止・数値なら、そちらを先に（「跪け。話はそれからだ」→「……跪け」） */
    var firstFirst = sens.length > 1 && /([ろれけせえ]|[うくすつぬむぶぐる]な|[0-9０-９]|ml)[。！!]?$/.test(sens[0].replace(/[…‥っ]+$/, ''));
    for (var sj = 0; sj < sens.length && !pick; sj++) {
      var si = firstFirst ? sj : sens.length - 1 - sj;
      var cl = sens[si].split('、').filter(function (c) { return !LEAD.test(c.replace(/[…‥\s]/g, '')); });
      for (var ci = cl.length - 1; ci >= 0; ci--) { var t = trim(cl[ci]); if (t.length >= 2 && t.length <= 12) { pick = t; ask = /[？?]/.test(sens[si]); ex = /[！!]/.test(sens[si]); break; } }
    }
    var h = hash(q) % 100;
    /* 選べるかたまりがないときも、短い文ならそのまま言う（中身を「……」で消さない） */
    if (!pick && sens.length) { var ls = sens[sens.length - 1].replace(/^[…‥\s、]+/, '').replace(/[。！？!?…‥っ]+$/, ''); if (ls.length >= 2 && ls.length <= 20) { pick = ls.replace(END, ''); ask = /[？?]/.test(sens[sens.length - 1]); } }
    if (!pick) { ask = /[？?]/.test(sens[0] || core); ex = /[！!]/.test(sens[0] || core); return ask ? '……？' : ex && h % 2 ? '……っ' : '……'; }
    return '……' + pick + (ask ? '？' : '');
  }

  /* 敬語まじりのため口のため口側は、「〜てくれ」より「〜て」のほうが合う */
  var mixed0 = mixed;
  mixed = function (q) {
    return mixed0(q).replace(/([てで])くれ(?=[…‥。！!？?」]|$)/g, '$1')
      /* 厳格寄りの硬い形を敬語にしたときの崩れ（「何してるのです？」「怒ってるではないですか」） */
      .replace(/のです(?=[？?])/g, 'んですか').replace(/ではないです(?=か|[。！？!?…」]|$)/g, 'じゃないです');
  };
  var CONV = { noja: noja, mixed: mixed, mukuchi: mukuchi };
  V.toneConv2 = CONV;
  var sq0 = V.styleQuote;
  V.styleQuote = function (q, who) {
    if (!who || !CONV[who.tone]) return sq0(q, who);
    /* 「見ないで、ください」の読点は先に詰める（口調の整形で「、くれ」だけ残らないように） */
    if (who.tone === 'mixed') q = q.replace(/([てで])、(?=ください|ちょうだい)/g, '$1');
    q = sq0(q, who);
    return CONV[who.tone](q, who).replace(/([！？!?])。/g, '$1');
  };
})();
