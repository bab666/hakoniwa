/* 箱庭シミュレーター: 口調「厳格」の仕上げ
   厳格は、文面の表の台詞を言い換えて話すが、くだけた言い回しが残りやすい。最後にここで整える（HK.toneFinish）。
   ・い抜き言葉を戻す：「見てない」→「見ていない」、「知ってた」→「知っていた」、「待ってて」→「待っていて」、「持ってく」→「持っていく」
     （捨てる・育てる・待てる・撫でる のように、て・で が動詞そのものの一部のときは触らない）
   ・くだけた縮め方を戻す：「しとく」→「しておく」、「言っちゃった」→「言ってしまった」、「飲んじゃう」→「飲んでしまう」
   ・無邪気な言い回しを外す：「わあ」「ねえねえ」「あはは」「えへへ」「わーい」は外し、「すごい！」「すげえ」は「見事だ」、「やったー！」は「よし！」、
     「〜だもん」は「〜のだ」、「〜じゃん」は言い切り、語尾の「〜」は外す
   ・「〜のではないか」「〜ではないか」は言わず、言い切る（「早いのではないか」→「早い」）
   ・喘ぎ・息の乱れた台詞（「っ……」「ぁ」「♡」など）は、無邪気な言い回しを外さない（崩れているのが自然なので）
   書き下ろし（tone-fix.js などの厳格の行）は、ここを通らずにそのまま使われる（voice.js） */
(function () {
  'use strict';
  var HK = window.HK;
  if (!HK || !HK.toneFinish) return;

  /* 「てく」（ていく）のあと。「てください」「てくれ」「てくる」を避けるため、だ・れ・る などは入れない */
  var AFTER_KU = /^(?:$|[。、！？!?…‥」』）\s　]|よ|ね|ぞ|から|けど|の|ん|か)/;
  /* て の前がこれなら、て は動詞の一部（捨てる・育てる・待てる・勝てる…）か形容詞（嬉しくて）なので、い抜きではない */
  var NOT_TE = /(?:捨|育|建|立|当|慌|果|企|隔|充|宛|待|持|勝|打|放|保|経|撃|満|見捨|役立|腹立|そだ|く|なん|と|(?:^|[^ぁ-ゖ])[すあ])$/;
  /* で の前がこれのときだけ、て形の「で」（飲んで・泳いで）とみなす */
  var TE_DE = /[んい]$/;
  var IN = [
    ['なかった', 'いなかった'], ['なくて', 'いなくて'], ['なく', 'いなく'], ['ない', 'いない'],
    ['ました', 'いました'], ['ません', 'いません'], ['ます', 'います'],
    ['んの', 'いるの'], ['んだ', 'いるんだ'], ['んじゃ', 'いるんじゃ'],
    ['る', 'いる'], ['た', 'いた'], ['て', 'いて'], ['られ', 'いられ'], ['く', 'いく']
  ];
  var RESTS = IN.map(function (x) { return x[0]; }).sort(function (x, y) { return y.length - x.length; });
  var IN_MAP = {}; IN.forEach(function (x) { IN_MAP[x[0]] = x[1]; });
  /* 前から一字ずつ見る（「育ててる」のように、動詞の一部の て の直後に、い抜きの て が来ることがあるため） */
  function inuki(q) {
    var out = '', i = 0;
    while (i < q.length) {
      var te = q.charAt(i);
      if (te === 'て' || te === 'で') {
        var pre = q.slice(Math.max(0, i - 3), i);
        var ok = te === 'て' ? !NOT_TE.test(pre) && pre !== '' : TE_DE.test(pre);
        if (ok) {
          for (var r = 0; r < RESTS.length; r++) {
            var rest = RESTS[r];
            if (q.substr(i + 1, rest.length) !== rest) continue;
            var after = q.slice(i + 1 + rest.length);
            /* 「てく」（ていく）は、後ろが語の切れ目のときだけ（「てください」「てくれ」「てくる」を避ける） */
            if (rest === 'く' && !AFTER_KU.test(after)) continue;
            out += te + IN_MAP[rest]; i += 1 + rest.length; ok = 'done'; break;
          }
          if (ok === 'done') continue;
        }
      }
      out += te; i++;
    }
    return out;
  }
  function shrink(q) {
    return q
      .replace(/([しっい])と(く|こう|いて|け)(?=[。、！？!?…‥」\s　]|$|よ|ね|な|ぞ|か|から|けど)/g, function (m, p, e) { return p + 'てお' + { く: 'く', こう: 'こう', いて: 'いて', け: 'け' }[e]; })
      .replace(/んど(く|こう|いて|け)(?=[。、！？!?…‥」\s　]|$|よ|ね|な|ぞ|か|から|けど)/g, function (m, e) { return 'んでお' + e; })
      .replace(/([^め])ちゃ(う|った|って|え|いそう)/g, function (m, p, e) { return p + 'てしま' + e; })
      .replace(/んじゃ(う|った|え|いそう)/g, function (m, e) { return 'んでしま' + e; });
  }
  var MOAN = /[っッ][…‥、]|[ぁぃぅぇぉ]|♡|ん[…‥]/;
  function sober(q) {
    if (MOAN.test(q)) return q;
    var o = q
      .replace(/(^|[、。！？!?…‥\s　])(?:ねえねえ|ねぇねぇ|わーい|いえーい|えへへ?|あはは|あはっ|うわぁ|うわー|わぁ|わあ)[、！!…‥ー〜～]*/g, '$1')
      .replace(/(^|[。！？!?\s　])すごい、/g, '$1ほう、')
      .replace(/すっごく|すっごい/g, '実に')
      .replace(/(まあ|ま、)?いっか(?=[！!。…‥]|$)/g, function (m, a) { return (a ? 'まあ' : '') + 'いい'; })
      .replace(/すげ[えー]+/g, '見事だ')
      .replace(/すごい(?=[ねなよ]?(?:[。！？!?…‥」\s　]|$))/g, '見事だ')
      .replace(/見事だ([ねよ])(?=[。！？!?…‥]|$)/g, '見事だな')
      .replace(/(^|[、。！？!?\s　])やった[ーぁあ〜～]+[！!]*|(^|[。！？!?\s　])やった[！!]+/g, function (m, a, b) { return (a || b || '') + 'よし！'; })
      .replace(/だもん(?:ね)?(?=[。！？!?…‥]|$)/g, 'なのだ').replace(/もん(?:ね)?(?=[。！？!?…‥]|$)/g, 'のだ')
.replace(/じゃん(?=[。！？!?…‥]|$)/g, 'ではないか')
      .replace(/([ねよな])[ー〜～]+(?=[。！？!?…‥]|$)/g, '$1')
      .replace(/[〜～]+(?=[。！？!?…‥]|$)/g, '');
    /* 外したあとに残った先頭・文頭の「、」だけを落とす（「！　」の全角空きはそのまま） */
    if (o !== q) o = o.replace(/^[、\s　]+/, '').replace(/([。！？!?][\s　]*)、+/g, '$1');
    return o.replace(/[。、！？!?…‥\s　]/g, '') ? o : q;
  }
  /* やわらかい語尾を、厳格らしく言い切る（あなたが直した厳格の書き下ろしにそろえる：「逃げるなよ」→「逃げるな」、「見てないよね」→「見ていないよな」） */
  var E = '(?=[。！!？?…‥」]|$)';
  function R(s) { return new RegExp(s, 'g'); }
  function firm(q) {
    return q
      .replace(/([^っ])ちゃ(だめ|ダメ|いけない)/g, '$1ては$2').replace(/っちゃ(だめ|ダメ|いけない)/g, 'っては$1').replace(/んじゃ(だめ|ダメ|いけない)/g, 'んでは$1')
      .replace(R('(だめ|ダメ)よ' + E), '$1だ')
      .replace(R('([^ゃゅょぁぃぅぇぉ])のよ' + E), '$1のだ')
      .replace(R('わよ' + E), '').replace(R('わね' + E), 'な')
      /* 「〜てね」「〜でね」（頼み）→「〜てくれ」。「〜って聞いてね」（聞いた話）は除く */
      .replace(R('(て|で)ね' + E), function (m, te, at, all) {
        var pre = all.slice(0, at);
        if (/って(?:聞|き)い?$|と(?:聞|き)い?$/.test(pre)) return m;
        /* て形のときだけ（「楽しみでね」の「で」は助詞） */
        if (te === 'て' ? NOT_TE.test(pre) || !pre : !TE_DE.test(pre)) return m;
        return te + 'くれ';
      })
      .replace(R('よね(?=[、。！!？?…‥」]|$)'), 'よな')
      /* 命令のあとの「よ」は外す（「決めつけるなよ」「いい加減にしろよ」「借りは返せよ」） */
      .replace(R('(る|く|す|つ|ぬ|む|ぶ|う)なよ' + E), '$1な')
      .replace(R('(しろ|しろっ|ろ|れ|せ|け|え|め|て|べ)よ(?=[。！!…‥」]|$)'), function (m, p) { return p === 'て' ? 'てくれ' : p; })
      .replace(R('なあ' + E), 'な');
  }
  /* 「〜のではないか」「〜ではないか」は言わない。言い切る（「早いのではないか」→「早い」、「手が冷たいではないか」→「手が冷たい」、
     名詞のあとは「〜だ」：「狼の動きではないか？」→「狼の動きだ」） */
  function plain(q) {
    return q.replace(/(な)?の?ではないか(?:[？?])?(?=[。！!…‥」]|$)|(な)?の?ではないか(?=[、])/g, function (m, na, na2, at, all) {
      var pre = all.slice(0, at), noun = na || na2;
      if (noun) return 'だ';
      if (/のではないか/.test(m)) return '';
      /* 動詞・形容詞の終わり（る・た・い・う…）ならそのまま、名詞のあとなら「だ」 */
      return /[るたいうくすつぬむぶぐだ]$/.test(pre) ? '' : 'だ';
    });
  }
  function stern(q) { return plain(firm(sober(shrink(inuki(q))))); }
  HK.Voice && (HK.Voice.sternFinish = stern);
  HK.toneFinish('stern', stern);
})();
