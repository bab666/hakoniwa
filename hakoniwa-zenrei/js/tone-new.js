/* 箱庭シミュレーター: アンケートで希望の多かった口調（2026-10-25）
   どれも既存の口調の文面と言い換えを借り、できあがった台詞の語尾だけを最後に付け替える（tone-registry.js の derive・HK.toneFinish）。
   ・無愛想な敬語（〜ですが、何か） … 敬語から。感嘆を削り、言い切りと皮肉の一言で突き放す
   ・偉そうな敬語（〜なさい） … 敬語から。頼みを「〜なさい」、誘いを「〜しますよ」に
   ・無機質な敬語 … 敬語から。感嘆・間投詞・「ね」「よ」を削り、報告のような言い切りに
   ・ふつうのタメ口 … 気質の文面から敬語を外す（tone-plus.js の plain）。語尾の付け替えはしない
   ・ダウナー系チャラ男（〜ですよー） … 敬語から。語尾を伸ばし、「〜けど」で軽く逃げる
   喘ぎ（っ・♡・ぁ などを含む台詞）は崩さない */
(function () {
  'use strict';
  var HK = window.HK, V = HK && HK.Voice;
  if (!V || !HK.toneFinish) return;
  /* 喘ぎ：♡・濁点・小さい母音や「っ」で声が切れる（「あっ……」「んっ、」「ぁ！」）・「……」で終わる。
     「待って」「やっぱり」の「っ」は喘ぎではない（2026-10-26 順81：前は「っ」を含む台詞をすべて素通しにしていた） */
  var MOAN = /[♡゛]|[ぁぃぅぇぉ](?:[っッ…‥、！!？?〜ー」]|$)|[っッ](?:[…‥、！!？?♡〜ー」]|$)|[…‥]っ|……$/;
  var E = '(?=[。！？!?…‥」]|$)';
  function base(q, who, o) { return V.iIre ? V.iIre(q, who, o) : q; }
  /* 文ごとに直す（句点・感嘆・疑問で区切る） */
  function bySent(q, fn) {
    return q.replace(/[^。！？!?]+[。！？!?]*/g, function (s) {
      var m = s.match(/^(.*?)([。！？!?]*)$/);
      return fn(m[1], m[2]) ;
    });
  }
  /* 言いよどみ（……で始まる）・告白の台詞には、皮肉や念押しの一言を足さない */
  function quiet(q) { return /^[…‥]/.test(q) || /好き|愛して|付き合って/.test(q); }
  function lot(q, n) { return HK.lineLot ? HK.lineLot(q, n) : false; }
  /* 2026-10-30 第3回（TA）：無愛想・偉そう・無機質の敬語は、敬語の文面の尊敬語・謙譲語（いらっしゃる・おっしゃる・伺う・存じる・さしあげる・ございます）を
     ふつうの敬語にし、言いよどみ（「あの、その…」「な、何でも」）は外す（感情を見せない・上から言う話し方なので） */
  function deHonor(q) {
    return q.replace(/([てで])いらっしゃい(?=ま)/g, '$1い').replace(/([てで])いらっしゃる/g, '$1いる').replace(/ていらした/g, 'ていた').replace(/でいらっしゃいます/g, 'です')
      .replace(/おっしゃって/g, '言って').replace(/おっしゃらな/g, '言わな').replace(/おっしゃいま/g, '言いま').replace(/おっしゃる/g, '言う')
      .replace(/お伺い/g, 'お聞き').replace(/伺います/g, '聞きます').replace(/伺って/g, '聞いて').replace(/存じています/g, '知っています').replace(/存じません/g, '知りません')
      .replace(/さしあげ/g, 'あげ').replace(/拝見しております/g, '見ています').replace(/([てで])おりま/g, '$1いま').replace(/でございます/g, 'です').replace(/でございました/g, 'でした')
      .replace(/(?<!ありがとう|おはよう|おめでとう)ございません/g, 'ありません').replace(/なさらないで/g, 'しないで').replace(/頂戴|ちょうだい/g, 'ください');
  }
  function unHesit(q) {
    return q.replace(/^(?:あの、)?その[…‥]+/, '').replace(/^あの、(?=[^。！？]*[…‥])/, '').replace(/^[なえあ]、(?=[^、。！？]{2})/, '');
  }
  /* 「〜てください」→「〜なさい」（よく出る動詞だけ。分からなければそのまま） */
  var TE = { 'して': 'し', '来て': '来', '見て': '見', '待って': '待ち', '言って': '言い', '行って': '行き', '座って': '座り', '黙って': '黙り', '帰って': '帰り', '休んで': '休み', '飲んで': '飲み', '読んで': '読み', '呼んで': '呼び', '書いて': '書き', '聞いて': '聞き', '急いで': '急ぎ', '離れて': '離れ', '落ち着いて': '落ち着き', '答えて': '答え', '教えて': '教え', '決めて': '決め', 'やめて': 'やめ', '止めて': 'やめ', '見せて': '見せ', '任せて': '任せ', '寝て': '寝', '出て': '出', '起きて': '起き', '下がって': '下がり', '気をつけて': '気をつけ', '信じて': '信じ', '入って': '入り', '戻って': '戻り', '頑張って': '頑張り', '笑って': '笑い', '泣いて': '泣き', '動いて': '動き', '隠れて': '隠れ', '逃げて': '逃げ', '考えて': '考え', '手伝って': '手伝い', '使って': '使い', '食べて': '食べ', '開けて': '開け', '閉めて': '閉め' };
  var TE_RE = new RegExp('(' + Object.keys(TE).sort(function (a, b) { return b.length - a.length; }).join('|') + ')ください');

  /* ---------- 無愛想な敬語 ---------- */
  function sarc(q, who, o) {
    q = base(q, who, o);
    if (MOAN.test(q)) return q;
    q = unHesit(deHonor(q)).replace(/^ふふ[、。…]*/, '');
    q = q.replace(/^(?:わあ|わぁ|えっと|あの|あのー|うわ|やった|よかった|わーい)[ーぁあ〜]*[、！!]*/, '');
    q = q.replace(/ありがとうございま(?:す|した)/g, 'どうも').replace(/よろしくお願いします/g, 'よろしく')
      .replace(/すみません(?=[、。！!]|$)/g, 'すみませんね');
    q = bySent(q, function (s, p) {
      s = s.replace(/(です|ます|ました|ません)(?:よね|よ|ね)$/, '$1');
      return s + (p ? p.replace(/[！!]+(?=[？?])/g, '').replace(/[！!]+/g, '。') : '');
    });
    /* 言い切りの敬語で終わる台詞には、ときどき皮肉の一言を足す */
    if (!quiet(q) && /(です|ます|ました|ません)。?$/.test(q) && lot(q, 4)) q = q.replace(/。?$/, '。') + (lot(q + 'x', 2) ? '……何か？' : '……で？');
    return q;
  }
  /* ---------- 偉そうな敬語 ---------- */
  function bossy(q, who, o) {
    q = base(q, who, o);
    if (MOAN.test(q)) return q;
    q = unHesit(deHonor(q));
    q = q.replace(TE_RE, function (m, v) { return TE[v] + 'なさい'; });
    q = q.replace(/ないでください/g, 'ないように').replace(/てほしいです/g, 'てもらいます').replace(/でほしいです/g, 'でもらいます').replace(/でしょうか(?=[。？?…」]|$)/g, 'ですか')
      .replace(/(?:よろしい|いい)でしょうか/g, 'よろしいですね').replace(/お願いします(?=[。！!…]|$)/g, '頼みましたよ');
    q = q.replace(/しましょう(?=か?[。！？!?…」]|$)/g, 'しますよ').replace(/ませんか(?=[？?]|$)/g, 'なさい');
    q = q.replace(/すみません(?=[、。！!]|$)/g, '悪かったですね').replace(/ありがとうございま(?:す|した)/g, '礼を言います');
    q = bySent(q, function (s, p) { return s + (p ? p.replace(/[！!]+(?=[？?])/g, '').replace(/[！!]+/g, '。') : ''); });
    if (quiet(q)) return q;
    /* 「答えなさい」は短い問いだけ（世間話の問い・許しを求める問いには付けない）、「当然でしょう」は言い張りの短い言い切りだけ（照れ・感想・「〜んです」には付けない）。2026-10-30 第3回（TA） */
    var core = q.replace(/[…‥、。！？!?　\s]/g, '');
    if (/なさい。?$/.test(q) && lot(q, 3)) q = q.replace(/。?$/, '。') + '……聞こえませんでしたか？';
    else if (/(?:ですか|ますか)[？?]$/.test(q) && core.length <= 12 && !/^あの|いいですか|ませんか|思いますか|でしたっけ|[、。]/.test(q.replace(/[？?]$/, '')) && lot(q, 3)) q += '　答えなさい。';
    else if (/(?:です|ます|ません)。?$/.test(q) && core.length >= 5 && !/^[^。]{1,2}、|[…‥]|嬉し|うれし|楽し|好き|わかり|分かり|んです。?$|のです。?$|ません。?$/.test(q) && lot(q + 'b', 5)) q = q.replace(/。?$/, '。') + '当然でしょう。';
    return q;
  }
  /* ---------- 無機質な敬語 ---------- */
  function flat(q, who, o) {
    q = base(q, who, o);
    /* 歓声は言わない（「やったぁ！」だけなら「成功です」、続きがあれば歓声を外す） */
    if (/^(?:やった(?:やった)?|わーい|わぁい|いえーい)[ーぁあ〜]*[！!。…‥]*$/.test(q)) q = '成功です。';
    q = q.replace(/^(?:やった(?:やった)?|わーい|わぁい|いえーい)[ーぁあ〜]*[、！!…‥\s　]*(?=.)/, '');
    if (MOAN.test(q)) return q;
    q = unHesit(deHonor(q));
    q = q.replace(/^(?:わあ|わぁ|えっと|あの|あのー|うわ|やった|よかった|ふふ|あはは|へえ|うん|ええと|はは|わーい|いえーい)[ーぁあ〜]*[、！!…]*/, '');
    q = q.replace(/ありがとうございま(?:す|した)/g, '感謝します').replace(/すみません(?=[、。！!]|$)/g, '失礼しました');
    q = q.replace(/でしょうか(?=[。？?…」]|$)/g, 'ですか').replace(/([るたいう])かもしれません/g, '$1可能性があります').replace(/分かりません(?=[。！？!?…」]|$)/g, '不明です')
      .replace(/大丈夫です(?=[。！？!?…」、]|$)/g, '問題ありません').replace(/(?:みたい|よう)です(?=[。！!…」]|$)/g, 'と判断します').replace(/と思います(?=[。！!…」]|$)/g, 'と判断します')
      .replace(/てほしいです/g, 'てください').replace(/でほしいです/g, 'でください').replace(/嬉しいです/g, '好ましい結果です');
    q = bySent(q, function (s, p) {
      s = s.replace(/(です|ます|ました|ません|でした)(?:よね|よ|ね|ねえ)$/, '$1').replace(/[〜ー♪]+$/, '');
      return s + (p ? p.replace(/[！!]+(?=[？?])/g, '').replace(/[！!]+/g, '。') : '');
    });
    return q.replace(/[♪]/g, '');
  }
  /* ---------- ダウナー系チャラ男 ---------- */
  /* 敬語の文面・書き下ろし（敬語の口調向け）が持つ謙譲語・尊敬語・改まった語を、ふつうの「です・ます」にくだけさせる（2026-10-26 順80）。
     「おります」「いたします」「ございます」「あなた様」などが残ると、軽薄な口調と混ざって崩れるため。喘ぎの台詞にも当てる（語の置き換えだけ） */
  var TEIDA = { 'き': 'い', 'け': 'え', 'いて': 'って', 'いた': 'った' };
  function kudake(q) {
    return q
      .replace(/([ぁ-ゖ一-鿿]*?)しゅうございま(す|した)/g, function (m, s, t) { return s + (t === 'す' ? 'しいです' : 'しかったです'); })
      .replace(/申し訳(?:ございません|ありません)(?:でした)?/g, 'すいません')
      /* 格式ばった詫びの定型（2026-10-29 利用者の指摘「お見苦しいところを、は硬い」）：軽い敬語の照れに */
      .replace(/(?:お、)?お見苦しいところを、?(?:お見せしました|失礼(?:いたし|し)ました)/g, 'かっこ悪いとこ、見せちゃいましたね').replace(/(?:お、)?お見苦しいところを(?=[。…‥」]|$)/g, 'かっこ悪いとこ、見せちゃいました')
      .replace(/お手数をおかけしました/g, '手間かけさせちゃいました').replace(/お手数をおかけします/g, '手間かけますねー')
      .replace(/恐れ入りますが/g, 'すいませんけど').replace(/恐れ入ります(?=、)/g, 'すいません').replace(/恐れ入ります/g, 'どうもです').replace(/恐縮(?:でございます|です)/g, 'どうもです')
      .replace(/でございま(す|した|しょう)/g, function (m, t) { return t === 'す' ? 'です' : t === 'した' ? 'でした' : 'でしょう'; })
      .replace(/ございましたら/g, 'あったら')
      .replace(/(ありがとう|おはよう|おめでとう|ごちそうさまで|お疲れさまで)?ございま(す|せん|した)/g, function (m, k, t) { return k ? m : 'ありま' + t; })
      .replace(/かしこまりました/g, 'はーい、了解です').replace(/承知(?:いたし|し)ました/g, '了解です')
      .replace(/と存じ(?:ております|ています|ます)/g, 'と思ってます').replace(/存じ(?:ております|ています|上げています|ます)/g, '知ってます').replace(/存じません/g, '知らないです').replace(/と存じて(?:い|お)/g, 'と思って').replace(/存じて(?:い|お)/g, '知って').replace(/おっしゃる/g, '言う').replace(/おっしゃっ/g, '言っ').replace(/おっしゃいま/g, '言いま')
      .replace(/お伺い/g, '伺い').replace(/伺っ/g, '聞い').replace(/伺い/g, '聞き')
      .replace(/と申します/g, 'っていいます').replace(/申し上げ/g, '言い').replace(/お申し付けください/g, '言ってください')
      .replace(/頂戴(?:いたし|し)ま/g, 'もらいま')
      .replace(/([てでを])いただ(き|け|いて|いた)/g, function (m, te, k) { return te + 'もら' + TEIDA[k]; })
      .replace(/(?:いたし|致し)(?=ま|て|た)/g, 'し').replace(/いたしかねます/g, 'できないですねー')
      .replace(/([てで])おりま/g, '$1ま').replace(/おりま/g, 'いま')
      .replace(/参りま(?!した)/g, 'いきま').replace(/くださいませ/g, 'ください')
      .replace(/ご覧になり(?=ま)/g, '見').replace(/ご覧になって/g, '見て').replace(/ご覧ください/g, '見てください').replace(/あなた様/g, 'あなた').replace(/皆(?:さま|様)/g, 'みなさん').replace(/本日/g, '今日').replace(/今宵/g, '今夜').replace(/先ほど/g, 'さっき').replace(/少々/g, 'ちょっと')
      .replace(/(?:大変|たいへん)(?=失礼|申し訳|美味|おいし|結構|お世話|助かり|光栄)/g, 'ほんと').replace(/いかが(?=で)/g, 'どう').replace(/ご無事/g, '無事');
  }
  function downer(q, who, o) {
    q = base(q, who, o);
    q = kudake(q);
    if (MOAN.test(q)) return q;
    q = q.replace(/ありがとうございま(?:す|した)/g, 'あざーす').replace(/すみません(?=[、。！!]|$)/g, 'さーせん').replace(/よろしくお願いします/g, 'よろしくでーす');
    /* 2026-10-30 第3回（TB）：敬語の書き下ろしを借りた台詞の、改まった言い方・尊敬語・「〜ています」を、軽い「です・ます」に（ダウナー系チャラ男だけ） */
    q = q.replace(/([てで])いらっしゃ(?:いま|る)/g, function (m, t) { return t + (/る$/.test(m) ? 'る' : 'ま'); }).replace(/いらっしゃいま/g, 'いま')
      .replace(/何とお呼びすれば/g, 'なんて呼べば').replace(/お呼びすれば/g, '呼べば').replace(/お話しし/g, '話し').replace(/お名前/g, '名前').replace(/ご自分/g, '自分').replace(/お声/g, '声').replace(/お顔/g, '顔').replace(/お体/g, '体').replace(/素敵な/g, 'いい')
      .replace(/お持ちしま/g, '持ちま').replace(/お気になさらず/g, '気にしないで').replace(/なさら(ない|なく)/g, 'し$1').replace(/拝見し/g, '見').replace(/お付き合いのことは置いておいて/g, '付き合うとかは置いといて').replace(/まいりません/g, 'いきません').replace(/よろしいでしょうか/g, 'いいですかー')
      .replace(/([てで])いま(す|した|せん)/g, '$1ま$2').replace(/([てで])い(る|た)(?=[。、…！？!?]|$|ん|の|か|け|は|ら)/g, '$1$2').replace(/ておいて/g, 'といて')
      .replace(/^では(?=[、あ-んア-ン一-鿿])/g, 'じゃ').replace(/([。　…])では、/g, '$1じゃ、').replace(/ではありません/g, 'じゃないです').replace(/のですが/g, 'んですけど').replace(/のでしたっけ/g, 'んでしたっけ').replace(/ですものね/g, 'ですもんね').replace(/(?<![もこ])のです/g, 'んです')
      .replace(/少し/g, 'ちょっと').replace(/本当に/g, 'ほんと').replace(/どちらの/g, 'どっちの').replace(/どうして/g, 'なんで')
      .replace(/どなたか/g, '誰か').replace(/いらっしゃいません/g, 'いません').replace(/お許しをいただけるなら/g, 'いいって言ってくれるなら').replace(/お許しいただけますか/g, 'いいですかー').replace(/なくて結構/g, 'なくていい').replace(/てくださって/g, 'てくれて');
    q = q.replace(/でしょうか(?=[。？?…」]|$)/g, 'ですかねー').replace(/ください(?=[。！!…」]|$)/g, 'くださいよー').replace(/てほしいです/g, 'てほしいなー、なんて').replace(/でほしいです/g, 'でほしいなー、なんて');
    q = bySent(q, function (s, p) {
      var P = p ? p.replace(/[！!]+(?=[？?])/g, '').replace(/[！!]+/g, '。') : '';
      /* 問いかけは「〜ですかー？」にすることがある（「〜けど」「〜よー」は付けない） */
      if (/[？?]/.test(p)) return (/(ですか|ますか)$/.test(s) && lot(s, 2) ? s + 'ー' : s) + p;
      if (/(です|ます)よ$/.test(s)) return s + 'ー' + P;
      if (/(です|ます|ません)$/.test(s) && lot(s, 3)) return s + 'けど' + P;
      if (/(です|ます)$/.test(s) && lot(s + 'y', 2)) return s + 'よー' + P;
      return s + P;
    });
    return q;
  }
  HK.toneFinish('keigo_sarc', sarc);
  HK.toneFinish('keigo_bossy', bossy);
  HK.toneFinish('keigo_flat', flat);
  HK.toneFinish('chara_down', downer);
  V.newToneFinish = { keigo_sarc: sarc, keigo_bossy: bossy, keigo_flat: flat, chara_down: downer };
})();
