    if (P.length < 3) { if (P.length === 2 && !(HK.GoukonMob && HK.GoukonMob.count(ctx))) ctx.say({ text: '二人しかいないので、王様ゲームは「じゃんけんで負けたほうが本音を一つ言う。私からね｜じゃんけんで負けたほうが本音を一つ言う。私からだ｜じゃんけんで負けたほうが本音を一つ言います。私からですね」に変更された。' }); return; }
