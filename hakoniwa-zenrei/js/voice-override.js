  function esc(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }
  function hash(s) { var h = 7; for (var i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 100003; return h; }
  function choose(v, seed) { return Array.isArray(v) ? v[hash(seed) % v.length] : v; }
  /* 台詞の中の住人の名前を〈〉にして、出てきた順の名前の並びと一緒に返す */
  function normalize(q, people) {
    var ns = people.map(function (p) { return p.name; }).filter(Boolean).sort(function (a, b) { return b.length - a.length; });
    if (!ns.length) return { key: q, names: [] };
    var re = new RegExp(ns.map(esc).join('|'), 'g'), names = [];
    var key = q.replace(re, function (m) { names.push(m); return '〈〉'; });
    return { key: key, names: names };
  }
  function fill(t, names) { var i = 0; return t.replace(/〈〉/g, function () { var n = names[Math.min(i, names.length - 1)]; i++; return n || ''; }); }
