/* 箱庭シミュレーター: 奔放から派生する口調（ギャル）
   文面と台詞の言い換えは「奔放」をそのまま使い、できあがった台詞の言い回しと語尾を、最後に付け替える（名前・一人称・見本・派生元は tone-registry.js）。
   ・ギャル … 「よろ〜」「あざまる〜」「マジ」「チョー」「ヤバい」「ウケる」「〜じゃん」「〜だし」「〜っしょ」「〜くない？」「〜的な」「〜だよね〜」「知らんし」
   スラングは台詞に一つ（長い台詞でも二つ）まで、HK.lineLot で間引いて毎回は付けない。
   喘ぎ・叫び・敬語の文、「……」で沈んだ文、重い台詞（死・怖い・痛い・ごめんなさい など）はそのまま（伸ばし棒の「〜」も付けない） */
(function () {
  'use strict';
  var HK = window.HK, V = HK && HK.Voice;
  if (!V || !HK.toneFinish) return;

  /* 喘ぎ・息づかい（「ぁ」「♡」、語尾や区切りの「っ」）。「待って」「だった」の「っ」は数えない */
  /* 驚きの「えっ！？」「あっ、」は喘ぎに数えない */
  var SURPRISE = /^(?:えっ|あっ|おっ|うわっ)(?=[！？!?、])/;
  var MOAN = /[ぁぃぅぇぉ♡]|[っッ](?=[…‥、。！!？?\s」〜～ー]|$)|[ぁ-ん]ー?ん[…‥]/;
  /* どもり（「す、好き」「だ、だめ」） */
  var STUTTER = /(?:^|[、…‥\s])([ぁ-んァ-ン])、\1/;
  /* 重い台詞：伸ばし棒・スラングを付けない */
  var GRAVE = /(?:死|殺|亡|葬|遺体|血|嫌|いや(?:だ|っ)|怖|こわ|痛|やめて|助けて|たすけて|許さ|許して|ごめんなさい|泣|涙|苦し|さよう?なら|別れ|逃げ|後悔|最低|寂し|さみし|悲し|かなし|つら|辛い|謝|吊|処刑|裏切)/;
  /* 敬語の文（「〜いただけるの」「お続けちょうだい」なども） */
  var KEIGO = /(?:です|ます|まし|ません|でした|ください|ござい|でしょう|いたし|申し|いただ|なさい|ちょうだい|お願いする|存じ|本日|お客様)/;
  /* 形容詞の語幹（「熱いね」→「熱くない？」）。「きれい」「嫌い」のような形容動詞は入れない */
  var ADJ = /(?:すご|かわい|可愛|おいし|美味し|うれし|嬉し|楽し|たのし|あったか|あたたか|暖か|温か|熱|暑|寒|さむ|涼し|すずし|うま|旨|面白|おもしろ|優し|やさし|甘|あま|まぶし|眩し|やわらか|柔らか|でか|デカ|多|速|早|強|高|長|話しやす|分かりやす|わかりやす|かっこよ|眠|ねむ|ずる|ズル|うるさ|だる|ダル|きつ|キツ|つめた|冷た|よ)$/;
  /* ぼやきの形容詞（「いちいちうるさい」→「いちいちうるさいし」） */
  var GRUMBLE = /(?:うるさ|ずる|ズル|だる|ダル|ウザ|うざ|きつ|キツ|めんどくさ|面倒くさ|眠|ねむ|寒|さむ|暑|あつ|遅|おそ|狭|せま|ダサ|ださ|しつこ|くさ|臭|まず|まぶし|眩し)い$/;
  var ADJ_ONLY = new RegExp("^" + ADJ.source);
  /* いたわり・慰めの台詞：「〜よね〜」「〜だし」で軽くしない */
  var SOFT = /(?:しんど|大変|疲れ|無理し|ひとりに|一人に|心配|大丈夫|平気|帰る家|ごめん)/;
  /* 決意・脅し・言い切りの「〜ない」には「し」を付けない */
  var VOW = /(?:残れ|生きられ|逃がさ|離さ|忘れ|負け|諦め|止まれ|させ|たまら|しれ|変わら|足りな|許さ|やめ|譲れ)ない$/;

  function lot(s, n) { return HK.lineLot(s, n); }

  /* 語句の置き換え（一つの台詞で一回まで）。成功したら新しい文、なければ null */
  function word(s, q) {
    var r;
    if (/(?:本当に|ほんとに|ほんとうに)(?![、…])/.test(s)) return s.replace(/(?:本当に|ほんとに|ほんとうに)/, 'マジで');
    if (/ほんと(?=[ぁ-ん一-鿿ァ-ヶ])(?![うはにだのっ])/.test(s)) return s.replace(/ほんと(?=[ぁ-ん一-鿿ァ-ヶ])(?![うはにだのっ])/, 'マジ');
    if ((r = s.replace(/(?:すごく|すっごく|とても|めっちゃ|めちゃくちゃ)(?=[ぁ-ん一-鿿ァ-ヶ])/, 'チョー')) !== s) return r;
    if (/本気で(?=[ぁ-ん一-鿿ァ-ヶ])/.test(s)) return s.replace(/本気で(?=[ぁ-ん一-鿿ァ-ヶ])/, 'マジで');
    if (/^とりあえず(?=[、ぁ-ん一-鿿ァ-ヶ])/.test(s)) return s.replace(/^とりあえず、?/, 'とりま');
    if (/(?:^|[、\s])大丈夫(?!か)/.test(s) && !/大丈夫か|[…‥]|ごめん/.test(q)) return s.replace(/大丈夫/g, 'だいじょぶ');
    return null;
  }

  /* 誘いの「〜しよう」「行こう」→「しよ」「行こ」、「やろうよ」→「やろーよ」、「行こうか」→「行こっか」（スラングには数えない）。
     「ありがとう」「おはよう」「向こう」「だろう」「〜そう」のような、誘いでない「〜う」は除く */
  var VOL = /^(.*?(?:[一-鿿]|[ぁ-ん]))([こごろぼもとよお])う(よ|か)?$/;
  function vol(s) {
    var m = s.match(VOL);
    if (!m || /(?:ありがと|おめでと|おはよ|向こ|だろ|でしょ|かろ|ましょ|ほんと|本と|同じよ|そうこ|こ|ど|も)う(?:よ|か)?$/.test(s) && !/(?:[行聞書置歩開動続引弾泣抱巻描届働]こ|[飲休読頼込積盛組揉挑進踏住噛楽し]も)う(?:よ|か)?$/.test(s)) return null;
    var pre = m[1].slice(-1), k = m[2];
    if (k === 'と' && !/[待持勝打立保育]$/.test(pre)) return null;
    if (k === 'よ' && !/[しみねめべえけせてれげでじきぎちにひびいり来見寝出着]$/.test(pre)) return null;
    if (k === 'お' && /[どそこほあ]$/.test(pre)) return null;
    if (k === 'も' && !/[一-鿿し]$/.test(pre)) return null;
    if (k === 'ろ' && /[だかど]$/.test(pre)) return null;
    return m[1] + k + (m[3] === 'よ' ? 'ーよ' : m[3] === 'か' ? 'っか' : '');
  }

  /* 語尾の付け替え。kind: 'q' 問い、'x' 叫び（！）、'' ふつう。戻り値 [文, 次の区切り] か null */
  function ending(s, kind, i, quote, last) {
    var m;
    /* あいさつ・お礼（叫びでも） */
    if (/^(?:じゃあ、|それじゃ、|今日は|今日も|これから|来週も|今後とも)?よろしく(?:ね|な|ー)?$/.test(s)) return s.replace(/よろしく(?:ね|な|ー)?$/, 'よろ〜');
    if ((m = s.match(/^(.*?)(?:ありがとう|ありがと)(?:ね|な|よ)?$/)) && kind !== 'q') {
      if (/^[…‥]/.test(quote)) return null;
      if (!m[1] || /^(?:うん、|ほんと、|ほんとに|本当に|マジで|マジ)$/.test(m[1])) return (m[1] || '') + (lot(quote, 2) ? 'あざまる〜' : 'ありがと〜');
      return m[1] + 'ありがと〜';
    }
    if (/^(?:おやすみ|またね|じゃあね|ばいばい|バイバイ|また明日|おつかれ|お疲れ)$/.test(s)) return s + '〜';
    if (kind === 'q') {
      if (/^(?:本当|ほんと|本気|マジ)(?:に|で)?$/.test(s)) return s.replace(/^(?:本当|ほんと|本気|マジ)(に|で)?$/, function (x, p) { return p ? 'マジで' : 'マジ'; });
      if ((m = s.match(/^(.*?)(?:なん|ん|の)?でしょ$/)) && m[1] && !/(?:、|うそ|嘘|ウソ|^そう)$/.test(m[1])) return m[1] + 'っしょ';
      return null;
    }
    /* 「知らない」→「知らんし」 */
    if (/(?:知らない|知らねえ|知らねー|知らん)(?:よ|って|し)?$/.test(s)) return s.replace(/(?:知らない|知らねえ|知らねー|知らん)(?:よ|って|し)?$/, '知らんし');
    if (/^(?:最高|サイコー)(?:だ|だね|だよ|じゃん)?$/.test(s)) return lot(quote, 2) ? 'アゲ〜' : 'マジ最高';
    if (/(?:かわいい|可愛い)(?:ね|よ|な)?$/.test(s) && lot(quote, 2)) return s.replace(/(かわい|可愛)い(?:ね|よ|な)?$/, '$1すぎ');
    if (/(?:面白い|おもしろい|笑える)(?:ね|よ|な)?$/.test(s) && !/^(?:何|なに|どこ)/.test(s) && lot(quote, 2)) return s.replace(/(?:面白い|おもしろい|笑える)(?:ね|よ|な)?$/, 'ウケる');
    if (/(?:みたいな(?:感じ)?|って感じ)$/.test(s) && s.length > 5 && lot(quote, 2)) return s.replace(/(?:みたいな(?:感じ)?|って感じ)$/, '的な');
    /* 「〜でしょ」→「〜っしょ」（「〜なんでしょ」「〜ないんでしょ」も） */
    if ((m = s.match(/^(.*?)(?:なん|ん|の)?でしょ$/)) && m[1] && !/(?:、|うそ|嘘|ウソ|^そう)$/.test(m[1])) return m[1] + 'っしょ';
    if (/^(?:うん、|あー、|え、)?(?:わかる|分かる)$/.test(s) && lot(quote + 'k', 2)) return s + '〜';
    if (/(?:楽し|たのし|よ|おいし|美味し|うれし|嬉し|面白|おもしろ|すご|ヤバ)かった$/.test(s) && !/[…‥]/.test(quote) && !SOFT.test(quote) && lot(quote + 'k', 2)) return s + '〜';
    if (/わけ(?:が)?ない(?:よ|って)?$/.test(s) && !SOFT.test(quote) && lot(quote + 'w', 2)) return s.replace(/(?:よ|って)$/, '') + 'じゃん';
    /* 言い返しの「〜だよ」→「〜だし」（「同じだよ」「するほどのことだよ」）。「〜んだよ」「そうだよ」「何の〜だよ」は除く */
    if (last && kind === '' && (m = s.match(/^(.*(?:[一-鿿ァ-ヶー々]|[^ん、そま]も|こと|もの|じ))だよ$/)) && !/^(?:何|なに|誰|どこ|なんで|どう)/.test(s) && !/(?:私|俺|僕|自分|ウチ|オレ|ボク)だよ$/.test(s) && !/[…‥]/.test(quote) && !SOFT.test(quote) && lot(quote + 'd', 2)) return m[1] + 'だし';
    /* 気づいた・言い当てた「〜だ！」→「〜じゃん！」（「罠だ！」「同じだ！」）。「答えは〜」「目の前にいるのは〜」のような告げる文は除く */
    if (last && kind === 'x' && /(?:[一-鿿々]|同じ)だ$/.test(s) && !/(?:^|、)[^、]{0,2}だ$/.test(s) && !/(?:答え|正解|目の前|いるのは|のは|サービス|私|俺|僕|自分|あたし|ウチ|オレ|ボク)/.test(s) && !SOFT.test(quote) && lot(quote + 'd', 2)) return s.replace(/だ$/, 'じゃん');
    /* 叫びの「〜だ！」は、ギャルには硬い：短い言い切りは「好き！」「本物じゃん！」、長いものは「完了〜！」 */
    if (kind === 'x' && last && /だ$/.test(s) && !/(?:^|[、…‥])(?:私|俺|僕|自分|あたし|ウチ|オレ|ボク|それ|これ|あれ|何|なん)だ$/.test(s) && !/(?:んだ|のだ|まだ|そうだ|ようだ|まだだ|だだ)$/.test(s) && !SOFT.test(quote)) {
      if (/(?:好き|嫌い|大好き)だ$/.test(s)) return s.replace(/だ$/, '');
      return /^[^、]{1,4}だ$/.test(s) ? s.replace(/だ$/, 'じゃん') : s.replace(/だ$/, '〜');
    }
    if (kind === 'x') return /^(?:すごい|すげえ|すげー)$/.test(s) && lot(quote, 2) ? 'ヤバ' : null;
    /* 「すごいね」→「ヤバくない？」、「熱いね」→「熱くない？」（同意を求める「〜くない？」） */
    if ((m = s.match(/^(.*?)(い|いい)ね$/)) && (ADJ.test(m[1]) || m[2] === 'いい' && /(?:^|[、のがはもてに]|かっこ|気持ち|仲|頭|調子|運)$/.test(m[1])) && !/(?:たい|ない|しくない)ね$/.test(s) && lot(quote, 2)) {
      var stem = m[2] === 'いい' ? m[1] + 'よ' : m[1];
      if (/すご$/.test(stem) && lot(quote, 4)) stem = stem.replace(/すご$/, 'ヤバ');
      return [stem + 'くない', '？'];
    }
    /* 一言の感想（「暑い」「おいしい」）→「マジ暑い」「マジおいしい」 */
    if (/^[^、]{1,4}い$/.test(s) && ADJ_ONLY.test(s.slice(0, -1)) && !/^(?:い|よ)$/.test(s.slice(0, -1)) && lot(quote, 2)) return 'マジ' + s;
    if (/(?:すご|スゴ)(?=かった|くて)/.test(s) && lot(quote, 2)) return s.replace(/(?:すご|スゴ)(?=かった|くて)/, 'ヤバ');
    /* 形容詞・「〜すぎ」＋「だよ」「よ」→「じゃん」（「顔赤いよ」→「顔赤いじゃん」「考えすぎだよ」→「考えすぎじゃん」） */
    if ((m = s.match(/^(.*?)(い|すぎだ)よ$/)) && (m[2] === 'すぎだ' || ADJ.test(m[1]) && !/(?:^|[^っ])よ$/.test(m[1])) && s.length >= 4 && lot(quote, 3)) return m[1] + (m[2] === 'すぎだ' ? 'すぎ' : 'い') + 'じゃん';
    if (/(?:すごい|スゴい)(?:ね|な|よ)?$/.test(s) && lot(quote, 2)) return s.replace(/(?:すごい|スゴい)(?:ね|な|よ)?$/, 'ヤバい');
    /* 「〜だよね」→「〜だよね〜」 */
    if (/(?:だ|[いたる]|じゃん)よね$/.test(s) && !SOFT.test(quote) && lot(quote, 2)) return s + '〜';
    /* 「そうだね」→「それな〜」、「〜だね」→「〜じゃん」 */
    if (/^(?:うん、)?そうだね$/.test(s) && lot(quote, 2)) return s.replace(/そうだね$/, 'それな〜');
    if (/(?:[一-鿿ァ-ヶー々]|[ぁ-ゖ])だ(?:ね|な)$/.test(s) && !/(?:ん|の|そう|^まだ|、まだ)だ[ねな]$/.test(s) && s.length > 3 && !SOFT.test(quote) && lot(quote, 2)) return s.replace(/だ(?:ね|な)$/, 'じゃん');
    if (/[てで]るね$/.test(s) && s.length >= 4 && !SOFT.test(quote) && lot(quote + 't', 2)) return s.replace(/るね$/, 'んじゃん');
    if (last && GRUMBLE.test(s) && s.length >= 3 && lot(quote + 'n', 2)) return s + 'し';
    /* 言い切りの理由・否定に「〜し」（「Ωだから」→「Ωだし」「怒ってない」→「怒ってないし」） */
    if (/(?:[一-鿿ァ-ヶー々]|なん)だから$/.test(s) && !SOFT.test(quote) && lot(quote, 2)) return s.replace(/から$/, 'し');
    if (last && /[わらかさたまばがなけれ]ない(?:よ|って)?$/.test(s) && !VOW.test(s.replace(/(?:よ|って)$/, '')) && !/(?:しかない|じゃない|しょうがない|仕方ない|かまわない|構わない|いけない|ならない|なくない)/.test(s) && s.length >= 4 && s.length <= 14 && !SOFT.test(quote) && lot(quote, 3)) return s.replace(/ない(?:よ|って)?$/, 'ないし');
    return null;
  }

  function gyaru(q, who) {
    if (!q) return q;
    if (who && who.gender !== 'm') q = q.replace(/お前(?!さん)/g, 'あんた');
    if (MOAN.test(q.replace(SURPRISE, '')) || STUTTER.test(q)) return q;
    var grave = GRAVE.test(q);
    /* 驚きの「えっ！？」「ええ！？」→「え〜！？」 */
    if (!grave) q = q.replace(/^(?:えっ|ええ|えー)(?=[！？!?])/, 'え〜').replace(/^ちょっと待って/, 'ちょ、待って').replace(/やばい|やべえ|ヤベえ|やべー/g, 'ヤバい').replace(/ヤバいっ(?=[！!])/g, 'ヤバっ');
    if (grave || KEIGO.test(q)) return q;
    var parts = q.split(/([。！？!?…‥」\n]+)/), slang = 0, swapped = false;
    var out = parts.slice(), lastI = 0;
    parts.forEach(function (seg, j) { if (!(j % 2) && /[^\s、]/.test(seg)) lastI = j; });
    for (var i = 0; i < parts.length; i += 2) {
      var seg = parts[i], next = parts[i + 1] || '', prev = i ? parts[i - 1] : '';
      if (!seg || /[〜～ー]$/.test(seg)) continue;
      /* 「……」で沈んだ文（前後が「…」）はそのまま */
      if (/[…‥]/.test(prev) || /^[…‥]/.test(next) || /^[\s、]*[…‥]/.test(seg)) continue;
      var lead = (seg.match(/^[\s　、]+/) || [''])[0], body = seg.slice(lead.length);
      if (!body || KEIGO.test(body)) continue;
      var kind = /[？?]/.test(next) ? 'q' : /[！!]/.test(next) ? 'x' : '';
      /* 台詞全体で二つまで、一つの文には一つ（長い文なら二つ）まで */
      if (slang >= 2) break;
      var b = body, nx = null, here = 0, cap = body.length >= 12 ? 2 : 1;
      /* マジ・チョー：台詞に一回、二回に一回 */
      if (!swapped && lot(q + i, 2)) { var w = word(b, q); if (w) { b = w; swapped = true; slang++; here++; } }
      /* 誘いの縮め（三回に二回） */
      if (!lot(q + 'v', 3) && !/[…‥]/.test(q)) { var v = vol(b); if (v) b = v; }
      if (here < cap && slang < 2) {
        var e = ending(b, kind, i, q, i >= lastI);
        if (e) {
          if (typeof e !== 'string') { nx = e[1]; e = e[0]; }
          /* 置き換えのあとでも、短い文に二つは重ねない */
          b = e; slang++;
          if (nx) out[i + 1] = /^。/.test(next) ? nx + (i + 2 < parts.length && parts[i + 2] ? '　' : '') + next.slice(1) : nx + next;
        }
      }
      out[i] = lead + b;
    }
    /* 「あざまる〜！じゃあ」→「あざまる〜！　じゃあ」 */
    return out.join('').replace(/(〜[！？!?])(?=[^\s　！？!?」…‥〜])/g, '$1　');
  }
  V.gyaruQuote = gyaru;
  HK.toneFinish('gyaru', gyaru);
})();
